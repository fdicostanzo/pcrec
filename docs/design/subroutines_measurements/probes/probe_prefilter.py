"""[DD-14] PROBE 1 -- what a DFA prefilter is worth on call-SHAPED patterns.

pcrec cannot compile a subroutine call today (module `recursion` has no
producer -- every call spelling REFUSES, see probe_spellings.py's A6/backrefs
spellings.rxt). So this probe cannot time a call directly. What it CAN do is
time the call's INLINED EQUIVALENT: textually substitute the callee's body
for each call site, drop the `(?(DEFINE)...)` wrapper where present, and
compile THAT with pcrec -- a pattern pcrec accepts today, with the same
literal/class/alternation shape a called body would have.

The INLINING TABLE is hand-written (§ ROWS below), not generated by a general
inliner: a reader needs to be able to see, in one glance, that the two sides
of a row say the same thing. A general inliner is exactly the mechanism
DD-14 is trying to decide whether pcrec should HAVE -- building one here to
answer the question would be circular.

METHOD, four stages:

  1. EQUIVALENCE. For every row, compare `sr.search(call_pat, subj)` against
     `sr.search(inl_pat, subj)` on >=25 subjects (matching / non-matching /
     near-miss / empty / long), BOTH answered by libpcre2 -- the call side
     because PCRE2 accepts calls and pcrec does not, the inlined side as the
     control. This is an apples-to-apples check of the hand-substitution
     against ONE oracle, not a cross-engine diff. A row where any subject
     disagrees is DISQUALIFIED from the timing table (reported, not fixed).

  2. THE GROUPLESS DISCOVERY (read before trusting a ratio near 1.00).
     Measured here, not assumed: an INLINED pattern that drops the DEFINE
     wrapper AND has no capturing group left over compiles to pcrec's PURE
     DFA ARTIFACT -- no `RX_ENGINE`/`RX_VM_PREFILTER` macros at all, and
     `-fno-prefilter` on such a pattern is a byte-identical no-op (verified
     below by diffing the two arms' emitted .c, not assumed from the flag's
     name). The DFA-idiom rows below (define bodies with no other group)
     fall in this bucket and are reported SEPARATELY, as a reference
     baseline, not in the ratio table -- their ratio would read close to
     1.00 for a reason that has nothing to do with whether a prefilter
     helps: there IS no prefilter/VM distinction to measure on them. Only a
     row whose inlined pattern keeps a capturing group (the numeric-reuse
     and \\g<name>-reuse idioms always do, because the call site sits next
     to the group that defines it) reaches `RX_ENGINE "vm"` /
     `RX_VM_PREFILTER "hybrid"` and is a live measurement of the question
     DD-14 is asking.

  3. TIMING. For each VERIFIED, VM-reaching row: compile the inlined pattern
     twice (default vs `-fno-prefilter`), build each against a small custom
     driver (bigdriver.c, written to $SR_PF_TMP at runtime -- NOT the
     `--emit-main` artifact; see the ARGV FINDING below), and run best-of-3
     over a >=1MB subject built so the pattern's candidate starts are sparse
     (a 'Z'-filled run: none of these patterns' leading literal/class/
     alternation alphabets contain 'Z', so the filler contributes zero
     candidate starts and the only real work is at the tail). Two subject
     variants per row: one with a genuine match near the end, one with no
     match anywhere -- the prefilter's "rule this whole region out fast"
     case.

  4. REACHABILITY GUARDS -- printed, and the run is marked VACUOUS if any
     fails: (a) at least one default-arm artifact must stamp
     `RX_VM_PREFILTER "hybrid"` (or the whole table measured no prefilter at
     all); (b) the default and `-fno-prefilter` arms must agree on the match
     answer for every timed subject; (c) the same binary's own three-run
     spread is reported alongside every ratio, so a small ratio can be seen
     against the noise floor that produced it.

THE ARGV FINDING (an instrument defect caught before it produced a wrong
number). The brief's literal invocation is `--emit-main ... ; run the
binary over a >=1MB subject`. `--emit-main`'s generated `main()` takes the
subject from `argv[1]` -- and Linux caps a SINGLE argv element at
`MAX_ARG_STRLEN`, 128KiB, regardless of the total argv/environment budget.
A >=1MB subject therefore cannot be passed to a `--emit-main` binary at
all; the shell fails it with "Argument list too long" before pcrec's own
code ever runs. Had this gone unnoticed, the probe would have silently
fallen back to some smaller subject (or errored out and reported nothing),
either of which would have hidden the story WITHOUT saying so. The fix:
this probe generates the SAME artifact `--emit-main` would generate, minus
`--emit-main` itself (the two are otherwise the same `-o OUT.c` compile,
same flags), and links it against a driver adapted from
`eng_brep_measurements/probes/tdriver.c`'s technique -- except reading the
subject from a FILE (no argv limit) rather than argv, since tdriver.c's own
subjects are always small (an awk-generated `((a)|b){0,N}c` driver string,
never megabyte-scale).
"""
