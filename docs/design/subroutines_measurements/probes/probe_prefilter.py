def _strip_header_include(text):
    """The two arms differ only in the #include "<id>_{def,np}.h" line
    (the header BASENAME, generated per -o); everything else in a
    byte-identical artifact matches. Normalise that one line away so the
    diff is honest about what actually differs."""
    return re.sub(r'#include "[^"]+\.h"', '#include "HDR"', text)


