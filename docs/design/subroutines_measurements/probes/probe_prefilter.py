def battery(matches, nomatches):
    """>=25 subjects covering matching / non-matching / near-miss / empty /
    long, built generically from a row's canonical matches/nomatches so the
    table above stays a table, not 15 hand-typed 25-line subject lists."""
    subs = ["", "Z" * 5000, "Z" * 20000 + matches[0]]
    for m in matches:
        subs += [m, "Z" + m, m + "Z", "ZZ" + m + "ZZ", m + m]
    for nm in nomatches:
        subs += [nm, "Z" + nm + "Z", nm + nm]
    subs.append("ZZZ")
    return subs


def check_equivalence(row):
    """Compare libpcre2's answer for call_pat against libpcre2's answer for
    inl_pat over battery(). Returns (cells, disagreements)."""
    subs = battery(row["matches"], row["nomatches"])
    disagreements = []
    for subj in subs:
        rc = sr.search(row["call"], subj)
        ri = sr.search(row["inl"], subj)
        if rc == "ERR" or ri == "ERR":
            disagreements.append((subj, rc, ri, "compile-error"))
            continue
        if (rc is None) != (ri is None):
            disagreements.append((subj, rc, ri, "match/nomatch split"))
            continue
        if rc is None:
            continue
        span_c, groups_c = rc
        span_i, groups_i = ri
        if span_c != span_i:
            disagreements.append((subj, rc, ri, "span differs"))
            continue
        if row["compare_groups"] and groups_c != groups_i:
            disagreements.append((subj, rc, ri, "groups differ"))
            continue
    return len(subs), disagreements


