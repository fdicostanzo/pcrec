_BIGDRIVER_C = r"""
/* bigdriver.c -- [DD-14] PROBE 1 timing driver, written at runtime by
 * probe_prefilter.py (not committed). See the ARGV FINDING in that file's
 * docstring: reads the subject from a FILE (argv[1] is a PATH) rather than
 * from argv itself, because a single argv element is capped by the kernel's
 * MAX_ARG_STRLEN (128KiB) and this probe's subjects are >=1MB. Prints
 *   <rc-word>\t<ns>\t<span0>\t<span1>
 * rc-word is match/nomatch/giveup; ns is CLOCK_MONOTONIC elapsed around the
 * ONE rx_search call (the file read is outside the timed region). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <stddef.h>

int rx_search(const unsigned char *s, size_t n, size_t startpos,
              ptrdiff_t (*caps)[2]);

int main(int argc, char **argv)
{
    if (argc < 2) { fprintf(stderr, "usage: bigdriver SUBJECT_FILE\n"); return 2; }
    FILE *f = fopen(argv[1], "rb");
    if (!f) { perror("fopen"); return 2; }
    if (fseek(f, 0, SEEK_END) != 0) { perror("fseek"); return 2; }
    long sz = ftell(f);
    if (sz < 0) { perror("ftell"); return 2; }
    rewind(f);
    unsigned char *buf = malloc((size_t)sz + 1);
    if (!buf) { fprintf(stderr, "malloc failed\n"); return 2; }
    size_t got = fread(buf, 1, (size_t)sz, f);
    fclose(f);
    if (got != (size_t)sz) { fprintf(stderr, "short read\n"); return 2; }

    ptrdiff_t caps[64][2];
    memset(caps, 0, sizeof caps);

    struct timespec a, b;
    clock_gettime(CLOCK_MONOTONIC, &a);
    int rc = rx_search(buf, (size_t)sz, 0, caps);
    clock_gettime(CLOCK_MONOTONIC, &b);
    double ns = (double)(b.tv_sec - a.tv_sec) * 1e9
              + (double)(b.tv_nsec - a.tv_nsec);

    if (rc == 1)
        printf("match\t%.1f\t%lld\t%lld\n", ns,
               (long long)caps[0][0], (long long)caps[0][1]);
    else if (rc == 0)
        printf("nomatch\t%.1f\n", ns);
    else
        printf("giveup\t%.1f\t%d\n", ns, rc);
    free(buf);
    return 0;
}
"""

_BIGDRIVER_PATH = os.path.join(TMP, "bigdriver.c")
with open(_BIGDRIVER_PATH, "w") as _f:
    _f.write(_BIGDRIVER_C)


def pcrec_compile(pattern, out_c, extra_flags=()):
    cmd = [PCREC_BIN, "-p", "rx", "--features", "all", *extra_flags,
           "-o", out_c, "--", pattern]
    return run(cmd, timeout=60)


def gcc_build(c_file, out_bin):
    cmd = ["gcc", "-O2", "-w", "-std=gnu11", "-o", out_bin,
           _BIGDRIVER_PATH, c_file]
    return run(cmd, timeout=60)


def stamps(c_text):
    d = {}
    for key in ("RX_ENGINE", "RX_ENGINE_WHY", "RX_VM_PREFILTER",
                "RX_VM_PRUNE_CEILING"):
        m = re.search(r'#define %s "([^"]*)"' % re.escape(key), c_text)
        d[key] = m.group(1) if m else None
    return d


BIG_FILLER = 1_000_000  # 'Z' bytes -- outside every row's leading alphabet


def write_subject(path, with_match, tail):
    subj = ("Z" * BIG_FILLER) + (tail if with_match else "")
    with open(path, "wb") as f:
        f.write(subj.encode("latin-1"))
    return len(subj)


def time_binary(bin_path, subj_path, reps=3):
    """Returns (list of (word, ns) over `reps` runs) or None on any failure."""
    out = []
    for _ in range(reps):
        r = run([bin_path, subj_path], timeout=60)
        if r.returncode != 0:
            return None
        parts = r.stdout.strip().split("\t")
        if len(parts) < 2:
            return None
        out.append((parts[0], float(parts[1])))
    return out


