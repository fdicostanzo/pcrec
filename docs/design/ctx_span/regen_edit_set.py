#!/usr/bin/env python3
"""docs/design/ctx_span/regen_edit_set.py -- re-check R4 (ctx_span.md §4.5.4): the
edit set REGENERATED FROM THE REAL DIFF of each build commit, and compared with the
design's own hand list `edit_set.tsv`.

For each named commit C, `git diff -U0 C^ C -- src/` gives the lines C removed or
replaced. Every removed CODE line (not blank, not a comment-only line) becomes a
`line` entry of the regenerated set, tagged with C's step label; that set is what
`../start_table/sabotage_anchors.py` and `derive_rows.py` read. Then the two sets are
compared both ways:

  design-not-real  a design `line`/`token` for P2a-P2c that no removed line of the
                   real diff contains, or a design `def` no removed line sits in (read
                   off the base tree's call graph) -- the design planned an edit the
                   build did not make;
  real-not-design  a removed code line that no design entry covers (equal to a design
                   `line`, containing a design `token`, or inside a design `def`) -- the
                   build made an edit the design did not plan.

Usage: python3 -I regen_edit_set.py REPO BASE_TREE CALL_GRAPH DESIGN_SET OUT_SET \\
           LABEL=COMMIT [LABEL=COMMIT ...]"""
import collections, os, subprocess, sys

repo, base, cgp, dsp, outp = sys.argv[1:6]
steps = [a.split("=", 1) for a in sys.argv[6:]]

defs = collections.defaultdict(list)
for l in open(cgp):
    p = l.rstrip("\n").split("\t")
    if p[0].startswith("def-"):
        f, rng = p[2].rsplit(":", 1)
        a, b = map(int, rng.split("-"))
        defs[f].append((a, b, p[1]))

def owner(f, ln):
    best = None
    for a, b, n in defs.get(f, []):
        if a <= ln <= b and (best is None or b - a < best[1] - best[0]):
            best = (a, b, n)
    return best[2] if best else None

def is_code(t):
    s = t.strip()
    return bool(s) and not s.startswith(("/*", "*", "//", "*/"))

removed = []          # (label, file, old_lineno, text, owner)
for label, c in steps:
    out = subprocess.run(["git", "-C", repo, "diff", "-U0", c + "^", c, "--",
                          "src/*.c", "src/*.h", "src/*.def"],
                         capture_output=True, text=True, check=True).stdout
    f = None; ln = 0
    for l in out.splitlines():
        if l.startswith("--- "):
            f = l[6:] if l.startswith("--- a/") else None
        elif l.startswith("@@"):
            ln = int(l.split()[1][1:].split(",")[0])
        elif l.startswith("-") and not l.startswith("---") and f:
            t = l[1:]
            # the old line number is only meaningful against the commit's parent;
            # owner() reads the BASE tree's call graph, exact for the first commit
            # touching a file and a close approximation after it (lines shift)
            removed.append((label, f, ln, t, owner(f, ln)))
            ln += 1

design = []
for l in open(dsp):
    if l.startswith("#") or not l.strip():
        continue
    k, v, c, why = l.rstrip("\n").split("\t")
    if c in ("P2a", "P2b", "P2c"):
        design.append((k, v, c))

def covers(entry, r):
    k, v, _ = entry
    _, f, _, t, own = r
    if k == "line":
        return t.strip() == v.strip()
    if k == "token":
        return v in t
    if k == "def":
        return own == v
    return False

with open(outp, "w") as o:
    o.write("# regenerated by regen_edit_set.py from the real diff of the build commits\n")
    o.write("# kind\tvalue\tcommit\twhy\n")
    seen = set()
    ndrop = 0
    for label, f, ln, t, own in removed:
        if not is_code(t) or (t, label) in seen:
            continue
        # A `line` entry matches as a substring in EVERY file (the anchor map's
        # rule), so only a line that is DISTINCTIVE may enter: unique in its own
        # base file. `}`, `break;` and `return r;` would select half the matrix.
        try:
            base_text = open(os.path.join(base, f), errors="replace").read()
        except OSError:
            base_text = ""
        if base_text.count(t.strip()) != 1:
            ndrop += 1
            continue
        seen.add((t, label))
        o.write("line\t%s\t%s\tremoved or replaced by %s (%s:%d, owner %s)\n"
                % (t, label, label, f, ln, own or "?"))

code = [r for r in removed if is_code(r[3])]
print("(%d removed code lines not distinctive in their base file: left out of the set)" % ndrop)
print("== design-not-real (planned, not made) ==")
n1 = 0
for e in design:
    if not any(covers(e, r) for r in removed):
        n1 += 1
        print("  %s\t%s\t%s" % e)
print("  (%d of %d design entries)" % (n1, len(design)))
print("== real-not-design (made, not planned) ==")
n2 = 0
for r in code:
    if not any(covers(e, r) for e in design):
        n2 += 1
        print("  %s\t%s:%d\t%s\t[%s]" % (r[0], r[1], r[2], r[3].strip()[:90], r[4] or "?"))
print("  (%d of %d removed code lines)" % (n2, len(code)))
