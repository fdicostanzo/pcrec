#!/usr/bin/env python3
"""upa.py -- lane r17upa: USES PER ACTIVATION of every set-FIND site on the
bench's own subjects (memfn R-17, setfind.md rev 2.3 §9.2 (P), §12.4a's filed
counter `mfk-upa`; the bench request's Q3).

A COUNTS-ONLY instrument (no timing). For each bench pattern:

 1. compile it as the bench's pcrec testee compiles it (testees/pcrec/
    adapter.py at the bench pin: `pcrec -p rx -fcomments <config flags> -o
    artifact.c --pattern <raw bytes>`; configs.toml: pcrec-auto = `--features
    all`, pcrec-nocaps adds `--no-captures`, the utf8 set adds `-e utf8`);
 2. find every set-FIND site in the emitted C -- the 256-entry table walk
    `while (P < N && !T[S[P]]) P++;` (census.py's WALK_RE, same file family);
 3. write an INSTRUMENTED COPY: `upa_act(F);` at the entry of the function
    holding the site (one activation = one call of that function = the
    lifetime of the storage a stateful form would declare there, setfind.md
    §7.5), and each walk statement wrapped as `{ <walk> upa_use(F, hit); }`
    (one use = one "next candidate at or after lo");
 4. build the plain and the instrumented artifact into upa_driver.c, which
    drives each exactly as the bench's timed loop does (search-short = one
    rx_search(s, n, 0) per short subject; find-all = the match_api.md §3.1
    loop per throughput subject, utf8 advance on the utf8 set);
 5. CONTROLS: the two builds' answers must be identical on every subject
    (answer identity), and the counters must be self-consistent against facts
    computed here from the subject and the parsed table, sharing no code with
    the counter: within one activation the hit positions strictly rise (MONO,
    in the driver), so a level's hits <= |positions whose byte is in S| x its
    activations; hits <= uses; calls <= activations of a site in
    `<prefix>_search`/`_run` <= 2 x calls (the deep tier re-runs `_run` after
    a FRAMES give-up). Oracle: answers against the bench's own libpcre2
    expectations; a pcrec give-up shows there as a difference in BOTH builds. A zero-use activation (the function entered,
    the site not reached, e.g. behind a pre-check) is DATA (mfk-upa's bucket
    0), reported as share_zero.

Subjects are regenerated by the bench's OWN generators into a scratch copy
(--bench-src, made by `git archive` of the bench clone, manifests checked
byte-identical by the caller); patterns and the regime -> subject mapping come
from the bench's own loader (pcrecbench.subbench), its `.rxt` source read
through THIS tree's pcrec (`--list-source`; the loader's pin resolution is
monkeypatched, nothing else).

    upa.py --pcrec build/pcrec --bench-src SCRATCH/benchsrc --out OUTDIR
           [--sets utf8,syntax,...] [--configs auto,nocaps] [--cells FILE]
           [--jobs 4]

Writes OUTDIR/counts.tsv (one row per cell x config x regime x subject x
level), OUTDIR/sites.tsv (one row per site), OUTDIR/controls.tsv, and
OUTDIR/work/ (artifacts, binaries; scratch).
"""
import argparse
import concurrent.futures
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WALK_RE = re.compile(r"while \((\w+)( \+ 1)? < (\w+) && !(\w+)\[(\w+)\[\1\]\]\) \1\+\+;")
TABLE_RE = re.compile(r"static const unsigned char (\w+)\[256\] = \{([^}]*)\};", re.S)
CALL_RE = re.compile(r"\b(\w+)\s*\(")
CONFIGS = {"auto": [], "nocaps": ["--no-captures"]}
GENCC = ["gcc", "-O2", "-w", "-std=gnu11"]


def role_of(tname):
    if tname.endswith("can_begin_match"):
        return "dfa-pf"
    if tname.endswith("start_bytes"):
        return "dfa-hat"
    if tname.endswith("start_set"):
        return "vm-hat"
    return "other:" + tname


def enclosing_function(lines, idx):
    """-> (name, index of its opening `{` line) for the walk at lines[idx]."""
    j = idx
    while j >= 0 and lines[j] != "{":
        j -= 1
    if j < 0:
        raise RuntimeError("no enclosing function for line %d" % (idx + 1))
    k = j - 1
    while k >= 0:
        ln = lines[k]
        if ln[:1].isalpha() or ln[:1] == "_":
            names = [n for n in CALL_RE.findall(ln) if n != "__attribute__"]
            if names:                      # the first call-shaped name is the function
                return names[0], j
        k -= 1
    raise RuntimeError("no signature above line %d" % (j + 1))


PLANT = False                          # --plant: the instrumented copy skips each candidate


def instrument(text):
    """-> (instrumented text, sites list). Each site: dict(fn, fid, role,
    table, members, bounded, line)."""
    tables = {}
    for m in TABLE_RE.finditer(text):
        vals = [int(v) for v in m.group(2).replace("\n", " ").split(",") if v.strip()]
        if len(vals) == 256:
            tables[m.group(1)] = [i for i, v in enumerate(vals) if v]
    lines = text.split("\n")
    sites, fids, entry_lines = [], {}, {}
    for i, ln in enumerate(lines):
        ms = list(WALK_RE.finditer(ln))
        if not ms:
            continue
        if len(ms) > 1:
            raise RuntimeError("two walks on one line %d" % (i + 1))
        m = ms[0]
        fn, brace = enclosing_function(lines, i)
        fid = fids.setdefault(fn, len(fids))
        entry_lines[brace] = fid
        pos, bnd, lim, tname = m.group(1), m.group(2), m.group(3), m.group(4)
        hit = "%s%s < %s" % (pos, bnd or "", lim)
        plant = (" if (%s) %s++;" % (hit, pos)) if PLANT else ""
        lines[i] = (ln[:m.start()] + "{ " + m.group(0) + " upa_use(%d, %s, (size_t)(%s));%s }"
                    % (fid, hit, pos, plant)
                    + ln[m.end():])
        sites.append(dict(fn=fn, fid=fid, role=role_of(tname), table=tname,
                          members=tables.get(tname), bounded=int(bool(bnd)), line=i + 1))
    if len(fids) > 8:
        raise RuntimeError("more than 8 holding functions")
    for brace in sorted(entry_lines, reverse=True):
        lines.insert(brace + 1, "    upa_act(%d);" % entry_lines[brace])
    return "\n".join(lines), sites


def run(argv, timeout, **kw):
    return subprocess.run(argv, capture_output=True, timeout=timeout, **kw)


def stats(hist):
    """hist: list of (uses, count) -> dict of the distribution."""
    tot = sum(c for _, c in hist)
    if tot == 0:
        return None
    hist = sorted(hist)

    def q(p):                          # nearest-rank quantile: ceil(p * tot)
        rank = min(tot, max(1, -(-p * tot // 1)))
        acc = 0
        for u, c in hist:
            acc += c
            if acc >= rank:
                return u
        return hist[-1][0]
    uses = sum(u * c for u, c in hist)
    ge = lambda k: sum(c for u, c in hist if u >= k) / tot
    return dict(nact=tot, uses=uses, mean=uses / tot, p10=q(0.10), med=q(0.50),
                p90=q(0.90), max=hist[-1][0], ge2=ge(2), ge4=ge(4), ge16=ge(16),
                zero=sum(c for u, c in hist if u == 0) / tot)


def parse_hist(s):
    if s == "-":
        return []
    return [tuple(int(x) for x in p.split(":")) for p in s.split(",")]


def one_cell(job):
    (setid, name, pat, cfg, utf8, short, thr, work, pcrec, timeout, expect) = job
    cid = "%s__%s__%s" % (setid, name, cfg)
    d = os.path.join(work, cid)
    os.makedirs(d, exist_ok=True)
    art = os.path.join(d, "art.c")
    argv = ([pcrec, "-p", "rx", "-fcomments", "--features", "all"] + CONFIGS[cfg]
            + (["-e", "utf8"] if utf8 else []) + ["-o", art, "--pattern", pat])
    r = run(argv, timeout)
    if r.returncode != 0:
        return dict(cid=cid, status="refused", err=r.stderr.decode("latin-1")[:200].replace("\n", " "))
    text = open(art, encoding="latin-1").read()
    eng = re.search(r'#define RX_ENGINE "(\w+)"', text)
    pf = re.search(r'#define RX_VM_PREFILTER "([\w-]+)"', text)
    itext, sites = instrument(text)
    info = dict(cid=cid, engine=eng.group(1) if eng else "?", vmpf=pf.group(1) if pf else "-", sites=sites)
    if not sites:
        info["status"] = "nosite"
        return info
    with open(os.path.join(d, "art_upa.c"), "w", encoding="latin-1") as f:
        f.write(itext)
    drv = os.path.join(HERE, "upa_driver.c")
    for tag, src in (("plain", "art.c"), ("upa", "art_upa.c")):
        r = run(GENCC + ['-DUPA_ARTIFACT="%s"' % os.path.join(d, src), "-o", os.path.join(d, tag), drv], timeout)
        if r.returncode != 0:
            info["status"] = "build-fail:" + tag
            info["err"] = r.stderr.decode("latin-1")[:300].replace("\n", " ")
            return info
    args = (["--utf8"] if utf8 else [])
    for p in short:
        args += ["S", p]
    for p in thr:
        args += ["T", p]
    outs = {}
    for tag in ("plain", "upa"):
        r = run([os.path.join(d, tag)] + args, timeout * 4)
        if r.returncode != 0:
            info["status"] = "run-fail:%s rc=%d" % (tag, r.returncode)
            return info
        outs[tag] = r.stdout.decode("latin-1").splitlines()
    ans = lambda ls: [l for l in ls if l.startswith("ANS\t")]
    info["answers_identical"] = ans(outs["plain"]) == ans(outs["upa"])
    info["n_answers"] = len(ans(outs["upa"]))
    info["answers"] = {tuple(l.split("\t")[1:3]): l.split("\t")[3] for l in ans(outs["upa"])}
    info["lvl"] = [l.split("\t")[1:] for l in outs["upa"] if l.startswith("LVL\t")]
    info["mono"] = sum(int(l.split("\t")[3]) for l in outs["upa"] if l.startswith("MONO\t"))
    # the bench's own libpcre2-derived expectation (independent of pcrec)
    odiff, ochk = [], 0
    for (path, rg), a in info["answers"].items():
        e = expect.get((os.path.basename(path)[:-4], "search_short" if rg == "short" else "throughput"))
        if e is None:
            continue
        ochk += 1
        f = dict(kv.split("=") for kv in a.split(" "))
        if rg == "short":
            got = f["first"] if int(f["matches"]) else "-1,-1"
            want = "%d,%d" % (e[1], e[2]) if e[0] else "-1,-1"
        else:
            got, want = f["matches"], str(e[3] if e[0] else 0)
        if got != want:
            odiff.append("%s %s got %s want %s" % (os.path.basename(path), rg, got, want))
    info["oracle_checked"], info["oracle_diff"] = ochk, odiff
    info["status"] = "ok"
    return info


def scount(path, members):
    if members is None:
        return None
    m = set(members)
    b = open(path, "rb").read()
    return sum(1 for x in b if x in m), len(b)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pcrec", required=True)
    ap.add_argument("--bench-src", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--sets", default="utf8,syntax,capability,email,loglines,bounded,altwide,litrun")
    ap.add_argument("--configs", default="auto,nocaps")
    ap.add_argument("--cells", help="file of set/name lines to restrict to")
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--timeout", type=int, default=300)
    ap.add_argument("--plant", action="store_true",
                    help="planted control: the copy skips every candidate; the identity "
                         "and oracle checks must then fire")
    a = ap.parse_args()
    global PLANT
    PLANT = a.plant
    pcrec = os.path.abspath(a.pcrec)
    src = os.path.abspath(a.bench_src)
    sys.path.insert(0, src)
    from pcrecbench import subbench, rxt_source
    rxt_source.resolve_pcrec_bin = lambda: pcrec
    want = None
    if a.cells:
        want = set(l.split()[0] for l in open(a.cells) if l.strip() and not l.startswith("#"))
    work = os.path.join(os.path.abspath(a.out), "work")
    os.makedirs(work, exist_ok=True)
    jobs = []
    for st in a.sets.split(","):
        sb = subbench.load(os.path.join(src, "bench", st))
        utf8 = getattr(sb, "encoding", None) == "utf8"
        short = [s.path for s in sb.subjects_for("search_short")] if "search_short" in sb.regimes else []
        thr = [s.path for s in sb.subjects_for("throughput")] if "throughput" in sb.regimes else []
        for p in sb.patterns:
            if want is not None and "%s/%s" % (st, p.name) not in want:
                continue
            expect = {}
            for (pn, sid, rg), e in sb.expectations.items():
                if pn == p.name and e.convention is None:
                    expect[(sid, rg)] = (e.matched, e.start, e.end, e.nmatches)
            for cfg in a.configs.split(","):
                jobs.append((st, p.name, sb.pattern_bytes(p.name).rstrip(b"\n"), cfg, utf8,
                             short, thr, work, pcrec, a.timeout, expect))
    out = os.path.abspath(a.out)
    fc = open(os.path.join(out, "counts.tsv"), "w")
    fs = open(os.path.join(out, "sites.tsv"), "w")
    fk = open(os.path.join(out, "controls.tsv"), "w")
    fc.write("cell\tconfig\tengine\tvm_prefilter\tregime\tsubject\tlevel\tbytes\tS_count\tdensity_ppm\t"
             "matches\tnact\tuses\thits\tmean\tp10\tmedian\tp90\tmax\tshare_ge2\tshare_ge4\tshare_ge16\t"
             "share_zero\thits_per_match\thist\n")
    fs.write("cell\tconfig\tengine\tvm_prefilter\tstatus\tfn\trole\tbounded\t|S|\tmembers\n")
    fk.write("cell\tconfig\tstatus\tanswers_identical\tn_answers\toracle_checked\toracle_diff\tchecks\tviolations\n")
    nviol = noracle = 0
    with concurrent.futures.ThreadPoolExecutor(a.jobs) as ex:
        for info in ex.map(one_cell, jobs):
            setid, name, cfg = info["cid"].split("__")
            cell = setid + "/" + name
            eng, vmpf = info.get("engine", "-"), info.get("vmpf", "-")
            for s in info.get("sites", []) or [{}]:
                if not s:
                    fs.write("%s\t%s\t%s\t%s\t%s\t-\t-\t-\t-\t-\n" % (cell, cfg, eng, vmpf, info["status"]))
                    continue
                mem = s["members"] or []
                fs.write("%s\t%s\t%s\t%s\t%s\t%s\t%s\t%d\t%d\t%s\n" % (
                    cell, cfg, eng, vmpf, info["status"], s["fn"], s["role"], s["bounded"], len(mem),
                    ",".join("%02X" % x for x in mem)))
            if info["status"] != "ok":
                fk.write("%s\t%s\t%s\t-\t-\t-\t-\t-\t-\n" % (cell, cfg, info["status"] + (" " + info.get("err", ""))))
                continue
            fnames = {}
            members = None
            for s in info["sites"]:
                fnames[s["fid"]] = s["fn"]
                members = sorted(set(members or []) | set(s["members"] or []))
            viol, checks = [], 0
            calls = {}
            for row in info["lvl"]:
                path, rg, lvl, nact, uses, hits, matches, hist = row
                nact, uses, hits, matches = int(nact), int(uses), int(hits), int(matches)
                h = parse_hist(hist)
                st_ = stats(h)
                sc = scount(path, members)
                if lvl == "call":
                    calls[(path, rg)] = nact
                # controls (independent of the counter's own code)
                checks += 2
                # each activation's hits are distinct rising positions (MONO), so
                # a level's hits are bounded by |S positions| x its activations
                if sc is not None and lvl.startswith("fn:") and hits > sc[0] * nact:
                    viol.append("hits>S*act %s %s %s" % (os.path.basename(path), rg, lvl))
                if hits > uses:
                    viol.append("hits>uses %s %s %s" % (os.path.basename(path), rg, lvl))
                lvname = ("fn:" + fnames[int(lvl[3:])]) if lvl.startswith("fn:") else lvl
                sid = os.path.basename(path)[:-4]
                dens = (1e6 * sc[0] / sc[1]) if sc and sc[1] else 0.0
                if st_ is None:
                    st_ = dict(mean=0, p10=0, med=0, p90=0, max=0, ge2=0, ge4=0, ge16=0, zero=0)
                fc.write("%s\t%s\t%s\t%s\t%s\t%s\t%s\t%d\t%s\t%.0f\t%d\t%d\t%d\t%d\t%.3f\t%d\t%d\t%d\t%d\t"
                         "%.4f\t%.4f\t%.4f\t%.4f\t%s\t%s\n" % (
                             cell, cfg, eng, vmpf, rg, sid, lvname, sc[1] if sc else 0,
                             sc[0] if sc else "-", dens, matches, nact, uses, hits, st_["mean"], st_["p10"],
                             st_["med"], st_["p90"], st_["max"], st_["ge2"], st_["ge4"], st_["ge16"],
                             st_["zero"], ("%.3f" % (hits / matches)) if matches else "-", hist))
            # activations of a site in the search entry's own body == calls
            for row in info["lvl"]:
                path, rg, lvl = row[0], row[1], row[2]
                if lvl.startswith("fn:") and fnames[int(lvl[3:])] in ("rx_search", "rx_search_run"):
                    checks += 1
                    nact = int(row[3])
                    # the holding function is entered once per rx_search call, and
                    # once more where a FRAMES give-up escalates to the deep tier
                    # (rx_search_deep re-runs _run); a zero-use activation is data
                    c = calls.get((path, rg), -1)
                    if not (c <= nact <= 2 * c):
                        viol.append("act>calls %s %s" % (os.path.basename(path), rg))
            checks += 1
            if info["mono"]:
                viol.append("MONO %d" % info["mono"])
            if not info["answers_identical"]:
                viol.append("ANSWERS DIFFER")
            nviol += len(viol)
            noracle += len(info["oracle_diff"])
            fk.write("%s\t%s\tok\t%s\t%d\t%d\t%d\t%d\t%d%s\n" % (
                cell, cfg, info["answers_identical"], info["n_answers"], info["oracle_checked"],
                len(info["oracle_diff"]), checks, len(viol),
                ("\t" + "; ".join(viol[:5])) if viol else ""))
            fc.flush(); fs.flush(); fk.flush()
    print("UPA COMPLETE jobs=%d violations=%d oracle_diff=%d" % (len(jobs), nviol, noracle))
    return 1 if nviol else 0


if __name__ == "__main__":
    sys.exit(main())
