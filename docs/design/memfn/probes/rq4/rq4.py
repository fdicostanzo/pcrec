#!/usr/bin/env python3
"""docs/design/memfn/probes/rq4/rq4.py -- the RQ-4 tier-U timing harness
(lane rq4h): DEFAULT (-fmemfn-simd, KA AND KB) vs KB-DENY (--memfn=no-vrun-kb,
KA alone) vs OFF (-fno-memfn-simd, the scalar layer with glibc memchr inside),
at -O2 -march=x86-64 (w16 live) and -O2 -march=x86-64-v3 (w32 live), both
-mtune=generic. The question is docs/dev/lanes/rankuse_report.md §6; the regime
is integration.md §R4.9.5 (tier U, sub-class U-dev on the 7700X).

    python3 rq4.py --pcrec BIN --out DIR [--cpus 12-15] [--launches 3]
                   [--min-ms 50] [--subjects DIR] [--cells a,b] [--tiny]

Stages, each logged as a `STAGE <name> ...` line:
  header   box, CPU class, governor, boost, glibc, gcc, pcrec, cpus and their
           SMT siblings, load1 (header.txt)
  emit     one artifact per (cell, arm), `pcrec -p rx --features all
           [--engine=vm] ARM -o art/<cell>/<arm>/rx.c` (the SAME basename in
           every arm, so a byte compare is a text compare)
  facts    per cell: FORMS stamp per arm, byte identity of every arm pair
           (the null population, §R4.9.5 item 5), KA/KB as the DEFAULT
           artifact's w16 helper sets them; per (cell, arm, level) the LIVE
           dispatcher arm read from the preprocessed artifact (`gcc -E` at the
           level: a surviving call to `__w32(` = w32, else `__w16(` = w16,
           else scalar); a vrun arm whose live level is not the level's
           expected one is a FAIL (meta.tsv)
  build    one binary per (cell, arm, level): the artifact + rq4_drv.c
  check    every subject of every cell answered by all three arms through
           the driver's find-all: (hits, FNV of the bytes, position sum)
           must be equal across arms (check.tsv); a mismatch is a FAIL
  time     launches x levels x cells x regimes, the three arms INTERLEAVED
           per regime (rotated order, so each arm takes each position);
           one process per reading under `taskset -c CPUS`; per reading the
           SMT siblings' busy% (/proc/stat deltas), the CPUs' mean
           scaling_cur_freq and load1 (raw.tsv, appended row by row)
Last line: `RQ4-RUN COMPLETE <out> fails=<n> readings=<n> wall=<s>s`.
rq4_table.py renders raw.tsv + meta.tsv.

Regimes (K-1 names; every cell gets all of them, `--tiny` only the first):
  gate/tail-64k, gate/tail-1m        THROUGHPUT, isolated: one call from 0,
                                     the scan crosses the subject to its one
                                     hit at the end (hit-sparse extreme)
  sweep/sparse-64k, sweep/sparse-1m  THROUGHPUT, chained find-all, a hit per
                                     ~16 KiB (hit-sparse)
  sweep/dense-64k, sweep/dense-1m    THROUGHPUT, chained, a hit per ~256 B
                                     (hit-dense)
  pc16, pc64, pc256, pc1024          PER-CALL: one call from 0 on each of up
                                     to 256 chunks of sparse-64k
  short75                            PER-CALL: the capability set's 75 short
                                     subjects (only with --subjects)
  space8 .. space256                 DENSITY: find-all over 64 KiB with the
                                     witness every S bytes (§R4.9.5 item 7)
  bench/<set>/t-64k|t-1m gate, sweep R-1's own bench subjects (cells whose
                                     `bench` column names a set; --subjects)
Every subject is generated by the driver from (spec, witness, seed); see
rq4_drv.c's header.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))

ARMS = [("DEFAULT", ["-fmemfn-simd"]),
        ("KBDENY", ["-fmemfn-simd", "--memfn=no-vrun-kb"]),
        ("OFF", ["-fno-memfn-simd"])]
LEVELS = [("v1", ["-O2", "-march=x86-64", "-mtune=generic"], "w16"),
          ("v3", ["-O2", "-march=x86-64-v3", "-mtune=generic"], "w32")]
K64, M1 = 65536, 1048576


def regimes(cell, subjects):
    """(label, class, driver regime, subject spec) for one cell, in order"""
    r = [("gate/tail-64k", "THROUGHPUT", "gate", "tail:%d" % K64),
         ("gate/tail-1m", "THROUGHPUT", "gate", "tail:%d" % M1),
         ("sweep/sparse-64k", "THROUGHPUT", "sweep", "rand:%d:16384" % K64),
         ("sweep/sparse-1m", "THROUGHPUT", "sweep", "rand:%d:16384" % M1),
         ("sweep/dense-64k", "THROUGHPUT", "sweep", "rand:%d:256" % K64),
         ("sweep/dense-1m", "THROUGHPUT", "sweep", "rand:%d:256" % M1)]
    for L in (16, 64, 256, 1024):
        r.append(("pc%d" % L, "PER-CALL", "pc%d" % L, "rand:%d:16384" % K64))
    if subjects:
        r.append(("short75", "PER-CALL", "gate", "short:" + os.path.join(subjects, "short.bin")))
    wl = len(cell["witness"])
    for S in (8, 16, 32, 64, 128, 256):
        if S > wl:
            r.append(("space%d" % S, "DENSITY", "sweep", "space:%d:%d" % (K64, S)))
    if subjects and cell["bench"] != "-":
        for size in ("t-64k", "t-1m"):
            f = "file:" + os.path.join(subjects, cell["bench"], size + ".bin")
            r.append(("bench/%s-%s/gate" % (cell["bench"], size), "BENCH", "gate", f))
            r.append(("bench/%s-%s/sweep" % (cell["bench"], size), "BENCH", "sweep", f))
    return r


def unescape(s):
    return s.encode("latin-1").decode("unicode_escape").encode("latin-1")


def read_cells(path):
    cells = []
    for ln in open(path, encoding="utf-8"):
        if ln.startswith("#") or not ln.strip():
            continue
        f = ln.rstrip("\n").split("\t")
        if len(f) != 7:
            sys.exit("rq4: cells.tsv: want 7 fields, got %d: %r" % (len(f), ln))
        cells.append(dict(id=f[0], engine=f[1], cls=f[2], bench=f[3], inject=f[4],
                          witness=unescape(f[5]), pattern=f[6]))
    return cells


def sh(argv, **kw):
    return subprocess.run(argv, capture_output=True, **kw)


def readf(p, default="?"):
    try:
        return open(p).read().strip()
    except OSError:
        return default


def cpu_list(spec):
    out = []
    for part in spec.split(","):
        a, _, b = part.partition("-")
        out += list(range(int(a), int(b or a) + 1))
    return out


def stat_cpus(cpus):
    """{cpu: (busy, total)} jiffies from /proc/stat"""
    want = {"cpu%d" % c for c in cpus}
    res = {}
    for ln in open("/proc/stat"):
        f = ln.split()
        if f and f[0] in want:
            v = [int(x) for x in f[1:9]]
            res[int(f[0][3:])] = (sum(v) - v[3] - v[4], sum(v))
    return res


def busy_pct(a, b):
    db = sum(b[c][0] - a[c][0] for c in a)
    dt = sum(b[c][1] - a[c][1] for c in a)
    return 100.0 * db / dt if dt else 0.0


def load1():
    return float(readf("/proc/loadavg", "0").split()[0])


def mhz(cpus):
    v = [int(readf("/sys/devices/system/cpu/cpu%d/cpufreq/scaling_cur_freq" % c, "0")) for c in cpus]
    return sum(v) / len(v) / 1000.0 if v else 0.0


def cpu_class(model):
    for key, cls in (("7700X", "zen4"), ("1600 ", "zen1"), ("Apple M1", "m1")):
        if key in model:
            return cls
    return "unknown"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pcrec", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--cells-file", default=os.path.join(HERE, "cells.tsv"))
    ap.add_argument("--cells", default="", help="comma list of cell ids (default all)")
    ap.add_argument("--cpus", default="12-15")
    ap.add_argument("--launches", type=int, default=3)
    ap.add_argument("--min-ms", type=float, default=50.0)
    ap.add_argument("--subjects", default="", help="subjects_r4b.py OUTDIR (bench + short75)")
    ap.add_argument("--wait-load", type=float, default=0.0,
                    help="before each launch wait (cap 600 s) for load1 below this; 0 = no wait")
    ap.add_argument("--jobs", type=int, default=8, help="parallel emits/builds (not timing)")
    ap.add_argument("--tiny", action="store_true",
                    help="dry run: cells mi,n01, regime gate/tail-64k, 1 launch, 5 ms loops")
    a = ap.parse_args()
    t_start = time.time()
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    tmp = os.path.join(out, "tmp")
    os.makedirs(tmp, exist_ok=True)
    env = dict(os.environ, TMPDIR=tmp)
    log = open(os.path.join(out, "rq4.log"), "a")
    fails = []

    def say(msg):
        print(msg, flush=True)
        log.write(msg + "\n")
        log.flush()

    def fail(msg):
        fails.append(msg)
        say("FAIL " + msg)

    cells = read_cells(a.cells_file)
    if a.tiny:
        a.cells, a.launches, a.min_ms = a.cells or "mi,n01", 1, 5.0
    if a.cells:
        want = a.cells.split(",")
        cells = [c for c in cells if c["id"] in want]
        if len(cells) != len(want):
            sys.exit("rq4: unknown cell in --cells %s" % a.cells)
    cpus = cpu_list(a.cpus)
    sibs = set()
    for c in cpus:
        sibs |= set(cpu_list(readf("/sys/devices/system/cpu/cpu%d/topology/thread_siblings_list" % c, str(c))))
    sibs -= set(cpus)

    # ---- header ----
    model = next((ln.split(":", 1)[1].strip() for ln in open("/proc/cpuinfo")
                  if ln.startswith("model name")), "?")
    hdr = [
        "# RQ-4 tier-U timing (rq4.py, lane rq4h) -- tier U, NOT a verdict (§R4.9.5)",
        "date        %s" % time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "host        %s" % os.uname().nodename,
        "cpu         %s" % model,
        "cpu_class   %s (sub-class U-dev on the 7700X)" % cpu_class(model),
        "governor    %s" % readf("/sys/devices/system/cpu/cpu%d/cpufreq/scaling_governor" % cpus[0]),
        "boost       %s" % readf("/sys/devices/system/cpu/cpufreq/boost"),
        "glibc       %s" % sh(["getconf", "GNU_LIBC_VERSION"], text=True).stdout.strip(),
        "gcc         %s" % sh(["gcc", "--version"], text=True).stdout.splitlines()[0],
        "pcrec       %s (%s)" % (sh(["git", "-C", REPO, "rev-parse", "--short", "HEAD"], text=True).stdout.strip(),
                                 a.pcrec),
        "kit         in-tree memfn/ at the same commit",
        "cpus        taskset -c %s; SMT siblings %s (busy%% recorded per reading)" %
        (a.cpus, ",".join(map(str, sorted(sibs))) or "none"),
        "levels      %s" % "; ".join("%s = %s (%s live)" % (n, " ".join(f), w) for n, f, w in LEVELS),
        "arms        %s" % "; ".join("%s = %s" % (n, " ".join(f)) for n, f in ARMS),
        "loops       min of 3 loops >= %.0f ms per reading; %d launches; median over launches" %
        (a.min_ms, a.launches),
        "load1       %.2f at start" % load1(),
        "mode        %s" % ("TINY DRY RUN -- numbers are NOT readings" if a.tiny else "full"),
    ]
    with open(os.path.join(out, "header.txt"), "w") as f:
        f.write("\n".join(hdr) + "\n")
    for h in hdr:
        say(h)

    # ---- emit ----
    t0 = time.time()

    def emit(job):
        c, (arm, flags) = job
        d = os.path.join(out, "art", c["id"], arm)
        os.makedirs(d, exist_ok=True)
        argv = [a.pcrec, "-p", "rx", "--features", "all"]
        if c["engine"] == "vm":
            argv.append("--engine=vm")
        r = sh(argv + flags + ["-o", os.path.join(d, "rx.c"), "--pattern", c["pattern"]], timeout=120)
        return c["id"], arm, r.returncode, r.stderr.decode(errors="replace").strip()

    with ThreadPoolExecutor(a.jobs) as ex:
        for cid, arm, rc, err in ex.map(emit, [(c, arm) for c in cells for arm in ARMS]):
            if rc:
                fail("emit %s/%s rc=%d %s" % (cid, arm, rc, err[:200]))
    say("STAGE emit rc=%d cells=%d artifacts=%d %.1fs" %
        (len(fails), len(cells), 3 * len(cells), time.time() - t0))

    # ---- facts ----
    t0 = time.time()
    meta = open(os.path.join(out, "meta.tsv"), "w")
    meta.write("cell\tengine\tclass\tbench\tforms_DEFAULT\tforms_KBDENY\tforms_OFF\tid_DK\tid_DO\tid_KO"
               "\tka\tkb\tlive_v1\tlive_v3\tinject\tpattern\n")
    for c in cells:
        txt = {}
        for arm, _ in ARMS:
            d = os.path.join(out, "art", c["id"], arm)
            txt[arm] = open(os.path.join(d, "rx.c"), "rb").read() + open(os.path.join(d, "rx.h"), "rb").read()
        forms = {arm: (re.search(rb'#define RX_MEMFN_FORMS "([^"]*)"', t) or [b"", b"?"])[1].decode()
                 for arm, t in txt.items()}
        idp = lambda x, y: int(txt[x] == txt[y])
        # KA, KB as the DEFAULT artifact's first w16 helper sets them
        w16 = txt["DEFAULT"].split(b"__w16(", 1)[1] if b"__w16(" in txt["DEFAULT"] else b""
        h = w16[:4000]
        sets = {k.decode(): int(v) for k, v in re.findall(rb"\b([mv][ab]) = _mm_set1_epi8\(\(char\)(\d+)\)", h)}

        def at(m, v):  # the load offset feeding the compare against m (masked) or v (exact)
            r = re.search(rb"subject \+ i(?: \+ (\d+))?\)\), (?:" + m + b"|" + v + rb")\)", h)
            return (r[1] or b"0").decode() if r else "?"
        ka = ("V=%d,M=%d,at=%s" % (sets["va"], sets.get("ma", 255), at(b"ma", b"va"))
              if "va" in sets else "-")
        kb = ("V=%d,M=%d,at=%s" % (sets["vb"], sets.get("mb", 255), at(b"mb", b"vb"))
              if "vb" in sets else "-")
        c["ka_vm"] = (sets["va"], sets.get("ma", 255)) if "va" in sets else None
        live = {}
        for lv, lflags, expect in LEVELS:
            col = []
            for arm, _ in ARMS:
                src = os.path.join(out, "art", c["id"], arm, "rx.c")
                pp = sh(["gcc", "-E", "-P"] + lflags + [src], timeout=120, env=env).stdout
                w = "w32" if b"__w32(" in pp else "w16" if b"__w16(" in pp else "scalar"
                col.append("%s=%s" % (arm, w))
                vrun = "vrun" in forms[arm]
                if (vrun and w != expect) or (not vrun and w != "scalar"):
                    fail("live %s/%s at %s reads %s (FORMS %s, expected %s)" %
                         (c["id"], arm, lv, w, forms[arm], expect if vrun else "scalar"))
            live[lv] = ",".join(col)
        meta.write("\t".join([c["id"], c["engine"], c["cls"], c["bench"], forms["DEFAULT"], forms["KBDENY"],
                              forms["OFF"], str(idp("DEFAULT", "KBDENY")), str(idp("DEFAULT", "OFF")),
                              str(idp("KBDENY", "OFF")), ka, kb, live["v1"], live["v3"], c["inject"],
                              c["pattern"]]) + "\n")
        if c["inject"] != "-" and not c["ka_vm"]:
            fail("cell %s injects KA but the DEFAULT artifact has no vrun helper" % c["id"])
    meta.close()
    say("STAGE facts rc=%d %.1fs (meta.tsv)" % (len(fails), time.time() - t0))

    # ---- build ----
    t0 = time.time()
    drv = os.path.join(HERE, "rq4_drv.c")
    for lv, lflags, _ in LEVELS:
        r = sh(["gcc"] + lflags + ["-Wall", "-Wextra", "-c", drv, "-o", os.path.join(tmp, "drv_%s.o" % lv)],
               env=env, timeout=120)
        if r.returncode:
            fail("build driver %s: %s" % (lv, r.stderr.decode()[:300]))

    def build(job):
        c, arm, (lv, lflags, _) = job
        d = os.path.join(out, "art", c["id"], arm)
        obj, exe = os.path.join(d, "rx_%s.o" % lv), os.path.join(d, "drv_%s" % lv)
        r = sh(["gcc"] + lflags + ["-c", os.path.join(d, "rx.c"), "-o", obj], env=env, timeout=300)
        if r.returncode == 0:
            r = sh(["gcc"] + lflags + [obj, os.path.join(tmp, "drv_%s.o" % lv), "-o", exe], env=env, timeout=120)
        return c["id"], arm, lv, r.returncode, r.stderr.decode(errors="replace")[:300]

    with ThreadPoolExecutor(a.jobs) as ex:
        for cid, arm, lv, rc, err in ex.map(build, [(c, arm, L) for c in cells for arm, _ in ARMS for L in LEVELS]):
            if rc:
                fail("build %s/%s/%s: %s" % (cid, arm, lv, err))
    say("STAGE build rc=%d binaries=%d %.1fs" % (len(fails), 6 * len(cells), time.time() - t0))

    def exe(c, arm, lv):
        return os.path.join(out, "art", c["id"], arm, "drv_%s" % lv)

    def drv_args(c, reg, spec):
        args = [b"--witness=" + c["witness"], "--subject=" + spec, "--regime=" + reg]
        if c["inject"] != "-" and c.get("ka_vm"):
            args.append("--inject=%d,%d,%s" % (c["ka_vm"][0], c["ka_vm"][1], c["inject"]))
        return args

    # ---- check ----
    t0 = time.time()
    plan = {c["id"]: regimes(c, a.subjects) for c in cells}
    if a.tiny:
        plan = {k: v[:1] for k, v in plan.items()}
    chk = open(os.path.join(out, "check.tsv"), "w")
    chk.write("cell\tlevel\tsubject\tarm\thits\tfnv\tpossum\n")
    nchk = 0
    for c in cells:
        for lv, _, _ in LEVELS:
            for spec in sorted({p[3] for p in plan[c["id"]]}):
                ans = {}
                for arm, _ in ARMS:
                    r = sh([exe(c, arm, lv)] + drv_args(c, "check", spec), timeout=300)
                    f = r.stdout.decode(errors="replace").strip().split("\t")
                    if r.returncode or len(f) != 9:
                        fail("check %s/%s/%s %s rc=%d %s" % (c["id"], arm, lv, spec, r.returncode,
                                                             r.stderr.decode(errors="replace")[:200]))
                        continue
                    ans[arm] = (f[5], f[6], f[7])
                    chk.write("\t".join([c["id"], lv, spec, arm] + list(ans[arm])) + "\n")
                    nchk += 1
                if len(set(ans.values())) > 1:
                    fail("check %s/%s %s: arms disagree %s" % (c["id"], lv, spec, ans))
                elif ans and int(next(iter(ans.values()))[0]) == 0 and not spec.startswith(("short:", "file:")):
                    fail("check %s/%s %s: no hit in a planted subject" % (c["id"], lv, spec))
    chk.close()
    say("STAGE check rc=%d answers=%d %.1fs (check.tsv)" % (len(fails), nchk, time.time() - t0))
    if fails:
        say("RQ4-RUN COMPLETE %s fails=%d readings=0 wall=%ds (stopped before timing)" %
            (out, len(fails), time.time() - t_start))
        return 1

    # ---- time ----
    t0 = time.time()
    total = a.launches * len(LEVELS) * sum(len(v) for v in plan.values()) * len(ARMS)
    say("STAGE time START readings=%d cells=%d launches=%d cpus=%s" % (total, len(cells), a.launches, a.cpus))
    raw_path = os.path.join(out, "raw.tsv")
    new = not os.path.exists(raw_path)
    raw = open(raw_path, "a")
    if new:
        raw.write("launch\tlevel\tcell\tengine\tclass\tarm\tpos\trlabel\trclass\tsubject\tns\tspread\thits"
                  "\tfnv\tpossum\tcalls\tsib_busy\tmhz\tload1\n")
    n = 0
    for launch in range(a.launches):
        w0 = time.time()
        while a.wait_load > 0 and load1() >= a.wait_load and time.time() - w0 < 600:
            time.sleep(10)
        say("LAUNCH %d load1=%.2f waited=%ds" % (launch + 1, load1(), time.time() - w0))
        for lv, _, _ in LEVELS:
            for ci, c in enumerate(cells):
                for ri, (label, rclass, reg, spec) in enumerate(plan[c["id"]]):
                    k = (launch + ci + ri) % len(ARMS)
                    for pos, (arm, _) in enumerate(ARMS[k:] + ARMS[:k]):
                        st0, l1 = stat_cpus(sibs), load1()
                        r = sh(["taskset", "-c", a.cpus, exe(c, arm, lv)] + drv_args(c, reg, spec) +
                               ["--min-ms=%g" % a.min_ms], timeout=600)
                        sb = busy_pct(st0, stat_cpus(sibs)) if sibs else 0.0
                        f = r.stdout.decode(errors="replace").strip().split("\t")
                        if r.returncode or len(f) != 9:
                            fail("time %s/%s/%s %s rc=%d %s" % (c["id"], arm, lv, label, r.returncode,
                                                                r.stderr.decode(errors="replace")[:200]))
                            continue
                        raw.write("\t".join([str(launch + 1), lv, c["id"], c["engine"], c["cls"], arm, str(pos),
                                             label, rclass, spec] + f[3:9] +
                                            ["%.1f" % sb, "%.0f" % mhz(cpus), "%.2f" % l1]) + "\n")
                        raw.flush()
                        n += 1
                        if n % 200 == 0:
                            el = time.time() - t0
                            say("PROGRESS %d/%d readings %.0fs elapsed, ~%.0fs left" %
                                (n, total, el, el / n * (total - n)))
    raw.close()
    say("STAGE time rc=%d readings=%d %.1fs (raw.tsv)" % (len(fails), n, time.time() - t0))
    shutil.rmtree(tmp, ignore_errors=True)
    say("RQ4-RUN COMPLETE %s fails=%d readings=%d wall=%ds" % (out, len(fails), n, time.time() - t_start))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
