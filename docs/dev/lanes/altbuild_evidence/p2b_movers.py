"""p2b_movers.py BASE_PCREC STAGE_PCREC TREE BENCH_DIR OUT_TSV [--jobs N] --
Stage 2b's mover census (docs/design/alt_normal_form.md §5 2b "Predicted
movers": the census is the stage's first deliverable; lane altbuild,
2026-11-06). BASE is `80341284e` with only the abi digit bumped.

Population: p2b_work.py's (every corpus block at its encoding, every bench
pattern). Each is compiled `--features all -e ENC -o -` on two routes, the
default and `--engine=vm`, by BASE and by STAGE, and these observables are
read: the two altcls stamps, the engine, `RX_VM_PROGRAM_BYTES`,
`RX_VM_ALT_ISLANDS`, `RX_VM_RUNGS`, the artifact's byte size (the DFA's
tables), rc. Then STAGE again with `-fno-altcls-merge -fno-altcls-factor`
against BASE with the same: every byte-encoding cell must be IDENTICAL there
(the denials restore today's tree; utf8 cells keep stage 1's lowering under
a merge deny, which `-fno-altcls-merge` also denies, so they are held too).
Prints per observable the mover count and direction; writes every mover.
Exit 1 on a refusal that differs, or a denied cell that differs."""
import os, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import importlib.util
sp = importlib.util.spec_from_file_location("p2bw", os.path.join(os.path.dirname(os.path.abspath(__file__)), "p2b_work.py"))

STAMP = re.compile(rb'^#define RX_(ALTCLS_MERGES|ALTCLS_FACTORED|ENGINE|VM_PROGRAM_BYTES|VM_ALT_ISLANDS|VM_RUNGS) (\S+)', re.M)
HDR = re.compile(rb'^/\* Generated by pcrec [^\n]*\*/\n', re.M)

def load_pop(pcrec, tree, broot):
    src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "p2b_work.py")).read()
    src = src.replace("\nmain()\n", "\n")
    ns = {"__file__": os.path.join(os.path.dirname(os.path.abspath(__file__)), "p2b_work.py")}
    exec(compile(src, "p2b_work.py", "exec"), ns)
    return ns["corpus"](pcrec, tree) + ns["bench"](broot)

def comp(pcrec, pat, enc, flags, extra):
    inl = "".join(x for x in flags if x in "msx")
    if inl: pat = b"(?" + inl.encode() + b")" + pat
    argv = [pcrec, "-p", "rx", "-e", enc, "--features", "all", "-o", "-"] + extra
    if "i" in flags: argv.append("-i")
    try:
        r = subprocess.run(argv + ["--pattern", pat], capture_output=True, timeout=120)
    except subprocess.TimeoutExpired:
        return ("TIMEOUT",)
    if r.returncode: return ("REFUSED", r.stderr[-120:])
    out = HDR.sub(b"", r.stdout)
    st = dict((k.decode(), v.decode()) for k, v in STAMP.findall(out))
    return ("ok", st, len(out), out)

def one(args):
    base, stage, (where, pat, flags, enc) = args
    row = {"where": where, "pat": pat, "enc": enc}
    for route, extra in (("auto", []), ("vm", ["--engine=vm"])):
        row[route] = (comp(base, pat, enc, flags, extra), comp(stage, pat, enc, flags, extra))
    d = ["-fno-altcls-merge", "-fno-altcls-factor"]
    a, b = comp(base, pat, enc, flags, d), comp(stage, pat, enc, flags, d)
    row["denied_same"] = (a[0] == b[0] and (a[0] != "ok" or a[3] == b[3]))
    return row

def main():
    a = sys.argv[1:]
    jobs = 8
    if "--jobs" in a:
        i = a.index("--jobs"); jobs = int(a[i + 1]); del a[i:i + 2]
    base, stage, tree, broot, out = a
    pop = load_pop(stage, tree, broot)
    with ThreadPoolExecutor(jobs) as ex:
        rows = list(ex.map(one, [(base, stage, p) for p in pop]))
    obs = ["ALTCLS_MERGES", "ALTCLS_FACTORED", "ENGINE", "VM_PROGRAM_BYTES", "VM_ALT_ISLANDS", "VM_RUNGS", "size"]
    cnt = {(r, o): [0, 0, 0] for r in ("auto", "vm") for o in obs}
    bad, lines, nmov = [], [], set()
    for row in rows:
        for route in ("auto", "vm"):
            x, y = row[route]
            if x[0] != y[0]:
                bad.append("REFUSAL-MOVED %s %s %s %s" % (route, row["where"], x[0], y[0])); continue
            if x[0] != "ok": continue
            for o in obs:
                vx = x[2] if o == "size" else x[1].get(o, "-")
                vy = y[2] if o == "size" else y[1].get(o, "-")
                if vx == vy: continue
                c = cnt[(route, o)]
                try: c[0 if float(str(vy).rstrip("u")) < float(str(vx).rstrip("u")) else 1] += 1
                except ValueError: c[2] += 1
                nmov.add(row["where"])
                lines.append("%s\t%s\t%s\t%s\t%s\t%s" % (row["where"], row["enc"], route, o, vx, vy))
        if not row["denied_same"]:
            bad.append("DENIED-DIFFERS %s %s" % (row["where"], row["pat"][:60]))
    with open(out, "w") as f:
        f.write("where\tenc\troute\tobservable\tbase\tstage\n" + "\n".join(lines) + "\n")
    print("population: %d patterns x 2 routes (+ the denied pair)" % len(rows))
    print("patterns with any mover: %d" % len(nmov))
    for (route, o), (dn, up, other) in sorted(cnt.items()):
        if dn or up or other:
            print("  %-4s %-18s down %5d  up %5d  other %d" % (route, o, dn, up, other))
    for b in bad[:30]: print(b)
    print("refusal or denied-identity findings: %d" % len(bad))
    print("p2b movers: %s" % ("FAIL" if bad else "PASS"))
    sys.exit(1 if bad else 0)

main()
