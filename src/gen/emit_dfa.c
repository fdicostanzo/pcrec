/* M2.1 self-loop skip: pick up to 4 states (excluding `exclude`) that stay
 * put on >= 192 of 256 bytes — their scan degenerates to a SIMD-friendly
 * skip loop. Motivated by compare case h (`.*=.*`): the post-'=' state
 * self-loops on everything but '\n' in both machines.
 *
 * M2.10 tried replacing this absolute byte count with a fraction of the
 * state's LIVE bytes, so that narrow-alphabet patterns like `[01]*1[01]{8}`
 * (2 live bytes, 100% stay) would qualify — R2-A5 had described that case as
 * having "no skip-eligible states". The reasoning was sound and the result
 * was a REGRESSION: it gives case (f) one reverse skip table and measures
 * 158.6/159.1 -> 118.7 MB/s on the compare harness and 159.1/157.5 ->
 * 115.9/115.8 MB/s on bdriver, spreads 1.01-1.02x, i.e. ~27% slower on the
 * exact case it was meant to fix. Reverted; see D13 and the 2026-08-09
 * journal entry. Do not re-attempt without measuring the REVERSE machine
 * specifically — the suspicion is that a backward byte-at-a-time skip loop
 * loses to the reverse table walk, but that is untested. */
static int pick_skip_states(const Dfa *d, int exclude, int out[4])
{
    int cls_size[256] = {0};
    for (int b = 0; b < 256; b++) cls_size[d->clsmap[b]]++;
    int nout = 0;
    for (int pass = 0; pass < 4; pass++) {
        int best = -1, bestcnt = 191;
        for (int i = 0; i < d->n; i++) {
            if (i == exclude) continue;
            /* [M6.2 wave B] A STATE WHOSE ACCEPT DEPENDS ON THE NEXT BYTE IS
             * NOT SKIP-ELIGIBLE, and this is the D11-rule-1 hazard §3.6.1
             * describes, resolved by declining rather than by intersecting.
             *
             * A skip advances without consulting accept flags and records
             * only its LANDING position. That is sound while the accept bit
             * is constant across the run — which the pre-wave scalar accept
             * made true unconditionally, and a class-indexed one does not.
             * The concrete loss: a forward skip whose run's bytes all accept
             * landing on a byte whose class does not, with `last` wanting the
             * LARGEST accepting position, throws away every position it just
             * passed.
             *
             * §3.6.1 argues from §3.5 that `\b` cannot reach this, on the
             * ground that a skip set is a union of classes and therefore
             * pins next-is-word across the run. THE SECOND HALF DOES NOT
             * FOLLOW: a union of classes may perfectly well contain both word
             * and non-word classes (a state that stays put on both `a` and
             * ` ` has exactly such a stay set). So the argument is not
             * available and this declines instead. Declining is always safe
             * and costs nothing on any pattern without a next-byte-sensitive
             * accept — i.e. nothing in the pre-wave corpus, where this test
             * is false at every state. */
            if (state_acc_varies(&d->st[i])) continue;
            bool taken = false;
            for (int k = 0; k < nout; k++)
                if (out[k] == i) taken = true;
            if (taken) continue;
            int stay = 0;
            for (int cl = 0; cl < d->ncls; cl++)
                if (d->st[i].tr[cl] == i) stay += cls_size[cl];
            if (stay > bestcnt) { bestcnt = stay; best = i; }
        }
        if (best < 0) break;
        out[nout++] = best;
    }
    return nout;
}

static void emit_stay_table(StrBuf *c, const char *p, const char *tag,
                            int idx, const Dfa *d)
{
    uint8_t stay[256];
    for (int b = 0; b < 256; b++)
        stay[b] = (uint8_t)(d->st[idx].tr[d->clsmap[b]] == idx);
    char name[32];
    snprintf(name, sizeof(name), "%s%d", tag, idx);
    emit_u8_table(c, p, name, stay, 256);
}

/* ---------------------------------------------------------------------
 * [M6-READ] LEGENDS: the block comments that make a table readable.
 *
 * Both are computed from the very data this file is about to write -- the
 * class map and the transition table themselves -- so neither can drift from
 * the table it describes. That is the plan row's engineering note (iv), "the
 * emitter tags what it emits, no after-the-fact inference", satisfied without
 * a tagging pass: a walk over emitter-owned data IS the tag.
 * --------------------------------------------------------------------- */

/* One byte rendered for a human: printable ASCII quoted, everything else as a
 * number. Legend text only; never emitted as code. */
static void legend_byte(StrBuf *c, int b)
{
    if (b == '\'')      sb_puts(c, "'\\''");
    else if (b == '\\') sb_puts(c, "'\\\\'");
    else if (b >= 0x20 && b < 0x7f) sb_printf(c, "'%c'", b);
    else                sb_printf(c, "%d", b);
}

/* WHICH BYTES EACH CLASS HOLDS, as ranges. Class 0 is named rather than
 * enumerated: it is the catch-all, and listing its ranges is pages of noise
 * that tells the reader nothing. */
static void emit_class_legend(StrBuf *c, const Dfa *d)
{
    sb_printf(c, "     * Class legend (%d classes; every byte not listed is class 0):\n",
              d->ncls);
    sb_puts(c, "     *   0  every other byte\n");
    for (int cl = 1; cl < d->ncls; cl++) {
        sb_printf(c, "     *   %d  ", cl);
        int shown = 0, b = 0;
        while (b < 256 && shown < 8) {
            if (d->clsmap[b] != cl) { b++; continue; }
            int a = b;
            while (b + 1 < 256 && d->clsmap[b + 1] == cl) b++;
            if (shown) sb_puts(c, ", ");
            legend_byte(c, a);
            if (b != a) { sb_puts(c, "-"); legend_byte(c, b); }
            shown++; b++;
        }
        if (b < 256) sb_puts(c, ", ...");
        sb_puts(c, "\n");
    }
}

/* WHAT EACH STATE MEANS, as the SHORTEST INPUT THAT REACHES IT -- a
 * breadth-first search over the transition table below, using each class's
 * representative byte.
 *
 * The example string IS the state's meaning, and it needs no knowledge of the
 * pattern's syntax: a reader comparing two adjacent states sees exactly what
 * the machine just consumed. On the reverse machine the walk consumes the
 * match right-to-left, so the examples read backwards and the banner says so.
 *
 * Capped: past LEGEND_MAX_STATES a full listing is noise rather than
 * orientation, so only the start and the accepting states are named and the
 * comment says what it left out. */
#define LEGEND_MAX_STATES 48
/* A state deep in the machine has an example as long as its distance from
 * the start; past this many bytes the string stops orienting anyone. */
#define LEGEND_MAX_EXAMPLE 40

static void emit_state_legend(StrBuf *c, const Dfa *d, bool reverse)
{
    int *dist  = malloc((size_t)d->n * sizeof(int));
    int *from  = malloc((size_t)d->n * sizeof(int));
    int *via   = malloc((size_t)d->n * sizeof(int));
    int *queue = malloc((size_t)d->n * sizeof(int));
    int *path  = malloc((size_t)d->n * sizeof(int));
    if (!dist || !from || !via || !queue || !path) {
        free(dist); free(from); free(via); free(queue); free(path);
        return;                    /* a legend is never worth failing a compile over */
    }
    for (int i = 0; i < d->n; i++) { dist[i] = -1; from[i] = -1; via[i] = -1; }
    int head = 0, tail = 0;
    if (d->s0 >= 0 && d->s0 < d->n) { dist[d->s0] = 0; queue[tail++] = d->s0; }
    while (head < tail) {
        int s = queue[head++];
        for (int cl = 0; cl < d->ncls; cl++) {
            int nx = d->st[s].tr[cl];
            if (nx < 0 || nx >= d->n || dist[nx] >= 0) continue;
            dist[nx] = dist[s] + 1; from[nx] = s; via[nx] = cl;
            queue[tail++] = nx;
        }
    }

    /* How many states accept? In a big machine this decides whether a listing
     * is orientation or noise -- `((a)|b){0,4000}c` has 4002 accepting states,
     * and naming them all cost 4000 lines and tripled the artifact. Caught by
     * the [ENG-BREP] emitted-size check, which is exactly what it is for. */
    int nacc = 0;
    for (int i = 0; i < d->n; i++) if (d->st[i].up[UPC_PLAIN].accept) nacc++;

    bool brief = d->n > LEGEND_MAX_STATES;
    if (brief) {
        /* A SUMMARY, not a truncated list. Which particular states accept is
         * not orientation once there are thousands of them; how many there
         * are, and what the shortest accepted input looks like, is. */
        int shortest = -1;
        for (int i = 0; i < d->n; i++)
            if (d->st[i].up[UPC_PLAIN].accept && dist[i] >= 0 &&
                (shortest < 0 || dist[i] < dist[shortest])) shortest = i;
        sb_printf(c, "     * State legend -- %d states, %d of them accepting: too many\n"
                     "     * to name individually. The start state is %d",
                  d->n, nacc, d->s0);
        if (shortest >= 0)
            sb_printf(c, ", and the\n"
                         "     * shortest input reaching an accepting state is %d byte(s) long",
                      dist[shortest]);
        sb_puts(c, ".\n");
        free(dist); free(from); free(via); free(queue); free(path);
        return;
    }
    if (reverse)
        sb_puts(c, "     * State legend -- the bytes this walk consumes, IN WALK\n"
                   "     * ORDER, i.e. the match read backwards:\n");
    else
        sb_puts(c, "     * State legend -- the shortest input that reaches each state:\n");
    for (int i = 0; i < d->n; i++) {
        bool acc = d->st[i].up[UPC_PLAIN].accept != 0;
        /* NOT "unreachable": this walk follows the plain transitions only, and
         * a state can also be selected by a POSITION VIEW (end of subject, end
         * of line) that has no edge in the table below. Saying what the walk
         * actually established is the honest claim; saying the state is dead
         * would be wrong, and is wrong on `^ab(c|d)e$` today. */
        if (dist[i] < 0) {
            sb_printf(c, "     *  %3d  (no path through the transitions above;\n"
                         "     *       a position view can still select it)\n", i);
            continue;
        }
        sb_printf(c, "     *  %3d  ", i);
        if (dist[i] == 0) sb_puts(c, "(start) nothing consumed yet");
        else {
            int len = dist[i], k = len, s = i;
            while (k > 0) { path[--k] = via[s]; s = from[s]; }
            sb_puts(c, "\"");
            int shown = len < LEGEND_MAX_EXAMPLE ? len : LEGEND_MAX_EXAMPLE;
            for (k = 0; k < shown; k++) {
                int b = d->rep[path[k]];
                if (b >= 0x20 && b < 0x7f && b != '"' && b != '\\')
                    sb_printf(c, "%c", b);
                else sb_printf(c, "\\x%02x", b);
            }
            sb_puts(c, "\"");
            if (shown < len) sb_printf(c, "... (%d bytes)", len);
        }
        if (acc) sb_puts(c, "   ACCEPTING");
        sb_puts(c, "\n");
    }
    free(dist); free(from); free(via); free(queue); free(path);
}

/* M2.7 put `$`-bearing patterns on this engine; M2.12 gave them back the
 * scan-avoidance M2.7 had traded away. Both live in ONE emitter on purpose:
 * M2.7 forked a second copy, and the fork is exactly how the prefilter and
 * skip loops went missing from the `$` path for a whole milestone.
 *
 * EOL handling: both machines switch to a state's EOL variant exactly at EOL
 * positions (end of subject, or before a final newline), guarded by
 * `pos + 1 >= n` — false for every byte but the last two, so the scan stays a
 * tight table walk.
 *
 * Scan avoidance under EOL (M2.12): a prefilter or self-loop skip advances
 * `pos` WITHOUT consulting accept flags, which is unsound when a state can
 * accept at an EOL position. The fix is to bound every skip at `n - 1` rather
 * than `n` and let the stepped loop handle the last two positions. That also
 * keeps the EOL-variant lookup correct for free: a skip can only run when
 * `pos + 1 < n`, and in that case `est == st` by construction, so the state
 * used for the transition is never stale. The forward prefilter additionally
 * must NOT keep its `return 0` early-out, since the start state's EOL variant
 * may still accept at n-1 or n. */
static void emit_unanchored(Ctx *cx, const char *fn, const char *storage)
{
    Job *job = cx->job;
    Dfa *fd = &job->dfa, *rd = &job->rdfa;
    StrBuf *c = &job->csb;
    const char *p = cx->opt->prefix;

    /* [DD-13] THE START ANALYSIS IS `unanch_start`'s, not this function's:
     * the view flags, the candidate set and the prefilter verdict are all
     * read a SECOND time by the artifact's `<PREFIX>_DFA_PREFILTER` stamp,
     * and that function's header states why they may not be derived twice. */
    UnanchStart us;
    unanch_start(fd, rd, &us);
    bool eol = us.eol, endv = us.endv, viewsel = us.viewsel, views = us.views;

    /* [M6.2 wave B] `facc2`/`racc2` — some state's accept actually varies with
     * the next byte, so §3.6's class-indexed accept table is needed. Its
     * sibling `wctx` (the machine carries a word context at all) lives in
     * `unanch_start` because `views` is built from it; a pattern can have the
     * first without the second, which is why they are two facts. */
    bool facc2 = dfa_has_clsacc(fd);
    bool racc2 = dfa_has_clsacc(rd);

    int fs = fd->s0;   /* no asserts -> s0 == s1 */
    int rs = rd->s0;
    /* MECHANISM 4 is only EMITTED where it can change an answer. With the two
     * interior start states interned to the same state the seed table would
     * be a constant column, so the pre-wave constant start is emitted instead
     * — which is also what keeps every existing artifact's first lines
     * unmoved. */
    bool fseed = dfa_needs_seed(fd);
    bool rseed = dfa_needs_seed(rd);

    emit_search_head(cx, c, fn, storage);

    /* [DD-13] THE ONE EMPTY-ENGINE EXIT. It used to be two — a dead start
     * state here, and the "can neither accept nor ever leave `fs`" proof
     * forty lines down — emitting the SAME three lines with nothing written
     * between them. `unanch_start` answers both as `empty`, so the stamp path
     * and the emitter agree by construction on which artifacts have no scan
     * at all (and therefore no prefilter). Byte-for-byte the same output. */
    if (us.empty) {
        sb_puts(c, "    (void)subject; (void)subject_length; (void)search_from; (void)capture_spans;\n"
                   "    return 0;\n}\n");
        return;
    }

    /* [DD-13] THE PREFILTER, READ OFF THE SHARED DERIVATION. The forty lines
     * of start-state analysis that used to sit here are `unanch_start`'s now,
     * verbatim and with their measurements; what is left is the translation
     * from its verdict to the two booleans this emitter's loop is written
     * against. `fcand` is COPIED rather than pointed at so every use site
     * below reads exactly as it did. */
    CandSet fcand = us.cand;
    bool prefilter  = us.kind != DFA_PF_NONE;
    bool use_memchr = us.kind == DFA_PF_MEMCHR;

    int fskip[4], rskip[4];
    int nfskip = pick_skip_states(fd, fs, fskip);
    int nrskip = pick_skip_states(rd, -1, rskip);

    /* [M6-READ] The tables are the artifact's data structures, and each gets
     * the block comment the plan row's requirement (1) asks for: what it is,
     * how it is indexed, what a cell means, and -- where the cells are STATES
     * -- a legend naming them. Requirement (3)'s clarification is why there is
     * no per-row commentary inside any of them. */
    sb_puts(c, "    /* ---- FORWARD TABLES: find where a match ENDS ------------------\n"
               "     * Byte class of every possible input byte. The pattern can only\n"
               "     * tell a few kinds of byte apart, so all 256 values fold into a\n"
               "     * few classes and the transition table needs one column per class\n"
               "     * rather than 256.\n"
               "     *\n");
    emit_class_legend(c, fd);
    sb_puts(c, "     */\n");
    emit_u8_table(c, p, "forward_byte_class", fd->clsmap, 256);
    sb_printf(c, "    /* Forward transitions, indexed [state * %d + class]; -1 means\n"
                 "     * the pattern cannot continue and the scan stops. %d rows of %d.\n"
                 "     *\n", fd->ncls, fd->n, fd->ncls);
    emit_state_legend(c, fd, false);
    sb_puts(c, "     */\n");
    emit_tr_table(c, p, "forward_next_state", fd);
    sb_puts(c, "    /* 1 where a match may end, indexed by forward state. */\n");
    emit_acc_table(c, p, "forward_is_accepting", fd);
    if (facc2) emit_acc_cls_table(c, p, "forward_is_accepting_by_class", fd);
    if (fseed) emit_seed_table(c, p, "forward_seed_state", fd, fd->s1u);
    if (eol)  emit_eol_table(c, p, "forward_eol_view", fd);
    if (endv) emit_end_table(c, p, "forward_end_view", fd);
    if (prefilter && !use_memchr) {
        sb_puts(c, "    /* 1 for each byte that could be the FIRST byte of a match. The\n"
                   "     * forward loop uses this to skip over bytes that cannot begin\n"
                   "     * one instead of stepping through them; speed only, it never\n"
                   "     * changes the answer. */\n");
        cand_emit_table(c, p, "can_begin_match", &fcand);
    }
    for (int k = 0; k < nfskip; k++)
        emit_stay_table(c, p, "forward_stay", fskip[k], fd);
    sb_puts(c, "    /* ---- REVERSE TABLES: find where that match BEGINS -------------\n"
               "     * The same three-table shape, built from the pattern read right to\n"
               "     * left and walked backwards from the end the forward scan found.\n"
               "     * The two machines are independent and need not agree.\n"
               "     *\n");
    emit_class_legend(c, rd);
    sb_puts(c, "     */\n");
    emit_u8_table(c, p, "reverse_byte_class", rd->clsmap, 256);
    sb_printf(c, "    /* Reverse transitions, indexed [state * %d + class]; -1 stops\n"
                 "     * the walk. %d rows of %d.\n"
                 "     *\n", rd->ncls, rd->n, rd->ncls);
    emit_state_legend(c, rd, true);
    sb_puts(c, "     */\n");
    emit_tr_table(c, p, "reverse_next_state", rd);
    sb_puts(c, "    /* 1 where the backwards walk has consumed a whole match,\n"
               "     * indexed by reverse state. */\n");
    emit_acc_table(c, p, "reverse_is_accepting", rd);
    if (racc2) emit_acc_cls_table(c, p, "reverse_is_accepting_by_class", rd);
    if (rseed) emit_seed_table(c, p, "reverse_seed_state", rd, rd->s1u);
    if (eol)  emit_eol_table(c, p, "reverse_eol_view", rd);
    if (endv) emit_end_table(c, p, "reverse_end_view", rd);
    for (int k = 0; k < nrskip; k++)
        emit_stay_table(c, p, "reverse_stay", rskip[k], rd);

    /* Under EOL the scan reads the accept flag and the transition row through
     * `est`/`erst` (the EOL view at the last two positions); otherwise those
     * collapse to `st`/`rst` and gcc sees exactly the pre-M2.7 loop. */
    const char *fsrc = viewsel ? "forward_view_state" : "forward_state";
    const char *rsrc = viewsel ? "reverse_view_state" : "reverse_state";
    /* Every skip must stop at n-1 so a state that accepts only at EOL is
     * never skipped past; below n-1 the EOL view is unreachable, which is
     * also why `est` cannot be stale after a skip. */
    const char *fbound = views ? "scan_position + 1 < subject_length" : "scan_position < subject_length";

    sb_puts(c,   "    // ---- FORWARD SCAN: where does a match end? ----------------\n"
                 "    // One byte per iteration. The loop keeps the LAST accepting\n"
                 "    // position rather than stopping at the first, so the longest\n"
                 "    // match wins.\n"
                 "    size_t scan_position = search_from;\n"
                 "    size_t last_accept_position = (size_t)-1;\n");
    if (fseed) {
        /* MECHANISM 4, forward initialization (§3.8.2). ONCE PER SEARCH, off
         * the loop entirely — the emitted hot path is unchanged.
         *
         * `s[startpos-1]` is a byte IN THE SUBJECT and OUTSIDE THE SEARCH
         * WINDOW, which is the whole point: `<prefix>_search` searches
         * `s[startpos, n)`, and a leading `\b` at `startpos` is a question
         * about the byte before it. A constant start state encodes exactly
         * one answer — "the context here is start-of-subject" — which is the
         * assumption a SLICE makes, not the assumption this API's contract
         * makes. MEASURED against libpcre2 10.46: 5 of §3.8.1's 10 cells
         * differ, in both directions, so no conservative shortcut exists.
         *
         * `startpos == 0` genuinely IS start-of-subject, where the constant
         * is right, which is what the ternary's else arm is.
         *
         * THE RANGE GUARD MOVES ABOVE THIS LINE, and it has to: the pre-wave
         * `int st = <const>;` could not read the subject, so `startpos > n`
         * was checked after it. Here the initializer dereferences
         * `s[startpos - 1]`, and on an out-of-range `startpos` that is an
         * out-of-bounds read in EMITTED code — K27's class. With the guard
         * first, `startpos <= n`, and `startpos > 0` then implies `n > 0`,
         * hence `s != NULL` under match_api.md §3.1's legal empty subject. */
        sb_puts(c,   "    if (search_from > subject_length) return 0;\n");
        sb_printf(c, "    int forward_state = search_from ? %s_forward_seed_state[%s_forward_byte_class[subject[search_from - 1]]]"
                     " : %d;\n", p, p, fs);
    } else {
        sb_printf(c, "    int forward_state = %d;\n", fs);
        sb_puts(c,   "    if (search_from > subject_length) return 0;\n");
    }
    sb_puts(c,   "    for (;;) {\n");
    /* Under EOL, scan avoidance must run BEFORE the accept/EOL evaluation, so
     * that evaluation sees the position the loop is really at: a skip bounded
     * at n-1 can LAND on n-1, and evaluating first would consume that byte
     * without ever taking its EOL view (53 divergences, see D11).
     *
     * Without EOL the order is a free choice semantically — every position a
     * skip passes has the same state and so the same accept bit — but NOT a
     * free choice in speed. Hoisting the prefilter above the accept check
     * costs 43% on `[01]*1[01]{8}` (158.4 -> 90.8 MB/s, 0 skip states, tight
     * spreads), so the non-EOL path keeps the original order. This asymmetry
     * is the whole reason the flag exists; do not "simplify" it away. */
    if (!views)
        sb_printf(c, "        if (%s_forward_is_accepting[forward_state]) last_accept_position = scan_position;\n", p);
    {
        const char *kw = "if";
        if (prefilter) {
            /* [M6-READ] The prefilter's own description, emitted HERE because
             * this is where its form is known -- the orientation block names
             * the step and defers to this comment rather than re-deriving
             * `use_memchr` a second time. */
            if (use_memchr) {
                sb_puts(c,   "        // Prefilter: nothing found yet and still at the start, so\n"
                             "        // skip straight to the next byte that could begin a match.\n"
                             "        // Only ");
                legend_byte(c, fcand.byte);
                sb_printf(c, " (%d) can, so one memchr() replaces the steps.\n",
                          fcand.byte);
            }
            else
                sb_puts(c,   "        // Prefilter: nothing found yet and still at the start, so\n"
                             "        // skip over bytes that cannot begin a match rather than\n"
                             "        // stepping through them. can_begin_match says which can.\n");
            sb_printf(c, "        if (forward_state == %d && last_accept_position == (size_t)-1) {\n", fs);
            if (use_memchr) {
                if (views) {
                    /* no early `return 0`: the EOL view may still accept at
                     * n-1 or n, so fall through to the stepped loop instead */
                    sb_puts(c,   "            if (scan_position + 1 < subject_length) {\n");
                    sb_printf(c, "                const void *q = memchr(subject + scan_position, %d, subject_length - 1 - scan_position);\n", fcand.byte);
                    sb_puts(c,   "                scan_position = q ? (size_t)((const unsigned char *)q - subject) : subject_length - 1;\n"
                                 "            }\n");
                } else {
                    /* [K27] The `pos >= n` guard is the FIX, and it is not
                     * defensive padding: docs/spec/match_api.md §3.1 makes
                     * (s == NULL, n == 0) a LEGAL subject, and on it this
                     * line used to call memchr(NULL, c, 0) — technical UB in
                     * EMITTED code, which a user compiling a generated
                     * matcher under their own -fsanitize=undefined sees
                     * pcrec's name on. It changes no answer: memchr over a
                     * zero-length range returns NULL, so the guarded early
                     * `return 0` is exactly the branch the unguarded form
                     * reached one line later. The EOL arm above needs no
                     * such guard — its own `pos + 1 < n` bound already
                     * implies n > 0, hence s != NULL. */
                    sb_puts(c,   "            if (scan_position >= subject_length) return 0;\n");
                    sb_printf(c, "            const void *q = memchr(subject + scan_position, %d, subject_length - scan_position);\n", fcand.byte);
                    sb_puts(c,   "            if (!q) return 0;\n"
                                 "            scan_position = (size_t)((const unsigned char *)q - subject);\n");
                }
            } else {
                sb_printf(c, "            while (%s && !%s_can_begin_match[subject[scan_position]]) scan_position++;\n", fbound, p);
                if (!views) sb_puts(c, "            if (scan_position >= subject_length) return 0;\n");
            }
            sb_puts(c, "        }\n");
            kw = "else if";
        }
        for (int k = 0; k < nfskip; k++) {
            int K = fskip[k];
            sb_printf(c, "        %s (forward_state == %d) {\n", kw, K);
            sb_printf(c, "            while (%s && %s_forward_stay%d[subject[scan_position]]) scan_position++;\n", fbound, p, K);
            /* With the accept check ahead of us (non-EOL order) the skipped
             * run's final position would otherwise go unrecorded; under EOL
             * the check runs after the skip and already covers it. */
            if (!views && fd->st[K].up[UPC_PLAIN].accept)
                sb_puts(c, "            last_accept_position = scan_position;\n");
            sb_puts(c, "        }\n");
            kw = "else if";
        }
    }
    if (viewsel)
        emit_view_select(c, p, eol, endv, "scan_position", "forward_state", "forward_view_state", "forward_eol_view", "forward_end_view",
                         "        ");
    if (views && !facc2)
        sb_printf(c, "        if (%s_forward_is_accepting[%s]) last_accept_position = scan_position;\n", p, fsrc);
    if (facc2) {
        /* §3.6.2's COMPOSITION RULE, and the `pos == n` arm is the half that
         * is easy to get wrong. The accept bit is class-indexed at every
         * position that HAS a next byte and SCALAR at the one that does not:
         * out-of-subject counts as non-word, which is a property of the
         * POSITION, and the base accept already is that bit. Indexing the
         * wide table with some class at `pos == n` would be asking what the
         * accept is when the next byte is "whatever byte happens to sit in
         * that equivalence class", which is meaningless there.
         *
         * The guard is also what makes `s[pos]` below unreachable at
         * `pos == n`. The class is computed ONCE into `cl` and shared with
         * the transition — the byte is read once, and the structural check
         * for this rule has a single named thing to look at rather than an
         * expression to parse. */
        sb_printf(c, "        if (scan_position >= subject_length) {\n"
                     "            if (%s_forward_is_accepting[%s]) last_accept_position = scan_position;\n"
                     "            break;\n"
                     "        }\n", p, fsrc);
        sb_printf(c, "        {\n"
                     "            unsigned forward_class = %s_forward_byte_class[subject[scan_position]];\n"
                     "            if (%s_forward_is_accepting_by_class[%s * %d + forward_class]) last_accept_position = scan_position;\n"
                     "            forward_state = %s_forward_next_state[%s * %d + forward_class];\n"
                     "            scan_position++;\n"
                     "        }\n",
                  p, p, fsrc, fd->ncls, p, fsrc, fd->ncls);
    } else {
        sb_puts(c,   "        if (scan_position >= subject_length) break;\n");
        sb_printf(c, "        forward_state = %s_forward_next_state[%s * %d + %s_forward_byte_class[subject[scan_position++]]];\n",
                  p, fsrc, fd->ncls, p);
    }
    sb_puts(c,   "        if (forward_state < 0) break;   // dead: no match can continue\n"
                 "    }\n"
                 "    if (last_accept_position == (size_t)-1) return 0;\n"
                 "    {\n"
                 "        size_t match_end_position = last_accept_position;\n"
                 "        size_t match_start_position = (size_t)-1;\n"
                 "        size_t rewind_position = match_end_position;\n");
    if (rseed) {
        /* MECHANISM 4, REVERSE INITIALIZATION (§3.8.3). The reverse walk
         * starts at `pp = end` and consumes LEFTWARD, so the byte that seeds
         * a TRAILING `\b`'s context is `s[end]` — one to the RIGHT of where
         * the walk begins, in the subject, and never consumed by the walk at
         * all. That site did not exist before this wave, and it cannot be a
         * compile-time constant the way the forward one nearly was: `end` is
         * produced by the forward loop, so this read is data-dependent and
         * has to happen HERE, after it.
         *
         * `end == n` is the out-of-subject case — no byte to the right —
         * which is a NON-word context and therefore the pre-wave constant. */
        sb_printf(c, "        int reverse_state = (match_end_position < subject_length) ? %s_reverse_seed_state[%s_reverse_byte_class[subject[match_end_position]]]"
                     " : %d;\n", p, p, rs);
    } else {
        sb_printf(c, "        int reverse_state = %d;\n", rs);
    }
    sb_puts(c,   "        for (;;) {\n");
    if (!views)
        sb_printf(c, "            if (%s_reverse_is_accepting[reverse_state]) match_start_position = rewind_position;\n", p);
    {   /* same ordering rule as the forward loop, and
         * `match_start_position` wants the SMALLEST accepting position,
         * which is where a reverse skip stops */
        const char *kw = "if";
        for (int k = 0; k < nrskip; k++) {
            int K = rskip[k];
            /* pp only ever DECREASES, so one entry guard is enough to keep the
             * whole skip below the EOL region */
            sb_printf(c, "            %s (reverse_state == %d%s) {\n", kw, K,
                      views ? " && rewind_position + 1 < subject_length" : "");
            sb_printf(c, "                while (rewind_position > search_from && %s_reverse_stay%d[subject[rewind_position - 1]]) rewind_position--;\n", p, K);
            if (!views && rd->st[K].up[UPC_PLAIN].accept)
                sb_puts(c, "                match_start_position = rewind_position;\n");
            sb_puts(c, "            }\n");
            kw = "else if";
        }
    }
    if (viewsel)
        emit_view_select(c, p, eol, endv, "rewind_position", "reverse_state", "reverse_view_state", "reverse_eol_view", "reverse_end_view",
                         "            ");
    if (views && !racc2)
        sb_printf(c, "            if (%s_reverse_is_accepting[%s]) match_start_position = rewind_position;\n", p, rsrc);
    if (racc2) {
        /* MECHANISM 4, REVERSE TERMINATION (§3.8.3.1) — the site whose
         * absence is a LOST MATCH, and the site whose PLACEMENT is the whole
         * of R30 N9.
         *
         * At `pp == startpos` the walk breaks before ever reading
         * `s[startpos-1]`, so a LEADING `\b`/`\B` at the match start is
         * otherwise evaluated with no left context — the walk silently
         * assuming start-of-subject. `\b` is safe BY ACCIDENT there (its
         * blind assumption coincides with the cases the forward pass lets
         * through), which is exactly why a leading-`\b` sweep reports clean
         * against a design that throws matches away. `\B` inverts it: `\Bfoo`
         * on "xfoo" at startpos 1 is (1,4) in libpcre2 and no-match blind.
         *
         * ATTACHED TO THE BOUNDARY BREAK, NOT A PEELED EPILOGUE BELOW THE
         * LOOP. This loop has TWO exits — this one and the dead-state `rst <
         * 0` below — and code placed after the loop would run on both. On the
         * dead-state exit `pp > startpos` and `rst < 0`, so an epilogue would
         * record `match_start_position` at a position the walk never reached (a WRONG
         * ANSWER, worse than a lost match) and would index the accept table
         * with a NEGATIVE state (an out-of-bounds read in emitted code,
         * K27's class). This arm is entered only when `pp <= startpos` and
         * `rst` is live, so both are unreachable by construction.
         *
         * `pp == startpos` happens exactly once and the loop already tests
         * for it, so this costs one emitted site and ZERO per-byte work.
         *
         * `startpos == 0` is out-of-subject to the left — non-word — hence
         * the SCALAR accept, the mirror of §3.6.2's `pos == n` rule. Note the
         * pleasing asymmetry: the forward machine's terminal boundary needs a
         * scalar accept because no byte exists past `n`; this one needs a
         * CONTEXT-INDEXED accept because the byte exists and is merely
         * outside the window. */
        sb_printf(c, "            if (rewind_position <= search_from) {\n"
                     "                if (search_from ? %s_reverse_is_accepting_by_class[%s * %d + "
                     "%s_reverse_byte_class[subject[search_from - 1]]]\n"
                     "                             : %s_reverse_is_accepting[%s]) match_start_position = rewind_position;\n"
                     "                break;\n"
                     "            }\n",
                  p, rsrc, rd->ncls, p, p, rsrc);
        sb_printf(c, "            {\n"
                     "                unsigned reverse_class = %s_reverse_byte_class[subject[rewind_position - 1]];\n"
                     "                if (%s_reverse_is_accepting_by_class[%s * %d + reverse_class]) match_start_position = rewind_position;\n"
                     "                reverse_state = %s_reverse_next_state[%s * %d + reverse_class];\n"
                     "                rewind_position--;\n"
                     "            }\n",
                  p, p, rsrc, rd->ncls, p, rsrc, rd->ncls);
    } else {
        sb_puts(c,   "            if (rewind_position <= search_from) break;\n");
        sb_printf(c, "            reverse_state = %s_reverse_next_state[%s * %d + %s_reverse_byte_class[subject[--rewind_position]]];\n",
                  p, rsrc, rd->ncls, p);
    }
    sb_puts(c,   "            if (reverse_state < 0) break;\n"
                 "        }\n"
                 "        if (match_start_position == (size_t)-1) return 0;\n"
                 "        if (capture_spans) { capture_spans[0][0] = (ptrdiff_t)match_start_position; capture_spans[0][1] = (ptrdiff_t)match_end_position; }\n"
                 "        return 1;\n"
                 "    }\n"
                 "}\n");
}

/* ---- ENG_ATTEMPT: computed-goto per-start attempt loop ---- */

static void emit_target(StrBuf *c, const char *p, int tgt)
{
    if (tgt < 0) sb_printf(c, "&&%s_dead", p);
    else         sb_printf(c, "&&%s_s%d", p, tgt);
}

static void emit_attempt(Ctx *cx, const char *fn, const char *storage)
{
    Job *job = cx->job;
    Dfa *d = &job->dfa;
    StrBuf *c = &job->csb;
    const char *p = cx->opt->prefix;

    emit_search_head(cx, c, fn, storage);

    if (d->n == 0) {
        /* no live start state: the pattern matches nothing */
        sb_puts(c, "    (void)subject; (void)subject_length; (void)search_from; (void)capture_spans;\n"
                   "    return 0;\n}\n");
        return;
    }

    sb_puts(c, "    /* ---- STATE MACHINE: this engine tries the pattern at one start\n"
               "     * position at a time, and each state is a LABEL rather than a table\n"
               "     * row, so a step is a computed goto.\n"
               "     *\n"
               "     * Byte class of every possible input byte: all 256 values fold into\n"
               "     * the few classes this pattern can tell apart.\n"
               "     *\n");
    emit_class_legend(c, d);
    sb_puts(c, "     */\n");
    emit_u8_table(c, p, "byte_class", d->clsmap, 256);

    /* [M6.2 wave B] this engine's share of §3.6 and §3.8. `acc2` is the
     * class-indexed accept, needed wherever a state's accept depends on the
     * next byte; `seed` is mechanism 4's PER-ATTEMPT start dispatch.
     *
     * ON THIS ENGINE THE SEED IS NOT ONCE PER SEARCH (§3.8.2's own note).
     * ENG_ATTEMPT re-initializes at EVERY attempt — n+1 of them — and only
     * the first begins at `startpos`; the rest begin at `start > startpos`,
     * where the context byte `s[start-1]` is squarely INSIDE the window. So
     * the same dispatch serves both the outside-the-window case this wave
     * exists for and the ordinary interior one, and it composes with the
     * `start == 0` selection this engine already made rather than adding a
     * second. */
    bool acc2 = dfa_has_clsacc(d);
    bool seed = dfa_needs_seed(d);
    /* [M6.2 wave D] TWO questions, not one. `gseed` is "does
     * `start == startpos` differ from `start > startpos` at all"; `gtbl` is
     * "does the `\G` family itself vary with the context byte". Both are
     * needed — `\G\bfoo|bar` has one live interior state for
     * `start > startpos` and three for `start == startpos`, so a single flag
     * emits a constant where a table belongs. */
    bool gseed = dfa_needs_gseed(d);
    /* But `gtbl` is a REFINEMENT of `gseed`, never independent of it, and the
     * `&& gseed` is load-bearing rather than defensive. On a `\G`-free
     * machine `s1g[] == s1u[]` entry for entry, so the loop below answers
     * exactly what `dfa_needs_seed` answers — true on every `\b` and `(?m)`
     * pattern — and without the conjunct those artifacts emit a `gseed[]`
     * table no dispatch ever reads. Found by moving this wave's reference
     * knob to the emitter (see below): with the knob in the analysis both
     * builds emitted the dead table and the byte-identity gate could not see
     * it. */
    bool gtbl = false;
    if (gseed)
        for (int u = UPC_PLAIN + 1; u < UPC_N; u++)
            if (upc_emit_live(u) && d->s1g[u] != d->s1g[UPC_PLAIN]) gtbl = true;
#ifdef PCREC_NO_GSTART
    /* [M6.2 wave D] THE REFERENCE-BUILD KNOB, and its PLACEMENT is the whole
     * point of it. `tests/codegen/run_gstart_identity.sh` builds a compiler
     * with this defined and requires byte-identical output over every
     * `\G`-free corpus pattern; forcing the two flags false HERE makes that
     * build take the pre-wave emitter branches unconditionally, so the
     * reference IS the pre-wave emitter rather than merely an analysis with
     * one fact suppressed.
     *
     * WAVE B's ANALOGOUS KNOB IS PLACED THE OTHER WAY AND THIS WAVE MEASURED
     * WHAT THAT COSTS. `-DPCREC_NO_WORDCTX` pins `has_word` false in
     * `src/ir/dfa.c`, i.e. inside the code a sabotage of that construction
     * edits — and the reference compiler is built from THE SAME (sabotaged)
     * SOURCES. So sabotage S71, which deletes the `if (has_word)` gate on the
     * alphabet refinement, refines in BOTH builds and cancels: measured
     * 2026-08-19, `run_wordctx_identity.sh`'s identity sweep stays
     * 1135/1135 BYTE-IDENTICAL under it, and the script fails only because
     * `has_word` becomes an unused parameter and the reference build emits a
     * warning. That is the project's own recorded check-design failure — a
     * control sharing a source with what it controls — in a new place, and
     * the reason this knob is at the emitter instead. See S71's and S76's
     * annotations; re-placing THOSE two is not this wave's to do.
     *
     * Never defined in a shipped build: under it a `\G` pattern takes the
     * two-way start dispatch, so `\G` can pass only at `start == 0` and
     * compiles to `\A`'s semantics — a WRONG matcher, which is what makes
     * that script's positive control non-vacuous. */
    gseed = false;
    gtbl = false;
#endif
    /* [M6.2 wave C] the class-axis context of a position whose next byte is a
     * newline: the EOL arms below know that byte from their own entry test,
     * so their accept bit is a COMPILE-TIME constant rather than a table read
     * (§3.6.2's composition with the position axis, both indices known). */
    int unl = upc_of_newline(d);
    if (acc2) {
        sb_puts(c, "    /* 1 where a match may end, indexed [state * classes + class]:\n"
                   "     * this machine's accept bit depends on the NEXT byte, so it is a\n"
                   "     * table read rather than a per-state constant. */\n");
        emit_acc_cls_table(c, p, "is_accepting_by_class", d);
    }

    /* [M6-READ] The jump rows are this engine's transition table, one array
     * per state instead of one flat table -- the cells are code ADDRESSES, so
     * a step is an indirect jump rather than a load and a compare. The legend
     * names the states those addresses belong to. */
    sb_printf(c, "    /* Jump targets, one row per state, indexed by byte class.\n"
                 "     * A cell is the label to jump to for that class; %s_dead ends\n"
                 "     * the attempt. %d states, %d classes.\n"
                 "     *\n", p, d->n, d->ncls);
    emit_state_legend(c, d, false);
    sb_puts(c, "     */\n");
    for (int i = 0; i < d->n; i++) {
        sb_printf(c, "    static const void *const %s_targets_%d[%d] = { ",
                  p, i, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->st[i].tr[cl]);
        }
        sb_puts(c, " };\n");
    }
    if (seed) {
        sb_printf(c, "    static const void *const %s_seed_state[%d] = { ",
                  p, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->s1u[upc_emit_of_class(d, cl)]);
        }
        sb_puts(c, " };\n");
    }
    /* [M6.2 wave D] `\G`'s own seed table, and it is gated on the `\G` FAMILY
     * varying rather than on `seed`. The two questions are genuinely
     * independent: `\G\bfoo|bar` has one interior state for `start >
     * startpos` (only the `bar` branch survives, and it reads no byte to its
     * left) and three for `start == startpos` (where the `\b` is live). A
     * single `seed` flag would emit a constant where a table is needed. */
    if (gtbl) {
        sb_printf(c, "    static const void *const %s_gstart_seed_state[%d] = { ",
                  p, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->s1g[upc_emit_of_class(d, cl)]);
        }
        sb_puts(c, " };\n");
    }

    /* [D63] THE CANDIDATE-START PREFILTER, this engine's first instance.
     * Derived by the shared helper; only the LOOP INTEGRATION is here. */
    CandSet cand;
    bool cpre = attempt_cand(d, &cand);

    /* anchored fast path (M2.1): if every interior start state is dead, every
     * branch requires ^, so only start == 0 can ever match.
     * [M6.2 wave B] there is now more than one interior start state, and the
     * fast path needs ALL of them dead — `(?:^|\b)x` has a live one and a
     * dead one. [M6.2 wave C] `(?m)^x` has exactly one live (the newline
     * context), which is what D63's candidate prefilter above is for: the
     * fast path does not apply, and every attempt but the line starts is
     * still provably dead. */
    /* [M6.2 wave D] `start_max` IS A THIRD VALUE NOW, not a wrap toggle
     * (assertions_design.md §4.1, which is DD-4's substantive answer). Read
     * the two interior families together:
     *
     *   s1u dead, s1g dead   every branch needs `^`     -> start_max = 0
     *   s1u dead, s1g LIVE   every branch needs `\G`    -> start_max = startpos
     *   s1u live             something can start later  -> start_max = n
     *
     * The middle row is `\G`'s whole engine cost: ONE attempt, at exactly the
     * position `\G` names, so a `\G`-anchored pattern is O(n) trivially and
     * needs neither a new engine nor `engine_m4.md` §7.3's toggle on
     * `nfa_wrap_unanchored`. ENG_ATTEMPT was already emitting the
     * un-self-looped shape.
     *
     * On a `\G`-free machine `s1g[] == s1u[]` entry for entry, so the middle
     * row is unreachable and the two surviving rows are the pre-wave
     * `anchored ? "0" : "n"` character for character. */
    bool a_bot = dfa_interior_dead(d->s1u);
    bool a_gst = dfa_interior_dead(d->s1g);
#ifdef PCREC_NO_GSTART
    a_gst = a_bot;   /* the reference build's third `start_max` string is
                      * unreachable — see the knob's comment above */
#endif
    bool anchored = a_bot && a_gst;
    sb_printf(c, "    size_t start;\n"
                 "    const size_t start_max = %s;\n",
              anchored ? "0 /* fully ^-anchored */"
                       : a_bot ? "search_from /* fully \\G-anchored */" : "subject_length");
    sb_puts(c, "    for (start = search_from; start <= start_max; start++) {\n");
    if (cpre) {
        /* [D63] LOOP INTEGRATION, ENG_ATTEMPT's shape: an advance BETWEEN
         * attempts, not a skip inside one. It composes with the three-way
         * start dispatch below rather than replacing it — the dispatch still
         * decides WHICH start state an attempt enters; this only skips the
         * starts whose state would be the dead one.
         *
         * `start == 0` is never skipped: it enters `s0`, which this
         * derivation says nothing about (assertions_design.md §3.7.2's
         * "offset 0 or immediately after a newline" is exactly the shape of
         * the two branches here).
         *
         * SOUNDNESS is by construction rather than by argument: a skipped
         * `start` would have jumped straight to the dead label and fallen
         * through `%s_done` with `last == (size_t)-1`, i.e. done nothing at
         * all. This is the one scan-avoidance mechanism in the file that
         * needs no D11 bound, because it skips whole ATTEMPTS rather than
         * positions within a scan, and an attempt records nothing until it
         * runs.
         *
         * THE GUARD READS `s[start - offset]`, IN RANGE BECAUSE `offset >= 1`
         * here: a predecessor-byte candidate set (D63's one new case) and
         * `start > 0` together put that read at `start - 1 <= n - 1`. A
         * future ENG_ATTEMPT caller with `offset == 0` would be reading
         * `s[start]` and needs its own `start < n` bound — which is exactly
         * why the derivation carries `offset` as data instead of the two
         * shapes being two functions.
         *
         * The MEASURED target is the linear non-crossing arm (§3.7.2, R30
         * N3): `(?m)^ERROR` dies in a byte or two per attempt, so the cost is
         * visiting every offset, and this is what removes it. The quadratic
         * crossing arm (§3.7.1) is NOT rescued and D63 accepts that —
         * DD-7's reverse BOT variant is the sequenced fix.
         *
         * [M6.2 wave D] THE LOWER BOUND IS `startpos`, NOT 0, WHENEVER THE
         * MACHINE HAS A `\G` FAMILY — and getting this wrong is a lost match,
         * not a slow one. The derivation reads `s1u[]`, the states an attempt
         * at `start > startpos` enters; the attempt at `start == startpos`
         * enters `s1g[]` instead, which the derivation never looked at. So a
         * pattern with a `(?m)^` branch AND a `\G` branch — `(?m)^a|\Gb`,
         * whose candidate set is the newline definition — would have had its
         * `\G` attempt skipped at any `startpos` not preceded by a newline.
         * `start > startpos` implies `start > 0`, so the bound is a
         * STRENGTHENING of the existing guard rather than a second condition,
         * and every position the skip then passes over is one this
         * derivation's domain covers. Sabotage S82 restores `start > 0`. */
        sb_printf(c, "        if (start > %s && subject[start - %d] != %d) {\n"
                         "            const void *q = memchr(subject + start, %d, "
                         "subject_length - start);\n"
                         "            if (!q) break;\n"
                         "            start = (size_t)"
                         "((const unsigned char *)q - subject) + %d;\n"
                         "        }\n",
                  gseed ? "search_from" : "0",
                  cand.offset, cand.byte, cand.byte, cand.offset);
    }
    sb_puts(c, "        size_t scan_position = start;\n"
               "        size_t last_accept_position = (size_t)-1;\n");

    /* [M6.2 wave D] THE START DISPATCH IS THREE-WAY WHEN `\G` IS PRESENT
     * (assertions_design.md §4.2's table), and the three cases are exactly
     * its three reachable rows:
     *
     *     start == 0          -> s0     (`\A` and `\G` both pass)
     *     start == startpos   -> s1g[]  (`\G` only)
     *     start >  startpos   -> s1u[]  (neither)
     *
     * `start == 0` is tested FIRST and that ordering is load-bearing: it is
     * the row where BOTH hold, and testing `start == startpos` first would
     * route offset 0 into the `\G`-only state and lose every `\A`/`^` branch.
     *
     * The `\G`-free path below is the pre-wave code untouched, three branches
     * and all — the same one-branch-that-reproduces-the-old-string discipline
     * `emit_view_select` is written with, for the same reason. */
    if (gseed) {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_puts(c, "\n               : (start == search_from) ? ");
        if (gtbl) sb_printf(c, "%s_gstart_seed_state[%s_byte_class[subject[start - 1]]]", p, p);
        else      emit_target(c, p, d->s1g[UPC_PLAIN]);
        sb_puts(c, "\n               : ");
        if (seed) sb_printf(c, "%s_seed_state[%s_byte_class[subject[start - 1]]]", p, p);
        else      emit_target(c, p, d->s1u[UPC_PLAIN]);
        sb_puts(c, ");\n");
    } else if (seed) {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_printf(c, " : %s_seed_state[%s_byte_class[subject[start - 1]]]);\n", p, p);
    } else if (d->s0 == d->s1u[UPC_PLAIN]) {
        sb_puts(c, "        goto ");
        if (d->s0 < 0) sb_printf(c, "*&&%s_dead;\n", p);
        else           sb_printf(c, "*&&%s_s%d;\n", p, d->s0);
    } else {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_puts(c, " : ");
        emit_target(c, p, d->s1u[UPC_PLAIN]);
        sb_puts(c, ");\n");
    }

    for (int i = 0; i < d->n; i++) {
        const DState *st = &d->st[i];
        /* labels marked unused: EOL-variant states are entered via their
         * transition tables only, never their own label */
        sb_printf(c, "%s_s%d: __attribute__((unused));\n", p, i);
        /* [M6.2 wave B] Does THIS state's accept depend on the next byte? A
         * per-state question, not a per-artifact one: a `\b` pattern's
         * artifact typically has a handful of such states and keeps the
         * pre-wave text at every other, which is what makes the byte-identity
         * property hold at state granularity rather than at file granularity. */
        bool wsplit = acc2 && state_acc_varies(st);
        if (wsplit) {
            /* THE ORDER FLIPS, and it has to. The pre-wave arms record the
             * accept and THEN test for `pos >= n`, which is sound while the
             * accept bit is a scalar; here the bit at `pos < n` is a function
             * of `s[pos]`, so the end-of-subject case has to be split off
             * first — it is the one position with no next byte, where §3.6.2
             * makes the accept SCALAR. That test is also what makes the
             * `s[pos]` below unreachable at `pos == n`. */
            int endview = st_emit_endvar(st) >= 0 ? st_emit_endvar(st)
                        : st->eolvar >= 0 ? st->eolvar : i;
            sb_puts(c, "        if (scan_position == subject_length) {\n");
            if (d->st[endview].up[UPC_PLAIN].accept)
                sb_puts(c, "            last_accept_position = scan_position;\n");
            sb_printf(c, "            goto %s_done;\n        }\n", p);
            if (st->eolvar >= 0) {
                /* [M6.2 wave C] THE EOL POSITION'S ACCEPT IS CLASS-INDEXED
                 * TOO, and wave B's note here said otherwise. Its reasoning
                 * was right for its own axis and its conclusion is now wrong:
                 * the byte at an EOL position is `\n`, which is indeed not a
                 * word character — so the WORD axis has nothing to add — but
                 * it IS the newline definition, which is precisely what
                 * `(?m)$` reads. `(?m)a(?:$|\Z)` is the shape that needs
                 * both: the `\Z` half makes an EOL view exist, and the
                 * `(?m)$` half makes that view's accept depend on the very
                 * byte the arm's entry test just pinned.
                 *
                 * Pinned, not read: both indices are compile-time facts here
                 * (the view from the position, the class from the arm's own
                 * `s[pos] == newline` test), so this is a constant, not a
                 * table lookup. `unl` is UPC_PLAIN on any machine without a
                 * newline refinement, which is what keeps the pre-wave text
                 * byte-identical. */
                const DState *v = &d->st[st->eolvar];
                sb_puts(c, "        if (scan_position + 1 == subject_length && subject[scan_position] == '\\n') {\n");
                if (v->up[unl].accept) sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            sb_printf(c, "        {\n"
                         "            unsigned forward_class = %s_byte_class[subject[scan_position]];\n"
                         "            if (%s_is_accepting_by_class[%d + forward_class]) last_accept_position = scan_position;\n"
                         "            scan_position++;\n"
                         "            goto *%s_targets_%d[forward_class];\n"
                         "        }\n",
                      p, p, i * d->ncls, p, i);
        } else if (st_emit_endvar(st) >= 0) {
            /* [M6.2 wave A] THE END VIEW (`\z`), reached on ENG_ATTEMPT only
             * when the pattern also carries a `^`/`\A` — `\Aa\z` is the
             * shape. Three arms in position order, most specific first:
             * `pos == n` takes the END view (and then there is no byte to
             * consume, so it always leaves), `pos + 1 == n && s[pos] == '\n'`
             * takes the EOL view, and everything else is the state itself.
             *
             * A state only reaches this branch when its END view DIFFERS from
             * its EOL view (`endvar >= 0` means exactly that, src/ir/dfa.c) —
             * which is why the `endvar < 0` else-branch below is still the
             * pre-wave text, unchanged, for every state of every pattern that
             * has no `\z`. */
            const DState *endv = &d->st[st_emit_endvar(st)];
            sb_puts(c, "        if (scan_position == subject_length) {\n");
            if (endv->up[UPC_PLAIN].accept)
                sb_puts(c, "            last_accept_position = scan_position;\n");
            sb_printf(c, "            goto %s_done;\n", p);
            sb_puts(c, "        }\n");
            if (st->eolvar >= 0) {
                const DState *v = &d->st[st->eolvar];
                sb_puts(c, "        if (scan_position + 1 == subject_length && subject[scan_position] == '\\n') {\n");
                if (v->up[unl].accept)
                    sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last_accept_position = scan_position;\n");
            /* both arms above returned or consumed, so pos < n here */
            sb_printf(c, "        goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n", p, i, p);
        } else if (st->eolvar >= 0) {
            const DState *v = &d->st[st->eolvar];
            /* at an EOL position ($ passable), use the EOL-view state:
             * its accept is correctly priority-pruned and its table
             * carries the $-gated continuations.
             *
             * [M6.2 wave C] THE TWO EOL POSITIONS CAN CARRY DIFFERENT ACCEPT
             * BITS and the pre-wave text merged them into one arm. They are
             * `pos == n` (no next byte: §3.6.2's SCALAR accept) and
             * `pos + 1 == n && s[pos] == '\n'` (next byte pinned to the
             * newline definition), and until `(?m)$` existed nothing could
             * tell them apart, because the EOL view's accept did not depend
             * on the next byte at all. `(?m)a$` on `"a\n"` is the witness:
             * the view accepts at the newline position and the merged arm
             * would have had to answer for both with one bit.
             *
             * The arms only SPLIT when the two bits differ, so a machine with
             * no newline refinement (`unl == UPC_PLAIN`) emits the pre-wave
             * text character for character. */
            bool a_end = v->up[UPC_PLAIN].accept;
            bool a_nl  = v->up[unl].accept;
            if (a_end == a_nl) {
                sb_puts(c, "        if (scan_position == subject_length || (scan_position + 1 == subject_length && "
                           "subject[scan_position] == '\\n')) {\n");
                if (a_end)
                    sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            if (scan_position >= subject_length) goto %s_done;\n", p);
                sb_printf(c, "            goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            } else {
                sb_puts(c, "        if (scan_position == subject_length) {\n");
                if (a_end)
                    sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            goto %s_done;\n        }\n", p);
                sb_puts(c, "        if (scan_position + 1 == subject_length && subject[scan_position] == '\\n') {\n");
                if (a_nl)
                    sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last_accept_position = scan_position;\n");
            /* not an EOL position implies pos < n: consume directly */
            sb_printf(c, "        goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n", p, i, p);
        } else {
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last_accept_position = scan_position;\n");
            sb_printf(c, "        if (scan_position >= subject_length) goto %s_done;\n", p);
            sb_printf(c, "        goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n", p, i, p);
        }
    }

    sb_printf(c, "%s_dead: __attribute__((unused));\n", p);
    sb_printf(c, "%s_done:\n", p);
    sb_puts(c, "        if (__builtin_expect(last_accept_position != (size_t)-1, 0)) {\n"
               "            if (capture_spans) { capture_spans[0][0] = (ptrdiff_t)start; capture_spans[0][1] = (ptrdiff_t)last_accept_position; }\n"
               "            return 1;\n"
               "        }\n"
               "    }\n"
               "    return 0;\n"
               "}\n");
}

