/* ---- THE DERIVATION: one machine's whole form, selected once ------------ */

static void dfa_form_derive(Ctx *cx, const Dfa *d, const UnanchStart *us,
                            const DfaDir *dir, DfaForm *f)
{
    DfaSel s = { cx, d, us, !dir->reverse };
    unsigned flags = cx->opt->flags;

    memset(f, 0, sizeof *f);
    f->cx      = cx;
    f->d       = d;
    f->p       = cx->opt->prefix;
    f->dir     = dir;
    f->repr    = DFA_SELECT(DfaRepr, dfa_reprs, &s, flags);
    f->view    = DFA_SELECT(DfaView, dfa_views, &s, flags);
    f->seed    = DFA_SELECT(DfaSeed, dfa_seeds, &s, flags);
    f->acc     = DFA_SELECT(DfaAcc,  dfa_accs,  &s, flags);
    /* The prefilter is the FORWARD scan's, and that is a clause in each
     * candidate's `applies` rather than a branch here: the reverse machine
     * walks a range the forward scan already proved contains a match, so
     * every real form declines and the list's total fallback `none` — a real
     * object with a NULL emitter — is what it selects. */
    f->pf      = DFA_SELECT(DfaPf, dfa_pfs, &s, flags);
    f->views   = us->views;
    f->viewsel = us->viewsel;
    f->src     = us->viewsel ? dir->viewv : dir->statev;
    f->cand    = us->cand;
    f->ofsk    = &us->ofsk;
    /* The forward machine never skips out of its own start state — the
     * prefilter owns that position. */
    f->nskip   = pick_skip_states(d, dir->reverse ? -1 : d->s0, f->skip);
}

/* ---- THE TABLES, one path called twice ---------------------------------- */

static void emit_machine_tables(StrBuf *c, const DfaForm *f)
{
    const char *p = f->p, *m = f->dir->c.name;
    char tag[PCREC_MAX_EMIT_NAME_LEN];

    /* [M6-READ] The tables are the artifact's data structures, and each gets
     * a block comment: what it is, how it is indexed, what a cell means, and
     * — where the cells are STATES — a legend naming them. */
    sb_puts(c, f->dir->tbl_hdr);
    emit_class_legend(c, f->d);
    sb_puts(c, "     */\n");
    snprintf(tag, sizeof tag, "%s_byte_class", m);
    emit_u8_table(c, p, tag, f->d->clsmap, 256);

    f->repr->emit_tr_comment(c, f);
    emit_state_legend(c, f->d, f->dir->reverse);
    sb_puts(c, "     */\n");
    snprintf(tag, sizeof tag, "%s_next_state", m);
    emit_tr_table(c, p, tag, f->d, f->repr);

    f->repr->emit_acc_comment(c, f);
    snprintf(tag, sizeof tag, "%s_is_accepting", m);
    emit_acc_table(c, p, tag, f->d, f->repr);

    if (f->acc->wide_table) {
        snprintf(tag, sizeof tag, "%s_is_accepting_by_class", m);
        emit_acc_cls_table(c, p, tag, f->d);
    }
    if (f->seed->table) {
        snprintf(tag, sizeof tag, "%s_seed_state", m);
        emit_seed_table(c, p, tag, f->d, f->d->s1u, f->repr);
    }
    if (f->viewsel) {
        /* The two view tables exist independently of which SELECTOR the
         * machine took: `end+eol` needs both, `eol`/`end` one each. The
         * object's name is the authority on which. */
        if (strcmp(f->view->c.name, "end")) {
            snprintf(tag, sizeof tag, "%s_eol_view", m);
            emit_eol_table(c, p, tag, f->d, f->repr);
        }
        if (strcmp(f->view->c.name, "eol")) {
            snprintf(tag, sizeof tag, "%s_end_view", m);
            emit_end_table(c, p, tag, f->d, f->repr);
        }
    }
    if (f->pf->emit_tables) f->pf->emit_tables(c, f);
    snprintf(tag, sizeof tag, "%s_stay", m);
    for (int k = 0; k < f->nskip; k++)
        emit_stay_table(c, p, tag, f->skip[k], f->d);
}

/* ---- THE SCAN LOOP, emitted ONCE and called twice ----------------------- */

static void emit_scan_loop(StrBuf *c, const DfaForm *f)
{
    const char *ind = f->dir->ind;

    f->seed->emit_init(c, f);
    sb_printf(c, "%sfor (;;) {\n", ind);
    /* THE EVALUATION ORDER IS AN AXIS, not a tidiness question. Under a view,
     * scan avoidance must run BEFORE the accept evaluation, so that
     * evaluation sees the position the loop is really at: a skip bounded at
     * n-1 can LAND on n-1, and evaluating first would consume that byte
     * without ever taking its view (53 divergences, D11).
     *
     * Without a view the order is a free choice SEMANTICALLY — every position
     * a skip passes has the same state and so the same accept bit — but NOT a
     * free choice in speed. Hoisting the prefilter above the accept check
     * costs 43% on `[01]*1[01]{8}` (158.4 -> 90.8 MB/s, 0 skip states, tight
     * spreads). That asymmetry is the whole reason axis E has a
     * `scalar-plain` object distinct from `scalar-viewed`; do not "simplify"
     * the two into one. */
    if (f->acc->emit_top) f->acc->emit_top(c, f);
    if (f->pf->emit) f->pf->emit(c, f);
    {
        const char *kw = f->pf->emit ? "else if" : "if";
        for (int k = 0; k < f->nskip; k++) {
            f->dir->emit_skip(c, f, f->skip[k], kw);
            kw = "else if";
        }
    }
    if (f->view->emit) f->view->emit(c, f);
    if (f->acc->emit_after_view) f->acc->emit_after_view(c, f);
    f->acc->emit_tail(c, f);
    sb_printf(c, "%s    if (%s_%s_is_dead(%s)) break;   // dead: no match can continue\n",
              ind, f->p, f->dir->c.name, f->dir->statev);
    sb_printf(c, "%s}\n", ind);
}

/* ---- ENG_UNANCH: the assembly ------------------------------------------- */

static void emit_unanchored(Ctx *cx, const char *fn, const char *storage)
{
    Job *job = cx->job;
    StrBuf *c = &job->csb;

    /* [DD-13] THE START ANALYSIS IS `unanch_start`'s, not this function's:
     * the view flags, the candidate set and the prefilter verdict are all
     * read a SECOND time by the artifact's `<PREFIX>_DFA_PREFILTER` stamp,
     * and that function's header states why they may not be derived twice. */
    UnanchStart us;
    unanch_start(cx, &us);

    /* [DD-13] THE ONE EMPTY-ENGINE EXIT, and it is taken BEFORE any token
     * block is emitted so an artifact that matches nothing grows nothing. */
    if (us.empty) {
        emit_search_head(cx, c, fn, storage);
        sb_puts(c, "    (void)subject; (void)subject_length; (void)search_from; (void)capture_spans;\n"
                   "    return 0;\n}\n");
        return;
    }

    DfaForm fwd, rev;
    dfa_form_derive(cx, &job->dfa,  &us, &dfa_dir_forward, &fwd);
    dfa_form_derive(cx, &job->rdfa, &us, &dfa_dir_reverse, &rev);

    /* LAYER 2, at file scope and above the body: the two accessor blocks,
     * and — [OPT-K] — the forward prefilter's own block where its form has
     * one. Same place, same reason: the VM hybrid inlines this emitter's
     * output, so a block emitted here is a block the hybrid gets. */
    fwd.repr->emit_token(c, &fwd);
    rev.repr->emit_token(c, &rev);
    if (fwd.pf->emit_block) fwd.pf->emit_block(c, &fwd);

    emit_search_head(cx, c, fn, storage);
    emit_machine_tables(c, &fwd);
    emit_machine_tables(c, &rev);

    sb_puts(c, "    // ---- FORWARD SCAN: where does a match end? ----------------\n"
               "    // One byte per iteration. The loop keeps the LAST accepting\n"
               "    // position rather than stopping at the first, so the longest\n"
               "    // match wins.\n"
               "    size_t scan_position = search_from;\n"
               "    size_t last_accept_position = (size_t)-1;\n");
    emit_scan_loop(c, &fwd);
    sb_puts(c, "    if (last_accept_position == (size_t)-1) return 0;\n"
               "    {\n"
               "        size_t match_end_position = last_accept_position;\n"
               "        size_t match_start_position = (size_t)-1;\n"
               "        size_t rewind_position = match_end_position;\n");
    emit_scan_loop(c, &rev);
    sb_puts(c, "        if (match_start_position == (size_t)-1) return 0;\n"
               "        if (capture_spans) { capture_spans[0][0] = (ptrdiff_t)match_start_position; capture_spans[0][1] = (ptrdiff_t)match_end_position; }\n"
               "        return 1;\n"
               "    }\n"
               "}\n");
}

/* ---- ENG_ATTEMPT: computed-goto per-start attempt loop ---- */

static void emit_target(StrBuf *c, const char *p, int tgt)
{
    if (tgt < 0) sb_printf(c, "&&%s_dead", p);
    else         sb_printf(c, "&&%s_s%d", p, tgt);
}

static void emit_attempt(Ctx *cx, const char *fn, const char *storage)
{
    Job *job = cx->job;
    Dfa *d = &job->dfa;
    StrBuf *c = &job->csb;
    const char *p = cx->opt->prefix;

    emit_search_head(cx, c, fn, storage);

    /* [DD-13c] THE EMPTY ENGINE, through the SHARED derivation. The condition
     * used to be `d->n == 0` spelled here; it is `dfa_engine_is_empty`'s now,
     * because `<PREFIX>_DFA_SCAN "empty"` is read off the same function and a
     * second copy of the condition is how a stamp and its body drift apart
     * (this file's header, M2.12). Byte-for-byte the same output. */
    if (dfa_engine_is_empty(cx)) {
        /* no live start state: the pattern matches nothing */
        sb_puts(c, "    (void)subject; (void)subject_length; (void)search_from; (void)capture_spans;\n"
                   "    return 0;\n}\n");
        return;
    }

    sb_puts(c, "    /* ---- STATE MACHINE: this engine tries the pattern at one start\n"
               "     * position at a time, and each state is a LABEL rather than a table\n"
               "     * row, so a step is a computed goto.\n"
               "     *\n"
               "     * Byte class of every possible input byte: all 256 values fold into\n"
               "     * the few classes this pattern can tell apart.\n"
               "     *\n");
    emit_class_legend(c, d);
    sb_puts(c, "     */\n");
    emit_u8_table(c, p, "byte_class", d->clsmap, 256);

    /* [M6.2 wave B] this engine's share of §3.6 and §3.8. `acc2` is the
     * class-indexed accept, needed wherever a state's accept depends on the
     * next byte; `seed` is mechanism 4's PER-ATTEMPT start dispatch.
     *
     * ON THIS ENGINE THE SEED IS NOT ONCE PER SEARCH (§3.8.2's own note).
     * ENG_ATTEMPT re-initializes at EVERY attempt — n+1 of them — and only
     * the first begins at `startpos`; the rest begin at `start > startpos`,
     * where the context byte `s[start-1]` is squarely INSIDE the window. So
     * the same dispatch serves both the outside-the-window case this wave
     * exists for and the ordinary interior one, and it composes with the
     * `start == 0` selection this engine already made rather than adding a
     * second. */
    bool acc2 = dfa_has_clsacc(d);
    bool seed = dfa_needs_seed(d);
    /* [M6.2 wave D] TWO questions, not one. `gseed` is "does
     * `start == startpos` differ from `start > startpos` at all"; `gtbl` is
     * "does the `\G` family itself vary with the context byte". Both are
     * needed — `\G\bfoo|bar` has one live interior state for
     * `start > startpos` and three for `start == startpos`, so a single flag
     * emits a constant where a table belongs. */
    bool gseed = dfa_needs_gseed(d);
    /* But `gtbl` is a REFINEMENT of `gseed`, never independent of it, and the
     * `&& gseed` is load-bearing rather than defensive. On a `\G`-free
     * machine `s1g[] == s1u[]` entry for entry, so the loop below answers
     * exactly what `dfa_needs_seed` answers — true on every `\b` and `(?m)`
     * pattern — and without the conjunct those artifacts emit a `gseed[]`
     * table no dispatch ever reads. Found by moving this wave's reference
     * knob to the emitter (see below): with the knob in the analysis both
     * builds emitted the dead table and the byte-identity gate could not see
     * it. */
    bool gtbl = false;
    if (gseed)
        for (int u = UPC_PLAIN + 1; u < UPC_N; u++)
            if (upc_emit_live(u) && d->s1g[u] != d->s1g[UPC_PLAIN]) gtbl = true;
#ifdef PCREC_NO_GSTART
    /* [M6.2 wave D] THE REFERENCE-BUILD KNOB, and its PLACEMENT is the whole
     * point of it. `tests/codegen/run_gstart_identity.sh` builds a compiler
     * with this defined and requires byte-identical output over every
     * `\G`-free corpus pattern; forcing the two flags false HERE makes that
     * build take the pre-wave emitter branches unconditionally, so the
     * reference IS the pre-wave emitter rather than merely an analysis with
     * one fact suppressed.
     *
     * WAVE B's ANALOGOUS KNOB IS PLACED THE OTHER WAY AND THIS WAVE MEASURED
     * WHAT THAT COSTS. `-DPCREC_NO_WORDCTX` pins `has_word` false in
     * `src/ir/dfa.c`, i.e. inside the code a sabotage of that construction
     * edits — and the reference compiler is built from THE SAME (sabotaged)
     * SOURCES. So sabotage S71, which deletes the `if (has_word)` gate on the
     * alphabet refinement, refines in BOTH builds and cancels: measured
     * 2026-08-19, `run_wordctx_identity.sh`'s identity sweep stays
     * 1135/1135 BYTE-IDENTICAL under it, and the script fails only because
     * `has_word` becomes an unused parameter and the reference build emits a
     * warning. That is the project's own recorded check-design failure — a
     * control sharing a source with what it controls — in a new place, and
     * the reason this knob is at the emitter instead. See S71's and S76's
     * annotations; re-placing THOSE two is not this wave's to do.
     *
     * Never defined in a shipped build: under it a `\G` pattern takes the
     * two-way start dispatch, so `\G` can pass only at `start == 0` and
     * compiles to `\A`'s semantics — a WRONG matcher, which is what makes
     * that script's positive control non-vacuous. */
    gseed = false;
    gtbl = false;
#endif
    /* [M6.2 wave C] the class-axis context of a position whose next byte is a
     * newline: the EOL arms below know that byte from their own entry test,
     * so their accept bit is a COMPILE-TIME constant rather than a table read
     * (§3.6.2's composition with the position axis, both indices known). */
    int unl = upc_of_newline(d);
    if (acc2) {
        sb_puts(c, "    /* 1 where a match may end, indexed [state * classes + class]:\n"
                   "     * this machine's accept bit depends on the NEXT byte, so it is a\n"
                   "     * table read rather than a per-state constant. */\n");
        emit_acc_cls_table(c, p, "is_accepting_by_class", d);
    }

    /* [M6-READ] The jump rows are this engine's transition table, one array
     * per state instead of one flat table -- the cells are code ADDRESSES, so
     * a step is an indirect jump rather than a load and a compare. The legend
     * names the states those addresses belong to. */
    sb_printf(c, "    /* Jump targets, one row per state, indexed by byte class.\n"
                 "     * A cell is the label to jump to for that class; %s_dead ends\n"
                 "     * the attempt. %d states, %d classes.\n"
                 "     *\n", p, d->n, d->ncls);
    emit_state_legend(c, d, false);
    sb_puts(c, "     */\n");
    for (int i = 0; i < d->n; i++) {
        sb_printf(c, "    static const void *const %s_targets_%d[%d] = { ",
                  p, i, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->st[i].tr[cl]);
        }
        sb_puts(c, " };\n");
    }
    if (seed) {
        sb_printf(c, "    static const void *const %s_seed_state[%d] = { ",
                  p, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->s1u[upc_emit_of_class(d, cl)]);
        }
        sb_puts(c, " };\n");
    }
    /* [M6.2 wave D] `\G`'s own seed table, and it is gated on the `\G` FAMILY
     * varying rather than on `seed`. The two questions are genuinely
     * independent: `\G\bfoo|bar` has one interior state for `start >
     * startpos` (only the `bar` branch survives, and it reads no byte to its
     * left) and three for `start == startpos` (where the `\b` is live). A
     * single `seed` flag would emit a constant where a table is needed. */
    if (gtbl) {
        sb_printf(c, "    static const void *const %s_gstart_seed_state[%d] = { ",
                  p, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->s1g[upc_emit_of_class(d, cl)]);
        }
        sb_puts(c, " };\n");
    }

    /* [D63] THE CANDIDATE-START PREFILTER, this engine's first instance.
     * Derived by the shared helper; only the LOOP INTEGRATION is here. */
    CandSet cand;
    bool cpre = attempt_cand(d, &cand);

    /* anchored fast path (M2.1): if every interior start state is dead, every
     * branch requires ^, so only start == 0 can ever match.
     * [M6.2 wave B] there is now more than one interior start state, and the
     * fast path needs ALL of them dead — `(?:^|\b)x` has a live one and a
     * dead one. [M6.2 wave C] `(?m)^x` has exactly one live (the newline
     * context), which is what D63's candidate prefilter above is for: the
     * fast path does not apply, and every attempt but the line starts is
     * still provably dead. */
    /* [M6.2 wave D] `start_max` IS A THIRD VALUE NOW, not a wrap toggle
     * (assertions_design.md §4.1, which is DD-4's substantive answer). Read
     * the two interior families together:
     *
     *   s1u dead, s1g dead   every branch needs `^`     -> start_max = 0
     *   s1u dead, s1g LIVE   every branch needs `\G`    -> start_max = startpos
     *   s1u live             something can start later  -> start_max = n
     *
     * The middle row is `\G`'s whole engine cost: ONE attempt, at exactly the
     * position `\G` names, so a `\G`-anchored pattern is O(n) trivially and
     * needs neither a new engine nor `engine_m4.md` §7.3's toggle on
     * `nfa_wrap_unanchored`. ENG_ATTEMPT was already emitting the
     * un-self-looped shape.
     *
     * On a `\G`-free machine `s1g[] == s1u[]` entry for entry, so the middle
     * row is unreachable and the two surviving rows are the pre-wave
     * `anchored ? "0" : "n"` character for character. */
    bool a_bot = dfa_interior_dead(d->s1u);
    bool a_gst = dfa_interior_dead(d->s1g);
#ifdef PCREC_NO_GSTART
    a_gst = a_bot;   /* the reference build's third `start_max` string is
                      * unreachable — see the knob's comment above */
#endif
    bool anchored = a_bot && a_gst;
    sb_printf(c, "    size_t start;\n"
                 "    const size_t start_max = %s;\n",
              anchored ? "0 /* fully ^-anchored */"
                       : a_bot ? "search_from /* fully \\G-anchored */" : "subject_length");
    sb_puts(c, "    for (start = search_from; start <= start_max; start++) {\n");
    if (cpre) {
        /* [D63] LOOP INTEGRATION, ENG_ATTEMPT's shape: an advance BETWEEN
         * attempts, not a skip inside one. It composes with the three-way
         * start dispatch below rather than replacing it — the dispatch still
         * decides WHICH start state an attempt enters; this only skips the
         * starts whose state would be the dead one.
         *
         * `start == 0` is never skipped: it enters `s0`, which this
         * derivation says nothing about (assertions_design.md §3.7.2's
         * "offset 0 or immediately after a newline" is exactly the shape of
         * the two branches here).
         *
         * SOUNDNESS is by construction rather than by argument: a skipped
         * `start` would have jumped straight to the dead label and fallen
         * through `%s_done` with `last == (size_t)-1`, i.e. done nothing at
         * all. This is the one scan-avoidance mechanism in the file that
         * needs no D11 bound, because it skips whole ATTEMPTS rather than
         * positions within a scan, and an attempt records nothing until it
         * runs.
         *
         * THE GUARD READS `s[start - offset]`, IN RANGE BECAUSE `offset >= 1`
         * here: a predecessor-byte candidate set (D63's one new case) and
         * `start > 0` together put that read at `start - 1 <= n - 1`. A
         * future ENG_ATTEMPT caller with `offset == 0` would be reading
         * `s[start]` and needs its own `start < n` bound — which is exactly
         * why the derivation carries `offset` as data instead of the two
         * shapes being two functions.
         *
         * The MEASURED target is the linear non-crossing arm (§3.7.2, R30
         * N3): `(?m)^ERROR` dies in a byte or two per attempt, so the cost is
         * visiting every offset, and this is what removes it. The quadratic
         * crossing arm (§3.7.1) is NOT rescued and D63 accepts that —
         * DD-7's reverse BOT variant is the sequenced fix.
         *
         * [M6.2 wave D] THE LOWER BOUND IS `startpos`, NOT 0, WHENEVER THE
         * MACHINE HAS A `\G` FAMILY — and getting this wrong is a lost match,
         * not a slow one. The derivation reads `s1u[]`, the states an attempt
         * at `start > startpos` enters; the attempt at `start == startpos`
         * enters `s1g[]` instead, which the derivation never looked at. So a
         * pattern with a `(?m)^` branch AND a `\G` branch — `(?m)^a|\Gb`,
         * whose candidate set is the newline definition — would have had its
         * `\G` attempt skipped at any `startpos` not preceded by a newline.
         * `start > startpos` implies `start > 0`, so the bound is a
         * STRENGTHENING of the existing guard rather than a second condition,
         * and every position the skip then passes over is one this
         * derivation's domain covers. Sabotage S82 restores `start > 0`. */
        sb_printf(c, "        if (start > %s && subject[start - %d] != %d) {\n"
                         "            const void *q = memchr(subject + start, %d, "
                         "subject_length - start);\n"
                         "            if (!q) break;\n"
                         "            start = (size_t)"
                         "((const unsigned char *)q - subject) + %d;\n"
                         "        }\n",
                  gseed ? "search_from" : "0",
                  cand.offset, cand.byte, cand.byte, cand.offset);
    }
    sb_puts(c, "        size_t scan_position = start;\n"
               "        size_t last_accept_position = (size_t)-1;\n");

    /* [M6.2 wave D] THE START DISPATCH IS THREE-WAY WHEN `\G` IS PRESENT
     * (assertions_design.md §4.2's table), and the three cases are exactly
     * its three reachable rows:
     *
     *     start == 0          -> s0     (`\A` and `\G` both pass)
     *     start == startpos   -> s1g[]  (`\G` only)
     *     start >  startpos   -> s1u[]  (neither)
     *
     * `start == 0` is tested FIRST and that ordering is load-bearing: it is
     * the row where BOTH hold, and testing `start == startpos` first would
     * route offset 0 into the `\G`-only state and lose every `\A`/`^` branch.
     *
     * The `\G`-free path below is the pre-wave code untouched, three branches
     * and all — the same one-branch-that-reproduces-the-old-string discipline
     * `emit_view_select` is written with, for the same reason. */
    if (gseed) {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_puts(c, "\n               : (start == search_from) ? ");
        if (gtbl) sb_printf(c, "%s_gstart_seed_state[%s_byte_class[subject[start - 1]]]", p, p);
        else      emit_target(c, p, d->s1g[UPC_PLAIN]);
        sb_puts(c, "\n               : ");
        if (seed) sb_printf(c, "%s_seed_state[%s_byte_class[subject[start - 1]]]", p, p);
        else      emit_target(c, p, d->s1u[UPC_PLAIN]);
        sb_puts(c, ");\n");
    } else if (seed) {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_printf(c, " : %s_seed_state[%s_byte_class[subject[start - 1]]]);\n", p, p);
    } else if (d->s0 == d->s1u[UPC_PLAIN]) {
        sb_puts(c, "        goto ");
        if (d->s0 < 0) sb_printf(c, "*&&%s_dead;\n", p);
        else           sb_printf(c, "*&&%s_s%d;\n", p, d->s0);
    } else {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_puts(c, " : ");
        emit_target(c, p, d->s1u[UPC_PLAIN]);
        sb_puts(c, ");\n");
    }

    for (int i = 0; i < d->n; i++) {
        const DState *st = &d->st[i];
        /* labels marked unused: EOL-variant states are entered via their
         * transition tables only, never their own label */
        sb_printf(c, "%s_s%d: __attribute__((unused));\n", p, i);
        /* [M6.2 wave B] Does THIS state's accept depend on the next byte? A
         * per-state question, not a per-artifact one: a `\b` pattern's
         * artifact typically has a handful of such states and keeps the
         * pre-wave text at every other, which is what makes the byte-identity
         * property hold at state granularity rather than at file granularity. */
        bool wsplit = acc2 && state_acc_varies(st);
        if (wsplit) {
            /* THE ORDER FLIPS, and it has to. The pre-wave arms record the
             * accept and THEN test for `pos >= n`, which is sound while the
             * accept bit is a scalar; here the bit at `pos < n` is a function
             * of `s[pos]`, so the end-of-subject case has to be split off
             * first — it is the one position with no next byte, where §3.6.2
             * makes the accept SCALAR. That test is also what makes the
             * `s[pos]` below unreachable at `pos == n`. */
            int endview = st_emit_endvar(st) >= 0 ? st_emit_endvar(st)
                        : st->eolvar >= 0 ? st->eolvar : i;
            sb_puts(c, "        if (scan_position == subject_length) {\n");
            if (d->st[endview].up[UPC_PLAIN].accept)
                sb_puts(c, "            last_accept_position = scan_position;\n");
            sb_printf(c, "            goto %s_done;\n        }\n", p);
            if (st->eolvar >= 0) {
                /* [M6.2 wave C] THE EOL POSITION'S ACCEPT IS CLASS-INDEXED
                 * TOO, and wave B's note here said otherwise. Its reasoning
                 * was right for its own axis and its conclusion is now wrong:
                 * the byte at an EOL position is `\n`, which is indeed not a
                 * word character — so the WORD axis has nothing to add — but
                 * it IS the newline definition, which is precisely what
                 * `(?m)$` reads. `(?m)a(?:$|\Z)` is the shape that needs
                 * both: the `\Z` half makes an EOL view exist, and the
                 * `(?m)$` half makes that view's accept depend on the very
                 * byte the arm's entry test just pinned.
                 *
                 * Pinned, not read: both indices are compile-time facts here
                 * (the view from the position, the class from the arm's own
                 * `s[pos] == newline` test), so this is a constant, not a
                 * table lookup. `unl` is UPC_PLAIN on any machine without a
                 * newline refinement, which is what keeps the pre-wave text
                 * byte-identical. */
                const DState *v = &d->st[st->eolvar];
                sb_puts(c, "        if (scan_position + 1 == subject_length && subject[scan_position] == '\\n') {\n");
                if (v->up[unl].accept) sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            sb_printf(c, "        {\n"
                         "            unsigned forward_class = %s_byte_class[subject[scan_position]];\n"
                         "            if (%s_is_accepting_by_class[%d + forward_class]) last_accept_position = scan_position;\n"
                         "            scan_position++;\n"
                         "            goto *%s_targets_%d[forward_class];\n"
                         "        }\n",
                      p, p, i * d->ncls, p, i);
        } else if (st_emit_endvar(st) >= 0) {
            /* [M6.2 wave A] THE END VIEW (`\z`), reached on ENG_ATTEMPT only
             * when the pattern also carries a `^`/`\A` — `\Aa\z` is the
             * shape. Three arms in position order, most specific first:
             * `pos == n` takes the END view (and then there is no byte to
             * consume, so it always leaves), `pos + 1 == n && s[pos] == '\n'`
             * takes the EOL view, and everything else is the state itself.
             *
             * A state only reaches this branch when its END view DIFFERS from
             * its EOL view (`endvar >= 0` means exactly that, src/ir/dfa.c) —
             * which is why the `endvar < 0` else-branch below is still the
             * pre-wave text, unchanged, for every state of every pattern that
             * has no `\z`. */
            const DState *endv = &d->st[st_emit_endvar(st)];
            sb_puts(c, "        if (scan_position == subject_length) {\n");
            if (endv->up[UPC_PLAIN].accept)
                sb_puts(c, "            last_accept_position = scan_position;\n");
            sb_printf(c, "            goto %s_done;\n", p);
            sb_puts(c, "        }\n");
            if (st->eolvar >= 0) {
                const DState *v = &d->st[st->eolvar];
                sb_puts(c, "        if (scan_position + 1 == subject_length && subject[scan_position] == '\\n') {\n");
                if (v->up[unl].accept)
                    sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last_accept_position = scan_position;\n");
            /* both arms above returned or consumed, so pos < n here */
            sb_printf(c, "        goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n", p, i, p);
        } else if (st->eolvar >= 0) {
            const DState *v = &d->st[st->eolvar];
            /* at an EOL position ($ passable), use the EOL-view state:
             * its accept is correctly priority-pruned and its table
             * carries the $-gated continuations.
             *
             * [M6.2 wave C] THE TWO EOL POSITIONS CAN CARRY DIFFERENT ACCEPT
             * BITS and the pre-wave text merged them into one arm. They are
             * `pos == n` (no next byte: §3.6.2's SCALAR accept) and
             * `pos + 1 == n && s[pos] == '\n'` (next byte pinned to the
             * newline definition), and until `(?m)$` existed nothing could
             * tell them apart, because the EOL view's accept did not depend
             * on the next byte at all. `(?m)a$` on `"a\n"` is the witness:
             * the view accepts at the newline position and the merged arm
             * would have had to answer for both with one bit.
             *
             * The arms only SPLIT when the two bits differ, so a machine with
             * no newline refinement (`unl == UPC_PLAIN`) emits the pre-wave
             * text character for character. */
            bool a_end = v->up[UPC_PLAIN].accept;
            bool a_nl  = v->up[unl].accept;
            if (a_end == a_nl) {
                sb_puts(c, "        if (scan_position == subject_length || (scan_position + 1 == subject_length && "
                           "subject[scan_position] == '\\n')) {\n");
                if (a_end)
                    sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            if (scan_position >= subject_length) goto %s_done;\n", p);
                sb_printf(c, "            goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            } else {
                sb_puts(c, "        if (scan_position == subject_length) {\n");
                if (a_end)
                    sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            goto %s_done;\n        }\n", p);
                sb_puts(c, "        if (scan_position + 1 == subject_length && subject[scan_position] == '\\n') {\n");
                if (a_nl)
                    sb_puts(c, "            last_accept_position = scan_position;\n");
                sb_printf(c, "            goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last_accept_position = scan_position;\n");
            /* not an EOL position implies pos < n: consume directly */
            sb_printf(c, "        goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n", p, i, p);
        } else {
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last_accept_position = scan_position;\n");
            sb_printf(c, "        if (scan_position >= subject_length) goto %s_done;\n", p);
            sb_printf(c, "        goto *%s_targets_%d[%s_byte_class[subject[scan_position++]]];\n", p, i, p);
        }
    }

    sb_printf(c, "%s_dead: __attribute__((unused));\n", p);
    sb_printf(c, "%s_done:\n", p);
    sb_puts(c, "        if (__builtin_expect(last_accept_position != (size_t)-1, 0)) {\n"
               "            if (capture_spans) { capture_spans[0][0] = (ptrdiff_t)start; capture_spans[0][1] = (ptrdiff_t)last_accept_position; }\n"
               "            return 1;\n"
               "        }\n"
               "    }\n"
               "    return 0;\n"
               "}\n");
}

