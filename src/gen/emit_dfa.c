/* DFA -> C code generation, two engines (see docs/dev/decisions.md D3/D7):
 *
 * ENG_UNANCH (patterns without `^`, including `$`-bearing ones since M2.7):
 * one O(n) forward pass over the
 * subject with the unanchored priority DFA (finds the leftmost-first match
 * END), then a backward pass with the non-pruning reverse DFA (earliest
 * accepting position = match START). Emitted TABLE-DRIVEN — int16 transition
 * tables + a generic loop — because gcc's compile time on huge computed-goto
 * functions is superlinear (R1 A-3) while data initializers stay flat. A
 * memchr (single escape byte) or bitmap skip loop runs while the machine is
 * parked in the start state (M2.1 prefilter).
 *
 * ENG_ATTEMPT (patterns containing `^`): per-start-position computed-goto
 * attempt loop with EOL-variant states (R1 S-C1/S-C2). `^` needs a
 * position-dependent BOT variant in the REVERSE machine, which the DFA does
 * not build yet, so these stay here; fully-anchored patterns get the
 * start_max=0 fast path, so the slow shape is `^` on only SOME branches.
 *
 * Generated code is self-contained: no dependency on pcrec at build or run
 * time. */

#include <ctype.h>
#include <stdio.h>
#include <string.h>

#include "core/internal.h"

static void emit_pattern_comment(StrBuf *sb, const char *pat)
{
    sb_puts(sb, "/* Generated by pcrec. Pattern: ");
    int prev = 0;
    for (const char *q = pat; *q; q++) {
        unsigned char ch = (unsigned char)*q;
        if (ch >= 32 && ch < 127 && !(prev == '*' && ch == '/'))
            sb_putc(sb, (char)ch);
        else
            sb_printf(sb, "\\x%02x", ch);
        prev = ch;
    }
    sb_puts(sb, " */\n");
}

/* D37 (docs/dev/decisions.md): emitted C is SELF-DESCRIBING about which
 * feature modules were enabled at generation time — the comment for a
 * human, the macros for a machine (or a future pcrec: pass
 * PCREC_FEATURE_MODULES's value to --features and get the same gate state
 * this artifact was built with, even if a named set's own meaning, or
 * "all"'s membership, has since changed). Both values come from
 * src/parse/enabled.c's OWN render of the currently-installed set — there
 * is no second copy of "what does this mask mean as names" here. Every
 * value in play (a named set's name, "all"/"none"/"explicit", and every
 * module name) comes from pcrec's own fixed vocabulary, never from the
 * pattern text, so unlike emit_pattern_comment above nothing here needs
 * escaping. */
static void emit_feature_comment(StrBuf *sb)
{
    const char *label = pcrec_enabled_set_label();
    const char *mods = pcrec_enabled_set_modules();
    sb_printf(sb, "/* Feature set: %s (modules: %s) */\n",
              label, *mods ? mods : "none");
}

/* Macros, ONCE PER FILE like emit_span_typedef above — the enabled set is
 * process-wide (one set for the whole compile), so every engine a future
 * multi-engine file carries (OS-0b) shares one stamp. Lives only in the .c:
 * a paired .h gets the comment (emit_header, matching its existing
 * pattern-comment convention) but not these, so a .c that #includes its own
 * .h never sees the pair twice. */
static void emit_feature_macros(StrBuf *sb)
{
    sb_printf(sb, "#define PCREC_FEATURE_SET \"%s\"\n",
              pcrec_enabled_set_label());
    sb_printf(sb, "#define PCREC_FEATURE_MODULES \"%s\"\n",
              pcrec_enabled_set_modules());
}

/* ---- the multi-engine naming surface (OS-0b; D18 measured, D20 owns it) ----
 *
 * One output file may eventually carry SEVERAL engines — one per point of the
 * option product, chosen by a generated selector (D18/D20). Almost nothing
 * here needs to change for that, because every identifier either emitter
 * produces is a FUNCTION-LOCAL static except the two named below: the
 * unanchored engine's fcls/ftr/facc/fev/first/fs<N>/rcls/rtr/racc/rev/rs<N>
 * and the attempt engine's cls/t<N> are all declared inside the engine
 * function, so two engines in two functions cannot collide on them however
 * similar their patterns. (D18 measured this on `.*=.*$`: 15 emitted
 * identifiers, 12 function-local.)
 *
 * That leaves TWO file-scope names — the span type and the entry point — and
 * both go through the helpers below:
 *
 *   emit_span_typedef  ONCE PER FILE, shared by every engine in it. Emitting
 *                      it per engine is NOT a benign redefinition — each
 *                      occurrence declares a fresh anonymous struct type, so
 *                      gcc rejects the file with "conflicting types for
 *                      'rx_span'" (verified under -std=gnu11 and -std=c99).
 *   emit_search_decl   ONCE PER ENGINE, under that engine's own entry name.
 *
 * The entry name is produced by engine_entry_name() and read from nowhere
 * else, so a finder can hand each engine a distinct name (`rx_search_ci`)
 * without any emitter knowing that options have a product. Today there is one
 * engine per file and the name is "<prefix>_search". */

static void emit_span_typedef(StrBuf *sb, const char *p)
{
    sb_printf(sb, "typedef struct { size_t start, end; } %s_span;\n", p);
}

static void emit_search_decl(StrBuf *sb, const char *p, const char *fn)
{
    sb_printf(sb, "int %s(const unsigned char *s, size_t n, "
                  "size_t startpos, %s_span *m);\n", fn, p);
}

/* The definition's signature, kept next to the declaration it must match. */
static void emit_search_head(StrBuf *c, const char *p, const char *fn)
{
    sb_printf(c, "int %s(const unsigned char *s, size_t n, "
                 "size_t startpos, %s_span *m)\n{\n", fn, p);
}

static const char *engine_entry_name(Ctx *cx)
{
    const char *p = cx->opt->prefix;
    size_t sz = strlen(p) + sizeof("_search");
    char *fn = arena_alloc(&cx->arena, sz);
    snprintf(fn, sz, "%s_search", p);
    return fn;
}

static void emit_header(Ctx *cx, const char *fn)
{
    StrBuf *h = &cx->job->hsb;
    const char *p = cx->opt->prefix;
    char guard[80];
    size_t gi = 0;
    for (const char *q = p; *q && gi < sizeof(guard) - 1; q++)
        guard[gi++] = (char)(isalnum((unsigned char)*q) ? toupper((unsigned char)*q) : '_');
    guard[gi] = 0;

    emit_pattern_comment(h, cx->pat);
    emit_feature_comment(h);
    sb_printf(h, "#ifndef PCREC_GEN_%s_H\n#define PCREC_GEN_%s_H\n\n", guard, guard);
    sb_puts(h, "#include <stddef.h>\n\n");
    emit_span_typedef(h, p);
    emit_search_decl(h, p, fn);
    sb_printf(h, "\n#endif /* PCREC_GEN_%s_H */\n", guard);
}

/* ---- shared table emitters ---- */

static void emit_u8_table(StrBuf *c, const char *p, const char *tag,
                          const uint8_t *v, int n)
{
    sb_printf(c, "    static const unsigned char %s_%s[%d] = {", p, tag, n);
    for (int i = 0; i < n; i++) {
        if (i % 16 == 0) sb_puts(c, "\n       ");
        sb_printf(c, " %3d,", v[i]);
    }
    sb_puts(c, "\n    };\n");
}

static void emit_tr_table(StrBuf *c, const char *p, const char *tag, const Dfa *d)
{
    sb_printf(c, "    static const short %s_%s[%d] = {", p, tag, d->n * d->ncls);
    int k = 0;
    for (int i = 0; i < d->n; i++) {
        for (int cl = 0; cl < d->ncls; cl++, k++) {
            if (k % 16 == 0) sb_puts(c, "\n       ");
            sb_printf(c, " %d,", d->st[i].tr[cl]);
        }
    }
    sb_puts(c, "\n    };\n");
}

static bool dfa_has_eolvar(const Dfa *d)
{
    for (int i = 0; i < d->n; i++)
        if (d->st[i].eolvar >= 0) return true;
    return false;
}

static void emit_eol_table(StrBuf *c, const char *p, const char *tag, const Dfa *d)
{
    sb_printf(c, "    static const short %s_%s[%d] = {", p, tag, d->n);
    for (int i = 0; i < d->n; i++) {
        if (i % 16 == 0) sb_puts(c, "\n       ");
        sb_printf(c, " %d,", d->st[i].eolvar);
    }
    sb_puts(c, "\n    };\n");
}

static void emit_acc_table(StrBuf *c, const char *p, const char *tag, const Dfa *d)
{
    sb_printf(c, "    static const unsigned char %s_%s[%d] = {", p, tag, d->n);
    for (int i = 0; i < d->n; i++) {
        if (i % 16 == 0) sb_puts(c, "\n       ");
        sb_printf(c, " %d,", d->st[i].accept ? 1 : 0);
    }
    sb_puts(c, "\n    };\n");
}

/* ---- ENG_UNANCH: table-driven forward + reverse (D7) ---- */

/* M2.1 self-loop skip: pick up to 4 states (excluding `exclude`) that stay
 * put on >= 192 of 256 bytes — their scan degenerates to a SIMD-friendly
 * skip loop. Motivated by compare case h (`.*=.*`): the post-'=' state
 * self-loops on everything but '\n' in both machines.
 *
 * M2.10 tried replacing this absolute byte count with a fraction of the
 * state's LIVE bytes, so that narrow-alphabet patterns like `[01]*1[01]{8}`
 * (2 live bytes, 100% stay) would qualify — R2-A5 had described that case as
 * having "no skip-eligible states". The reasoning was sound and the result
 * was a REGRESSION: it gives case (f) one reverse skip table and measures
 * 158.6/159.1 -> 118.7 MB/s on the compare harness and 159.1/157.5 ->
 * 115.9/115.8 MB/s on bdriver, spreads 1.01-1.02x, i.e. ~27% slower on the
 * exact case it was meant to fix. Reverted; see D13 and the 2026-08-09
 * journal entry. Do not re-attempt without measuring the REVERSE machine
 * specifically — the suspicion is that a backward byte-at-a-time skip loop
 * loses to the reverse table walk, but that is untested. */
static int pick_skip_states(const Dfa *d, int exclude, int out[4])
{
    int cls_size[256] = {0};
    for (int b = 0; b < 256; b++) cls_size[d->clsmap[b]]++;
    int nout = 0;
    for (int pass = 0; pass < 4; pass++) {
        int best = -1, bestcnt = 191;
        for (int i = 0; i < d->n; i++) {
            if (i == exclude) continue;
            bool taken = false;
            for (int k = 0; k < nout; k++)
                if (out[k] == i) taken = true;
            if (taken) continue;
            int stay = 0;
            for (int cl = 0; cl < d->ncls; cl++)
                if (d->st[i].tr[cl] == i) stay += cls_size[cl];
            if (stay > bestcnt) { bestcnt = stay; best = i; }
        }
        if (best < 0) break;
        out[nout++] = best;
    }
    return nout;
}

static void emit_stay_table(StrBuf *c, const char *p, const char *tag,
                            int idx, const Dfa *d)
{
    uint8_t stay[256];
    for (int b = 0; b < 256; b++)
        stay[b] = (uint8_t)(d->st[idx].tr[d->clsmap[b]] == idx);
    char name[32];
    snprintf(name, sizeof(name), "%s%d", tag, idx);
    emit_u8_table(c, p, name, stay, 256);
}

/* M2.7 put `$`-bearing patterns on this engine; M2.12 gave them back the
 * scan-avoidance M2.7 had traded away. Both live in ONE emitter on purpose:
 * M2.7 forked a second copy, and the fork is exactly how the prefilter and
 * skip loops went missing from the `$` path for a whole milestone.
 *
 * EOL handling: both machines switch to a state's EOL variant exactly at EOL
 * positions (end of subject, or before a final newline), guarded by
 * `pos + 1 >= n` — false for every byte but the last two, so the scan stays a
 * tight table walk.
 *
 * Scan avoidance under EOL (M2.12): a prefilter or self-loop skip advances
 * `pos` WITHOUT consulting accept flags, which is unsound when a state can
 * accept at an EOL position. The fix is to bound every skip at `n - 1` rather
 * than `n` and let the stepped loop handle the last two positions. That also
 * keeps the EOL-variant lookup correct for free: a skip can only run when
 * `pos + 1 < n`, and in that case `est == st` by construction, so the state
 * used for the transition is never stale. The forward prefilter additionally
 * must NOT keep its `return 0` early-out, since the start state's EOL variant
 * may still accept at n-1 or n. */
static void emit_unanchored(Ctx *cx, const char *fn)
{
    Job *job = cx->job;
    Dfa *fd = &job->dfa, *rd = &job->rdfa;
    StrBuf *c = &job->csb;
    const char *p = cx->opt->prefix;

    bool eol = dfa_has_eolvar(fd) || dfa_has_eolvar(rd);

    int fs = fd->s0;   /* no asserts -> s0 == s1 */
    int rs = rd->s0;

    emit_search_head(c, p, fn);

    if (fs < 0 || rs < 0) {
        sb_puts(c, "    (void)s; (void)n; (void)startpos; (void)m;\n"
                   "    return 0;\n}\n");
        return;
    }

    /* start-state prefilter analysis: bytes that advance the pattern */
    bool start_acc = fd->st[fs].accept;
    uint8_t first[256];
    int esc_count = 0, esc_byte = 0;
    for (int b = 0; b < 256; b++) {
        int t = fd->st[fs].tr[fd->clsmap[b]];
        first[b] = (uint8_t)(t != fs);
        if (first[b]) { esc_count++; esc_byte = b; }
    }
    /* "can neither accept nor ever leave the start state" is only a proof
     * that nothing matches when the start state has no EOL view. `$` alone is
     * exactly the counter-example: it never leaves fs and facc[fs] is 0, but
     * its EOL variant accepts. */
    if (esc_count == 0 && !start_acc && fd->st[fs].eolvar < 0) {
        sb_puts(c, "    (void)s; (void)n; (void)startpos; (void)m;\n"
                   "    return 0;\n}\n");
        return;
    }
    /* The prefilter stays valid under EOL because it is BOUNDED AT n-1: it
     * only ever skips non-EOL positions at which the machine provably stays
     * parked in fs.
     *
     * The `last == (size_t)-1` gate on the emitted `if` is NOT part of that
     * argument, and this comment used to present the two as jointly
     * load-bearing (R3.2 critic). The gate is redundant given D3's priority
     * pruning: the unanchored start self-loop is the LOWEST-priority thread,
     * so it is pruned out of every accepting state, an accepting state's
     * successors can therefore never be `fs`, and `last` is only ever set from
     * an accepting view — so `st == fs` already implies `last == -1`. Two
     * independent critics attacked the gate and neither could build a witness:
     * deleting it produced 0 divergences over 8.0M oracle-checked comparisons
     * and 0 failures across the whole .rxt corpus.
     *
     * Keep the gate — it is free belt-and-braces — but do not cite it as a
     * premise. Presenting a redundant condition and a load-bearing one as the
     * same claim is how someone eventually "simplifies away" the wrong half. */
    bool prefilter = !start_acc && esc_count > 0 && esc_count < 256;
    bool use_memchr = prefilter && esc_count == 1;

    int fskip[4], rskip[4];
    int nfskip = pick_skip_states(fd, fs, fskip);
    int nrskip = pick_skip_states(rd, -1, rskip);

    emit_u8_table(c, p, "fcls", fd->clsmap, 256);
    emit_tr_table(c, p, "ftr", fd);
    emit_acc_table(c, p, "facc", fd);
    if (eol) emit_eol_table(c, p, "fev", fd);
    if (prefilter && !use_memchr)
        emit_u8_table(c, p, "first", first, 256);
    for (int k = 0; k < nfskip; k++)
        emit_stay_table(c, p, "fs", fskip[k], fd);
    emit_u8_table(c, p, "rcls", rd->clsmap, 256);
    emit_tr_table(c, p, "rtr", rd);
    emit_acc_table(c, p, "racc", rd);
    if (eol) emit_eol_table(c, p, "rev", rd);
    for (int k = 0; k < nrskip; k++)
        emit_stay_table(c, p, "rs", rskip[k], rd);

    /* Under EOL the scan reads the accept flag and the transition row through
     * `est`/`erst` (the EOL view at the last two positions); otherwise those
     * collapse to `st`/`rst` and gcc sees exactly the pre-M2.7 loop. */
    const char *fsrc = eol ? "est" : "st";
    const char *rsrc = eol ? "erst" : "rst";
    /* Every skip must stop at n-1 so a state that accepts only at EOL is
     * never skipped past; below n-1 the EOL view is unreachable, which is
     * also why `est` cannot be stale after a skip. */
    const char *fbound = eol ? "pos + 1 < n" : "pos < n";

    sb_puts(c,   "    size_t pos = startpos;\n"
                 "    size_t last = (size_t)-1;\n");
    sb_printf(c, "    int st = %d;\n", fs);
    sb_puts(c,   "    if (startpos > n) return 0;\n"
                 "    for (;;) {\n");
    /* Under EOL, scan avoidance must run BEFORE the accept/EOL evaluation, so
     * that evaluation sees the position the loop is really at: a skip bounded
     * at n-1 can LAND on n-1, and evaluating first would consume that byte
     * without ever taking its EOL view (53 divergences, see D11).
     *
     * Without EOL the order is a free choice semantically — every position a
     * skip passes has the same state and so the same accept bit — but NOT a
     * free choice in speed. Hoisting the prefilter above the accept check
     * costs 43% on `[01]*1[01]{8}` (158.4 -> 90.8 MB/s, 0 skip states, tight
     * spreads), so the non-EOL path keeps the original order. This asymmetry
     * is the whole reason the flag exists; do not "simplify" it away. */
    if (!eol)
        sb_printf(c, "        if (%s_facc[st]) last = pos;\n", p);
    {
        const char *kw = "if";
        if (prefilter) {
            sb_printf(c, "        if (st == %d && last == (size_t)-1) {\n", fs);
            if (use_memchr) {
                if (eol) {
                    /* no early `return 0`: the EOL view may still accept at
                     * n-1 or n, so fall through to the stepped loop instead */
                    sb_puts(c,   "            if (pos + 1 < n) {\n");
                    sb_printf(c, "                const void *q = memchr(s + pos, %d, n - 1 - pos);\n", esc_byte);
                    sb_puts(c,   "                pos = q ? (size_t)((const unsigned char *)q - s) : n - 1;\n"
                                 "            }\n");
                } else {
                    sb_printf(c, "            const void *q = memchr(s + pos, %d, n - pos);\n", esc_byte);
                    sb_puts(c,   "            if (!q) return 0;\n"
                                 "            pos = (size_t)((const unsigned char *)q - s);\n");
                }
            } else {
                sb_printf(c, "            while (%s && !%s_first[s[pos]]) pos++;\n", fbound, p);
                if (!eol) sb_puts(c, "            if (pos >= n) return 0;\n");
            }
            sb_puts(c, "        }\n");
            kw = "else if";
        }
        for (int k = 0; k < nfskip; k++) {
            int K = fskip[k];
            sb_printf(c, "        %s (st == %d) {\n", kw, K);
            sb_printf(c, "            while (%s && %s_fs%d[s[pos]]) pos++;\n", fbound, p, K);
            /* With the accept check ahead of us (non-EOL order) the skipped
             * run's final position would otherwise go unrecorded; under EOL
             * the check runs after the skip and already covers it. */
            if (!eol && fd->st[K].accept)
                sb_puts(c, "            last = pos;\n");
            sb_puts(c, "        }\n");
            kw = "else if";
        }
    }
    if (eol) {
        sb_puts(c,   "        int est = st;\n");
        sb_printf(c, "        if (__builtin_expect(pos + 1 >= n, 0) && %s_fev[st] >= 0 &&\n"
                     "            (pos == n || (pos + 1 == n && s[pos] == '\\n')))\n"
                     "            est = %s_fev[st];\n", p, p);
        sb_printf(c, "        if (%s_facc[%s]) last = pos;\n", p, fsrc);
    }
    sb_puts(c,   "        if (pos >= n) break;\n");
    sb_printf(c, "        st = %s_ftr[%s * %d + %s_fcls[s[pos++]]];\n",
              p, fsrc, fd->ncls, p);
    sb_puts(c,   "        if (st < 0) break;\n"
                 "    }\n"
                 "    if (last == (size_t)-1) return 0;\n"
                 "    {\n"
                 "        size_t end = last;\n"
                 "        size_t sfound = (size_t)-1;\n"
                 "        size_t pp = end;\n");
    sb_printf(c, "        int rst = %d;\n", rs);
    sb_puts(c,   "        for (;;) {\n");
    if (!eol)
        sb_printf(c, "            if (%s_racc[rst]) sfound = pp;\n", p);
    {   /* same ordering rule as the forward loop, and `sfound` wants the
         * SMALLEST accepting position, which is where a reverse skip stops */
        const char *kw = "if";
        for (int k = 0; k < nrskip; k++) {
            int K = rskip[k];
            /* pp only ever DECREASES, so one entry guard is enough to keep the
             * whole skip below the EOL region */
            sb_printf(c, "            %s (rst == %d%s) {\n", kw, K,
                      eol ? " && pp + 1 < n" : "");
            sb_printf(c, "                while (pp > startpos && %s_rs%d[s[pp - 1]]) pp--;\n", p, K);
            if (!eol && rd->st[K].accept)
                sb_puts(c, "                sfound = pp;\n");
            sb_puts(c, "            }\n");
            kw = "else if";
        }
    }
    if (eol) {
        sb_puts(c,   "            int erst = rst;\n");
        sb_printf(c, "            if (__builtin_expect(pp + 1 >= n, 0) && %s_rev[rst] >= 0 &&\n"
                     "                (pp == n || (pp + 1 == n && s[pp] == '\\n')))\n"
                     "                erst = %s_rev[rst];\n", p, p);
        sb_printf(c, "            if (%s_racc[%s]) sfound = pp;\n", p, rsrc);
    }
    sb_puts(c,   "            if (pp <= startpos) break;\n");
    sb_printf(c, "            rst = %s_rtr[%s * %d + %s_rcls[s[--pp]]];\n",
              p, rsrc, rd->ncls, p);
    sb_puts(c,   "            if (rst < 0) break;\n"
                 "        }\n"
                 "        if (sfound == (size_t)-1) return 0;\n"
                 "        if (m) { m->start = sfound; m->end = end; }\n"
                 "        return 1;\n"
                 "    }\n"
                 "}\n");
}

/* ---- ENG_ATTEMPT: computed-goto per-start attempt loop ---- */

static void emit_target(StrBuf *c, const char *p, int tgt)
{
    if (tgt < 0) sb_printf(c, "&&%s_dead", p);
    else         sb_printf(c, "&&%s_s%d", p, tgt);
}

static void emit_attempt(Ctx *cx, const char *fn)
{
    Job *job = cx->job;
    Dfa *d = &job->dfa;
    StrBuf *c = &job->csb;
    const char *p = cx->opt->prefix;

    emit_search_head(c, p, fn);

    if (d->n == 0) {
        /* no live start state: the pattern matches nothing */
        sb_puts(c, "    (void)s; (void)n; (void)startpos; (void)m;\n"
                   "    return 0;\n}\n");
        return;
    }

    emit_u8_table(c, p, "cls", d->clsmap, 256);

    for (int i = 0; i < d->n; i++) {
        sb_printf(c, "    static const void *const %s_t%d[%d] = { ",
                  p, i, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->st[i].tr[cl]);
        }
        sb_puts(c, " };\n");
    }

    /* anchored fast path (M2.1): if the interior start state is dead, every
     * branch requires ^, so only start == 0 can ever match */
    sb_printf(c, "    size_t start;\n"
                 "    const size_t start_max = %s;\n",
              d->s1 < 0 ? "0 /* fully ^-anchored */" : "n");
    sb_puts(c, "    for (start = startpos; start <= start_max; start++) {\n"
               "        size_t pos = start;\n"
               "        size_t last = (size_t)-1;\n");

    if (d->s0 == d->s1) {
        sb_puts(c, "        goto ");
        if (d->s0 < 0) sb_printf(c, "*&&%s_dead;\n", p);
        else           sb_printf(c, "*&&%s_s%d;\n", p, d->s0);
    } else {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_puts(c, " : ");
        emit_target(c, p, d->s1);
        sb_puts(c, ");\n");
    }

    for (int i = 0; i < d->n; i++) {
        const DState *st = &d->st[i];
        /* labels marked unused: EOL-variant states are entered via their
         * transition tables only, never their own label */
        sb_printf(c, "%s_s%d: __attribute__((unused));\n", p, i);
        if (st->eolvar >= 0) {
            const DState *v = &d->st[st->eolvar];
            /* at an EOL position ($ passable), use the EOL-view state:
             * its accept is correctly priority-pruned and its table
             * carries the $-gated continuations */
            sb_puts(c, "        if (pos == n || (pos + 1 == n && "
                       "s[pos] == '\\n')) {\n");
            if (v->accept)
                sb_puts(c, "            last = pos;\n");
            sb_printf(c, "            if (pos >= n) goto %s_done;\n", p);
            sb_printf(c, "            goto *%s_t%d[%s_cls[s[pos++]]];\n",
                      p, st->eolvar, p);
            sb_puts(c, "        }\n");
            if (st->accept)
                sb_puts(c, "        last = pos;\n");
            /* not an EOL position implies pos < n: consume directly */
            sb_printf(c, "        goto *%s_t%d[%s_cls[s[pos++]]];\n", p, i, p);
        } else {
            if (st->accept)
                sb_puts(c, "        last = pos;\n");
            sb_printf(c, "        if (pos >= n) goto %s_done;\n", p);
            sb_printf(c, "        goto *%s_t%d[%s_cls[s[pos++]]];\n", p, i, p);
        }
    }

    sb_printf(c, "%s_dead: __attribute__((unused));\n", p);
    sb_printf(c, "%s_done:\n", p);
    sb_puts(c, "        if (__builtin_expect(last != (size_t)-1, 0)) {\n"
               "            if (m) { m->start = start; m->end = last; }\n"
               "            return 1;\n"
               "        }\n"
               "    }\n"
               "    return 0;\n"
               "}\n");
}

void pcrec_emit_dfa(Ctx *cx)
{
    Job *job = cx->job;
    StrBuf *c = &job->csb;
    const char *p = cx->opt->prefix;
    const char *fn = engine_entry_name(cx);

    if (cx->opt->header_name) emit_header(cx, fn);

    emit_pattern_comment(c, cx->pat);
    emit_feature_comment(c);
    emit_feature_macros(c);
    if (cx->opt->header_name) {
        sb_printf(c, "#include \"%s\"\n", cx->opt->header_name);
    } else {
        sb_puts(c, "#include <stddef.h>\n\n");
        /* file-scope, shared by every engine here; per-engine below */
        emit_span_typedef(c, p);
        emit_search_decl(c, p, fn);
    }
    if (job->engine == PCREC_ENG_UNANCH)
        sb_puts(c, "#include <string.h>\n");
    if (cx->opt->emit_main)
        sb_puts(c, "#include <stdio.h>\n#include <string.h>\n");
    sb_puts(c, "\n");

    if (job->engine == PCREC_ENG_UNANCH)
        emit_unanchored(cx, fn);
    else
        emit_attempt(cx, fn);

    if (cx->opt->emit_main) {
        sb_puts(c, "\n");
        sb_printf(c,
            "int main(int argc, char **argv)\n{\n"
            "    %s_span m = { 0, 0 };\n"
            "    if (argc < 2) { fprintf(stderr, \"usage: %%s <subject>\\n\", argv[0]); return 2; }\n"
            "    if (%s((const unsigned char *)argv[1], strlen(argv[1]), 0, &m)) {\n"
            "        printf(\"match %%zu %%zu\\n\", m.start, m.end);\n"
            "        return 0;\n"
            "    }\n"
            "    printf(\"nomatch\\n\");\n"
            "    return 1;\n"
            "}\n", p, fn);
    }
}
