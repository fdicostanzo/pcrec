/* The VIEW SELECTOR, emitted once per machine (forward and reverse) and the
 * one place the three-way position rule turns into C.
 *
 * `posv` is the position variable (`pos` / `pp`), `stv` the state variable
 * (`st` / `rst`), `outv` the view variable the scan then indexes through
 * (`est` / `erst`), and `ev`/`endv` the two table tags.
 *
 *   pos == n                      -> the END view   (`\z`, `$`, `\Z` all pass)
 *   pos + 1 == n && s[pos] == \n  -> the EOL view   (`$`/`\Z` only)
 *   otherwise                     -> the state itself
 *
 * WITH NO END VIEW IN THE MACHINE (`has_end` false) this emits the exact text
 * it emitted before [M6.2] wave A, character for character — the byte-identity
 * property is a property of this function, so it is written as one branch that
 * reproduces the old string rather than as a general form that happens to
 * agree. */
static void emit_view_select(StrBuf *c, const char *p, bool has_eol,
                             bool has_end, const char *posv, const char *stv,
                             const char *outv, const char *ev,
                             const char *endv, const char *ind)
{
    sb_printf(c, "%sint %s = %s;\n", ind, outv, stv);
    if (!has_end) {
        sb_printf(c, "%sif (__builtin_expect(%s + 1 >= n, 0) && %s_%s[%s] >= 0 &&\n"
                     "%s    (%s == n || (%s + 1 == n && s[%s] == '\\n')))\n"
                     "%s    %s = %s_%s[%s];\n",
                  ind, posv, p, ev, stv,
                  ind, posv, posv, posv,
                  ind, outv, p, ev, stv);
        return;
    }
    if (!has_eol) {
        /* `\z` with no `$`/`\Z` anywhere: only `pos == n` selects anything. */
        sb_printf(c, "%sif (__builtin_expect(%s == n, 0) && %s_%s[%s] >= 0)\n"
                     "%s    %s = %s_%s[%s];\n",
                  ind, posv, p, endv, stv,
                  ind, outv, p, endv, stv);
        return;
    }
    sb_printf(c, "%sif (__builtin_expect(%s + 1 >= n, 0)) {\n", ind, posv);
    sb_printf(c, "%s    if (%s == n) {\n", ind, posv);
    sb_printf(c, "%s        if (%s_%s[%s] >= 0)      %s = %s_%s[%s];\n",
              ind, p, endv, stv, outv, p, endv, stv);
    sb_printf(c, "%s        else if (%s_%s[%s] >= 0) %s = %s_%s[%s];\n",
              ind, p, ev, stv, outv, p, ev, stv);
    sb_printf(c, "%s    } else if (s[%s] == '\\n' && %s_%s[%s] >= 0) {\n",
              ind, posv, p, ev, stv);
    sb_printf(c, "%s        %s = %s_%s[%s];\n", ind, outv, p, ev, stv);
    sb_printf(c, "%s    }\n%s}\n", ind, ind);
}

/* The SCALAR accept table — the bit for a position with NO next byte, which
 * §3.6.2 makes the UPC_PLAIN view's own accept (out of subject is neither a
 * word character nor a newline). Every state of a machine with no class axis
 * carries that same bit in all three views, so this is also the pre-wave
 * table, byte for byte. */
static void emit_acc_table(StrBuf *c, const char *p, const char *tag, const Dfa *d)
{
    sb_printf(c, "    static const unsigned char %s_%s[%d] = {", p, tag, d->n);
    for (int i = 0; i < d->n; i++) {
        if (i % 16 == 0) sb_puts(c, "\n       ");
        sb_printf(c, " %d,", d->st[i].up[UPC_PLAIN].accept ? 1 : 0);
    }
    sb_puts(c, "\n    };\n");
}

/* [M6.2 wave B] Does THIS state's accept bit DEPEND ON THE NEXT BYTE? */
static bool state_acc_varies(const DState *st)
{
    for (int u = UPC_PLAIN + 1; u < UPC_N; u++)
        if ((bool)st->up[u].accept != (bool)st->up[UPC_PLAIN].accept)
            return true;
    return false;
}

/* Does this state accept at a position whose next byte is in ANY class? The
 * OR over the class views, and §3.6.1 is emphatic about why the prefilter's
 * gate needs the OR rather than one bit. */
static bool state_acc_any(const DState *st)
{
    for (int u = 0; u < UPC_N; u++)
        if (st->up[u].accept) return true;
    return false;
}

/* Does mechanism 4's runtime start dispatch change any answer? With every
 * interior start state interned to the same state the seed table would be a
 * constant column, so the pre-wave compile-time constant start is emitted
 * instead — which is what keeps every existing artifact's first lines
 * unmoved. */
static bool dfa_needs_seed(const Dfa *d)
{
    for (int u = UPC_PLAIN + 1; u < UPC_N; u++)
        if (d->s1u[u] != d->s1u[UPC_PLAIN]) return true;
    return false;
}

/* Does ANY state's accept bit depend on the next byte?
 *
 * This is the exact condition for emitting §3.6's class-indexed accept table,
 * and it is deliberately NOT "the pattern contains `\b` or `(?m)$`": an
 * assertion that is not reachable at an accepting position leaves every
 * state's accept bits equal across the views, and such a pattern keeps the
 * pre-wave scalar accept and the pre-wave loop text. False for every state of
 * every machine with no class axis by construction (with no N_WORDB and no
 * N_EOL_M the closures coincide, src/ir/dfa.c), which is what makes the
 * corpus's artifacts unmoved. */
static bool dfa_has_clsacc(const Dfa *d)
{
    for (int i = 0; i < d->n; i++)
        if (state_acc_varies(&d->st[i])) return true;
    return false;
}

/* §3.6's accept table: `[states x ncls]`, the bit for "this state accepts at a
 * position whose NEXT byte is in class cl". Two source bits and a class map
 * decide every entry, so this table is derived, never a second opinion. */
static void emit_acc_cls_table(StrBuf *c, const char *p, const char *tag,
                               const Dfa *d)
{
    sb_printf(c, "    static const unsigned char %s_%s[%d] = {", p, tag,
              d->n * d->ncls);
    int k = 0;
    for (int i = 0; i < d->n; i++) {
        for (int cl = 0; cl < d->ncls; cl++, k++) {
            if (k % 16 == 0) sb_puts(c, "\n       ");
            sb_printf(c, " %d,",
                      d->st[i].up[upc_of_class(d, cl)].accept ? 1 : 0);
        }
    }
    sb_puts(c, "\n    };\n");
}

/* The class-axis context of a position whose next byte is a NEWLINE — the one
 * position ENG_ATTEMPT's EOL arm knows the byte at without reading it, since
 * `s[pos] == '\n'` is the arm's own entry condition.
 *
 * D64: derived from `pcrec_cls_newline`, the ONE definition, rather than from
 * a `'\n'` written here. A machine with no newline refinement answers
 * UPC_PLAIN, which is correct for it: nothing distinguishes the two views
 * there, so the bit is the same either way. */
static int upc_of_newline(const Dfa *d)
{
    for (int b = 0; b < 256; b++)
        if (cls_has(pcrec_cls_newline, (unsigned)b))
            return upc_of_class(d, d->clsmap[b]);
    return UPC_PLAIN;
}

/* MECHANISM 4's seed table (§3.8.2): byte class of the context byte -> start
 * state. `ncls` entries, not 256 — the seed only has to distinguish classes,
 * and the alphabet refinement already guarantees the word set is a union of
 * them. It is read ONCE PER SEARCH, off the hot loop entirely.
 *
 * `s1u[]` are the interior start states, one per class-axis context of the
 * context byte; `s0` covers "no context byte exists", which every caller
 * handles with its own branch because the condition differs per machine
 * (`startpos == 0` forward, `end == n` reverse). */
static void emit_seed_table(StrBuf *c, const char *p, const char *tag,
                            const Dfa *d)
{
    sb_printf(c, "    static const short %s_%s[%d] = {", p, tag, d->ncls);
    for (int cl = 0; cl < d->ncls; cl++) {
        if (cl % 16 == 0) sb_puts(c, "\n       ");
        sb_printf(c, " %d,", d->s1u[upc_of_class(d, cl)]);
    }
    sb_puts(c, "\n    };\n");
}

/* ---- [D63] the CANDIDATE-START derivation: one site, two callers ---------
 *
 * A scan-avoidance mechanism has two halves, and D63 rules that exactly one of
 * them is shared. The DERIVATION — which byte VALUES can begin a match, how
 * many there are, whether that is one `memchr` or a 256-entry bitmap walk, and
 * the table for the bitmap case — is the SAME question for every engine, and
 * it lives here. The LOOP INTEGRATION differs structurally (ENG_UNANCH skips
 * WITHIN one scan while parked in its start state; ENG_ATTEMPT advances
 * BETWEEN attempts and composes with the three-way start dispatch) and stays
 * with each engine.
 *
 * The constraint is M2.12's lesson stated as a rule rather than as a warning:
 * "M2.7 forked a second copy, and the fork is exactly how the prefilter and
 * skip loops went missing from the `$` path for a whole milestone". D63
 * charters this as a TOOL — ENG_ATTEMPT's `(?m)^` instance is the first
 * customer and the only one built here, with D8's `^`-on-some-branches shape
 * and partial `\G` named as the next two, both of which are new CALLERS of
 * these three functions rather than new copies of them.
 *
 * THE ONE NEW CASE `(?m)^` ADDS is `offset`. ENG_UNANCH's candidates are
 * positions whose OWN byte is in the set; `(?m)^`'s are positions whose
 * PREDECESSOR is (a line start is the byte after a newline), so the candidate
 * is the found offset plus one. That is a field, not a fork. */
typedef struct {
    uint8_t set[256];   /* the candidate byte values */
    int     count;      /* how many */
    int     byte;       /* the single value when count == 1 */
    bool    usable;     /* a PROPER subset: worth filtering on at all */
    bool    use_memchr; /* usable and a single value */
    int     offset;     /* candidate position = found offset + offset */
} CandSet;

static void cand_derive(CandSet *cs, const uint8_t set[256], int offset)
{
    memcpy(cs->set, set, 256);
    cs->count = 0;
    cs->byte = 0;
    cs->offset = offset;
    for (int b = 0; b < 256; b++)
        if (cs->set[b]) { cs->count++; cs->byte = b; }
    /* NEITHER EXTREME IS FILTERABLE, and the two are different failures: an
     * empty set means the caller has already proved something stronger than a
     * prefilter (its own early-out), and a full one means every position is a
     * candidate, so the filter is pure cost. */
    cs->usable = cs->count > 0 && cs->count < 256;
    cs->use_memchr = cs->usable && cs->count == 1;
}

/* ENG_UNANCH's caller: the bytes on which the start state does not stay put —
 * i.e. the bytes that ADVANCE the pattern. A run of bytes outside this set
 * leaves the machine parked in `st`, so the scan may jump over it. */
static void cand_from_escapes(CandSet *cs, const Dfa *d, int st)
{
    uint8_t set[256];
    for (int b = 0; b < 256; b++)
        set[b] = (uint8_t)(d->st[st].tr[d->clsmap[b]] != st);
    cand_derive(cs, set, 0);
}

/* ENG_ATTEMPT's caller ([M6.2] wave C): the PREDECESSOR bytes after which an
 * attempt can still be alive. An attempt at `start > 0` enters
 * `s1u[upc_of_class(s[start-1])]`, so a predecessor byte whose seeded start
 * state is DEAD cannot begin a match and the attempt loop may skip it.
 *
 * This is `(?m)^`'s candidate set without naming `(?m)^` anywhere: for
 * `(?m)^ERROR` only the UPC_NL seed is live, so the set is the newline
 * definition and the derivation picks `memchr`; for a pattern with no
 * BOT-family node every seed is live, the set is all 256 and `usable` is
 * false, so nothing is emitted. `\b`-only patterns land there too — both
 * their seeds are live — which is why this costs wave B's artifacts nothing.
 *
 * `start == 0` is a candidate unconditionally (it enters `s0`, a different
 * state entirely) and every caller handles it with its own branch. */
static void cand_from_live_seeds(CandSet *cs, const Dfa *d)
{
    uint8_t set[256];
    for (int b = 0; b < 256; b++)
        set[b] = (uint8_t)(d->s1u[upc_of_class(d, d->clsmap[b])] >= 0);
    cand_derive(cs, set, 1);
}

static void cand_emit_table(StrBuf *c, const char *p, const char *tag,
                            const CandSet *cs)
{
    emit_u8_table(c, p, tag, cs->set, 256);
}

/* Does ENG_ATTEMPT get a candidate-start prefilter, and what is it? ONE
 * derivation with TWO readers — emit_attempt, which emits the loop, and
 * pcrec_emit_prologue, which has to decide about `#include <string.h>` before
 * any body exists. A second copy of this test in the prologue is how the
 * artifact would end up calling `memchr` without declaring it. */
static bool attempt_cand(const Dfa *d, CandSet *cs)
{
    /* A fully-anchored pattern already runs ONE attempt (`start_max` is the
     * literal 0), so there is nothing between attempts to skip. */
    bool anchored = true;
    for (int u = 0; u < UPC_N; u++) if (d->s1u[u] >= 0) anchored = false;
    if (d->n == 0 || anchored) return false;
    cand_from_live_seeds(cs, d);
    /* THE MEMCHR FORM ONLY, and that is a deliberate scope line rather than an
     * oversight. D63 charters the derivation as a tool and says to build ONLY
     * the `(?m)^` instance now; MEASURED against today's construct set, that
     * instance's candidate set is always a SINGLE byte — a seeded start state
     * is dead only when all three of its class views are empty, which `(?m)^`
     * achieves (nothing passes without a newline to the left) and `\b`/`\B`
     * structurally cannot (their truth needs BOTH sides, so some view always
     * survives). So the bitmap loop integration would be EMITTED CODE NO
     * PATTERN REACHES, and shipping an untested emitted loop is worse than
     * shipping none.
     *
     * The DERIVATION still handles the bitmap case (`cand_derive` computes it
     * and `cand_emit_table` emits it — ENG_UNANCH's caller uses exactly that
     * path today), so D63's next instance adds a LOOP, not a second
     * derivation. D8's `^`-on-some-branches shape is that instance: its
     * candidate set is a first-byte set at offset 0, which is both multi-byte
     * and a different bound, and D63 gates it on its own measurement. */
    return cs->usable && cs->use_memchr;
}

/* ---- ENG_UNANCH: table-driven forward + reverse (D7) ---- */

/* M2.1 self-loop skip: pick up to 4 states (excluding `exclude`) that stay
 * put on >= 192 of 256 bytes — their scan degenerates to a SIMD-friendly
 * skip loop. Motivated by compare case h (`.*=.*`): the post-'=' state
 * self-loops on everything but '\n' in both machines.
 *
 * M2.10 tried replacing this absolute byte count with a fraction of the
 * state's LIVE bytes, so that narrow-alphabet patterns like `[01]*1[01]{8}`
 * (2 live bytes, 100% stay) would qualify — R2-A5 had described that case as
 * having "no skip-eligible states". The reasoning was sound and the result
 * was a REGRESSION: it gives case (f) one reverse skip table and measures
 * 158.6/159.1 -> 118.7 MB/s on the compare harness and 159.1/157.5 ->
 * 115.9/115.8 MB/s on bdriver, spreads 1.01-1.02x, i.e. ~27% slower on the
 * exact case it was meant to fix. Reverted; see D13 and the 2026-08-09
 * journal entry. Do not re-attempt without measuring the REVERSE machine
 * specifically — the suspicion is that a backward byte-at-a-time skip loop
 * loses to the reverse table walk, but that is untested. */
static int pick_skip_states(const Dfa *d, int exclude, int out[4])
{
    int cls_size[256] = {0};
    for (int b = 0; b < 256; b++) cls_size[d->clsmap[b]]++;
    int nout = 0;
    for (int pass = 0; pass < 4; pass++) {
        int best = -1, bestcnt = 191;
        for (int i = 0; i < d->n; i++) {
            if (i == exclude) continue;
            /* [M6.2 wave B] A STATE WHOSE ACCEPT DEPENDS ON THE NEXT BYTE IS
             * NOT SKIP-ELIGIBLE, and this is the D11-rule-1 hazard §3.6.1
             * describes, resolved by declining rather than by intersecting.
             *
             * A skip advances without consulting accept flags and records
             * only its LANDING position. That is sound while the accept bit
             * is constant across the run — which the pre-wave scalar accept
             * made true unconditionally, and a class-indexed one does not.
             * The concrete loss: a forward skip whose run's bytes all accept
             * landing on a byte whose class does not, with `last` wanting the
             * LARGEST accepting position, throws away every position it just
             * passed.
             *
             * §3.6.1 argues from §3.5 that `\b` cannot reach this, on the
             * ground that a skip set is a union of classes and therefore
             * pins next-is-word across the run. THE SECOND HALF DOES NOT
             * FOLLOW: a union of classes may perfectly well contain both word
             * and non-word classes (a state that stays put on both `a` and
             * ` ` has exactly such a stay set). So the argument is not
             * available and this declines instead. Declining is always safe
             * and costs nothing on any pattern without a next-byte-sensitive
             * accept — i.e. nothing in the pre-wave corpus, where this test
             * is false at every state. */
            if (state_acc_varies(&d->st[i])) continue;
            bool taken = false;
            for (int k = 0; k < nout; k++)
                if (out[k] == i) taken = true;
            if (taken) continue;
            int stay = 0;
            for (int cl = 0; cl < d->ncls; cl++)
                if (d->st[i].tr[cl] == i) stay += cls_size[cl];
            if (stay > bestcnt) { bestcnt = stay; best = i; }
        }
        if (best < 0) break;
        out[nout++] = best;
    }
    return nout;
}

static void emit_stay_table(StrBuf *c, const char *p, const char *tag,
                            int idx, const Dfa *d)
{
    uint8_t stay[256];
    for (int b = 0; b < 256; b++)
        stay[b] = (uint8_t)(d->st[idx].tr[d->clsmap[b]] == idx);
    char name[32];
    snprintf(name, sizeof(name), "%s%d", tag, idx);
    emit_u8_table(c, p, name, stay, 256);
}

/* M2.7 put `$`-bearing patterns on this engine; M2.12 gave them back the
 * scan-avoidance M2.7 had traded away. Both live in ONE emitter on purpose:
 * M2.7 forked a second copy, and the fork is exactly how the prefilter and
 * skip loops went missing from the `$` path for a whole milestone.
 *
 * EOL handling: both machines switch to a state's EOL variant exactly at EOL
 * positions (end of subject, or before a final newline), guarded by
 * `pos + 1 >= n` — false for every byte but the last two, so the scan stays a
 * tight table walk.
 *
 * Scan avoidance under EOL (M2.12): a prefilter or self-loop skip advances
 * `pos` WITHOUT consulting accept flags, which is unsound when a state can
 * accept at an EOL position. The fix is to bound every skip at `n - 1` rather
 * than `n` and let the stepped loop handle the last two positions. That also
 * keeps the EOL-variant lookup correct for free: a skip can only run when
 * `pos + 1 < n`, and in that case `est == st` by construction, so the state
 * used for the transition is never stale. The forward prefilter additionally
 * must NOT keep its `return 0` early-out, since the start state's EOL variant
 * may still accept at n-1 or n. */
static void emit_unanchored(Ctx *cx, const char *fn, const char *storage)
{
    Job *job = cx->job;
    Dfa *fd = &job->dfa, *rd = &job->rdfa;
    StrBuf *c = &job->csb;
    const char *p = cx->opt->prefix;

    bool eol  = dfa_has_eolvar(fd) || dfa_has_eolvar(rd);
    /* [M6.2 wave A] `\z`'s third view. `views` is the flag every site below
     * that used to read `eol` now reads: what the D11 bound and the
     * evaluation ORDER protect is "a state can accept at a position a skip
     * would pass", and an END view creates exactly that situation at
     * `pos == n`. Both are false for every pattern the pre-wave corpus
     * contains, so `views == eol` there and nothing moves. */
    bool endv = dfa_has_endvar(fd) || dfa_has_endvar(rd);
    /* Does the emitted text carry the `est`/`erst` POSITION-view indirection
     * at all? Only `$`/`\Z`/`\z` create it. `\b` does not: its axis is the
     * byte class, which the transition lookup already indexes by. */
    bool viewsel = eol || endv;

    /* [M6.2 wave B] the two class-axis facts, kept apart on purpose because
     * they gate different things:
     *   `wctx`  — this machine carries a word context at all, so mechanism
     *             4's start seeding applies (§3.8) and the D11 evaluation
     *             ORDER must be the views one;
     *   `facc2`/`racc2` — some state's accept actually varies with the next
     *             byte, so §3.6's class-indexed accept table is needed. A
     *             pattern can have the first without the second. */
    bool wctx  = fd->clsctx || rd->clsctx;
    bool facc2 = dfa_has_clsacc(fd);
    bool racc2 = dfa_has_clsacc(rd);

    /* `views` is the D11 flag: "a state can accept at a position a skip would
     * pass, or the position a skip lands on is not the position whose accept
     * was evaluated". The EOL and END views create that at the last two
     * positions; a word context creates it everywhere, so it joins. */
    bool views = viewsel || wctx;

    int fs = fd->s0;   /* no asserts -> s0 == s1 */
    int rs = rd->s0;
    /* MECHANISM 4 is only EMITTED where it can change an answer. With the two
     * interior start states interned to the same state the seed table would
     * be a constant column, so the pre-wave constant start is emitted instead
     * — which is also what keeps every existing artifact's first lines
     * unmoved. */
    bool fseed = dfa_needs_seed(fd);
    bool rseed = dfa_needs_seed(rd);

    emit_search_head(c, fn, storage);

    if (fs < 0 || rs < 0) {
        sb_puts(c, "    (void)s; (void)n; (void)startpos; (void)caps;\n"
                   "    return 0;\n}\n");
        return;
    }

    /* start-state prefilter analysis: bytes that advance the pattern.
     *
     * [M6.2 wave B] `start_acc` is "accepts on ANY class", the OR over the
     * class views, and §3.6.1 is emphatic about why. The prefilter skips runs
     * of bytes at which the machine provably stays parked in `fs`; if `fs`
     * accepts on SOME classes and this read one bit, a pattern like `\bx*`
     * would keep its `memchr('x')` and jump straight past the empty matches
     * it owes at every word boundary. MEASURED cell, through the find-all
     * loop: `\bx*` on `'a x'` is [(0,0), (1,1), (2,3), (3,3)] and a
     * one-bit `start_acc` reports only (2,3).
     *
     * It is also the analysis for the start state's OTHER seeded forms —
     * `s1u[]` under mechanism 4 — so those are OR'd in too: with
     * `startpos > 0` the machine begins in one of those, and a prefilter
     * decision taken from `s0` alone would be a decision about a state the
     * search may never occupy.
     *
     * [M6.2 wave C] THE WIDENING IS BELT-AND-BRACES, NOT LOAD-BEARING, and
     * that is a correction to the paragraph above — §3.6.1's `\bx*` cell does
     * NOT lose three of four matches under a one-bit read. The reason is the
     * argument this file already makes for the `last == (size_t)-1` gate
     * thirty lines down: D3's accept-pruning cuts the unanchored start
     * self-loop out of every accepting closure, so a class the start state
     * ACCEPTS on cannot transition back to the start state — it ESCAPES —
     * so the prefilter's stay set never contains it and the skip never passes
     * an accepting position.
     *
     * MEASURED, this lane: narrowing to `fd->st[fs].up[UPC_PLAIN].accept`
     * changes 21 corpus artifacts and 0 answers, over 2,247 find-all cells
     * (21 patterns x 107 subjects). Keep the widening — it is free and it is
     * the honest reading of "accepts on any class" — but do not cite it as a
     * premise, and note that it therefore ships NO sabotage row: a check with
     * no failing direction is exactly what this file's own neighbouring
     * comment warns about. */
    bool start_acc = state_acc_any(&fd->st[fs]);
    if (fseed) {
        for (int u = 0; u < UPC_N; u++)
            start_acc = start_acc || state_acc_any(&fd->st[fd->s1u[u]]);
    }
    /* [D63] THE SHARED DERIVATION, this engine's caller. */
    CandSet fcand;
    cand_from_escapes(&fcand, fd, fs);
    /* "can neither accept nor ever leave the start state" is only a proof
     * that nothing matches when the start state has no EOL view. `$` alone is
     * exactly the counter-example: it never leaves fs and facc[fs] is 0, but
     * its EOL variant accepts. */
    /* [M6.2 wave B] `!fseed` joins the conjunction: the proof below is about
     * the ONE start state `fs`, and under mechanism 4 a search at
     * `startpos > 0` begins in a different state whose escapes and accepts
     * this analysis never looked at. With `fseed` false there is only one
     * start state and the pre-wave argument is unchanged. */
    if (fcand.count == 0 && !start_acc && !fseed && fd->st[fs].eolvar < 0 &&
        fd->st[fs].endvar < 0) {
        sb_puts(c, "    (void)s; (void)n; (void)startpos; (void)caps;\n"
                   "    return 0;\n}\n");
        return;
    }
    /* The prefilter stays valid under EOL because it is BOUNDED AT n-1: it
     * only ever skips non-EOL positions at which the machine provably stays
     * parked in fs.
     *
     * The `last == (size_t)-1` gate on the emitted `if` is NOT part of that
     * argument, and this comment used to present the two as jointly
     * load-bearing (R3.2 critic). The gate is redundant given D3's priority
     * pruning: the unanchored start self-loop is the LOWEST-priority thread,
     * so it is pruned out of every accepting state, an accepting state's
     * successors can therefore never be `fs`, and `last` is only ever set from
     * an accepting view — so `st == fs` already implies `last == -1`. Two
     * independent critics attacked the gate and neither could build a witness:
     * deleting it produced 0 divergences over 8.0M oracle-checked comparisons
     * and 0 failures across the whole .rxt corpus.
     *
     * Keep the gate — it is free belt-and-braces — but do not cite it as a
     * premise. Presenting a redundant condition and a load-bearing one as the
     * same claim is how someone eventually "simplifies away" the wrong half. */
    bool prefilter = !start_acc && fcand.usable;
    bool use_memchr = prefilter && fcand.use_memchr;

    int fskip[4], rskip[4];
    int nfskip = pick_skip_states(fd, fs, fskip);
    int nrskip = pick_skip_states(rd, -1, rskip);

    emit_u8_table(c, p, "fcls", fd->clsmap, 256);
    emit_tr_table(c, p, "ftr", fd);
    emit_acc_table(c, p, "facc", fd);
    if (facc2) emit_acc_cls_table(c, p, "facc2", fd);
    if (fseed) emit_seed_table(c, p, "fseed", fd);
    if (eol)  emit_eol_table(c, p, "fev", fd);
    if (endv) emit_end_table(c, p, "fendv", fd);
    if (prefilter && !use_memchr)
        cand_emit_table(c, p, "first", &fcand);
    for (int k = 0; k < nfskip; k++)
        emit_stay_table(c, p, "fs", fskip[k], fd);
    emit_u8_table(c, p, "rcls", rd->clsmap, 256);
    emit_tr_table(c, p, "rtr", rd);
    emit_acc_table(c, p, "racc", rd);
    if (racc2) emit_acc_cls_table(c, p, "racc2", rd);
    if (rseed) emit_seed_table(c, p, "rseed", rd);
    if (eol)  emit_eol_table(c, p, "rev", rd);
    if (endv) emit_end_table(c, p, "rendv", rd);
    for (int k = 0; k < nrskip; k++)
        emit_stay_table(c, p, "rs", rskip[k], rd);

    /* Under EOL the scan reads the accept flag and the transition row through
     * `est`/`erst` (the EOL view at the last two positions); otherwise those
     * collapse to `st`/`rst` and gcc sees exactly the pre-M2.7 loop. */
    const char *fsrc = viewsel ? "est" : "st";
    const char *rsrc = viewsel ? "erst" : "rst";
    /* Every skip must stop at n-1 so a state that accepts only at EOL is
     * never skipped past; below n-1 the EOL view is unreachable, which is
     * also why `est` cannot be stale after a skip. */
    const char *fbound = views ? "pos + 1 < n" : "pos < n";

    sb_puts(c,   "    size_t pos = startpos;\n"
                 "    size_t last = (size_t)-1;\n");
    if (fseed) {
        /* MECHANISM 4, forward initialization (§3.8.2). ONCE PER SEARCH, off
         * the loop entirely — the emitted hot path is unchanged.
         *
         * `s[startpos-1]` is a byte IN THE SUBJECT and OUTSIDE THE SEARCH
         * WINDOW, which is the whole point: `<prefix>_search` searches
         * `s[startpos, n)`, and a leading `\b` at `startpos` is a question
         * about the byte before it. A constant start state encodes exactly
         * one answer — "the context here is start-of-subject" — which is the
         * assumption a SLICE makes, not the assumption this API's contract
         * makes. MEASURED against libpcre2 10.46: 5 of §3.8.1's 10 cells
         * differ, in both directions, so no conservative shortcut exists.
         *
         * `startpos == 0` genuinely IS start-of-subject, where the constant
         * is right, which is what the ternary's else arm is.
         *
         * THE RANGE GUARD MOVES ABOVE THIS LINE, and it has to: the pre-wave
         * `int st = <const>;` could not read the subject, so `startpos > n`
         * was checked after it. Here the initializer dereferences
         * `s[startpos - 1]`, and on an out-of-range `startpos` that is an
         * out-of-bounds read in EMITTED code — K27's class. With the guard
         * first, `startpos <= n`, and `startpos > 0` then implies `n > 0`,
         * hence `s != NULL` under match_api.md §3.1's legal empty subject. */
        sb_puts(c,   "    if (startpos > n) return 0;\n");
        sb_printf(c, "    int st = startpos ? %s_fseed[%s_fcls[s[startpos - 1]]]"
                     " : %d;\n", p, p, fs);
    } else {
        sb_printf(c, "    int st = %d;\n", fs);
        sb_puts(c,   "    if (startpos > n) return 0;\n");
    }
    sb_puts(c,   "    for (;;) {\n");
    /* Under EOL, scan avoidance must run BEFORE the accept/EOL evaluation, so
     * that evaluation sees the position the loop is really at: a skip bounded
     * at n-1 can LAND on n-1, and evaluating first would consume that byte
     * without ever taking its EOL view (53 divergences, see D11).
     *
     * Without EOL the order is a free choice semantically — every position a
     * skip passes has the same state and so the same accept bit — but NOT a
     * free choice in speed. Hoisting the prefilter above the accept check
     * costs 43% on `[01]*1[01]{8}` (158.4 -> 90.8 MB/s, 0 skip states, tight
     * spreads), so the non-EOL path keeps the original order. This asymmetry
     * is the whole reason the flag exists; do not "simplify" it away. */
    if (!views)
        sb_printf(c, "        if (%s_facc[st]) last = pos;\n", p);
    {
        const char *kw = "if";
        if (prefilter) {
            sb_printf(c, "        if (st == %d && last == (size_t)-1) {\n", fs);
            if (use_memchr) {
                if (views) {
                    /* no early `return 0`: the EOL view may still accept at
                     * n-1 or n, so fall through to the stepped loop instead */
                    sb_puts(c,   "            if (pos + 1 < n) {\n");
                    sb_printf(c, "                const void *q = memchr(s + pos, %d, n - 1 - pos);\n", fcand.byte);
                    sb_puts(c,   "                pos = q ? (size_t)((const unsigned char *)q - s) : n - 1;\n"
                                 "            }\n");
                } else {
                    /* [K27] The `pos >= n` guard is the FIX, and it is not
                     * defensive padding: docs/spec/match_api.md §3.1 makes
                     * (s == NULL, n == 0) a LEGAL subject, and on it this
                     * line used to call memchr(NULL, c, 0) — technical UB in
                     * EMITTED code, which a user compiling a generated
                     * matcher under their own -fsanitize=undefined sees
                     * pcrec's name on. It changes no answer: memchr over a
                     * zero-length range returns NULL, so the guarded early
                     * `return 0` is exactly the branch the unguarded form
                     * reached one line later. The EOL arm above needs no
                     * such guard — its own `pos + 1 < n` bound already
                     * implies n > 0, hence s != NULL. */
                    sb_puts(c,   "            if (pos >= n) return 0;\n");
                    sb_printf(c, "            const void *q = memchr(s + pos, %d, n - pos);\n", fcand.byte);
                    sb_puts(c,   "            if (!q) return 0;\n"
                                 "            pos = (size_t)((const unsigned char *)q - s);\n");
                }
            } else {
                sb_printf(c, "            while (%s && !%s_first[s[pos]]) pos++;\n", fbound, p);
                if (!views) sb_puts(c, "            if (pos >= n) return 0;\n");
            }
            sb_puts(c, "        }\n");
            kw = "else if";
        }
        for (int k = 0; k < nfskip; k++) {
            int K = fskip[k];
            sb_printf(c, "        %s (st == %d) {\n", kw, K);
            sb_printf(c, "            while (%s && %s_fs%d[s[pos]]) pos++;\n", fbound, p, K);
            /* With the accept check ahead of us (non-EOL order) the skipped
             * run's final position would otherwise go unrecorded; under EOL
             * the check runs after the skip and already covers it. */
            if (!views && fd->st[K].up[UPC_PLAIN].accept)
                sb_puts(c, "            last = pos;\n");
            sb_puts(c, "        }\n");
            kw = "else if";
        }
    }
    if (viewsel)
        emit_view_select(c, p, eol, endv, "pos", "st", "est", "fev", "fendv",
                         "        ");
    if (views && !facc2)
        sb_printf(c, "        if (%s_facc[%s]) last = pos;\n", p, fsrc);
    if (facc2) {
        /* §3.6.2's COMPOSITION RULE, and the `pos == n` arm is the half that
         * is easy to get wrong. The accept bit is class-indexed at every
         * position that HAS a next byte and SCALAR at the one that does not:
         * out-of-subject counts as non-word, which is a property of the
         * POSITION, and the base accept already is that bit. Indexing the
         * wide table with some class at `pos == n` would be asking what the
         * accept is when the next byte is "whatever byte happens to sit in
         * that equivalence class", which is meaningless there.
         *
         * The guard is also what makes `s[pos]` below unreachable at
         * `pos == n`. The class is computed ONCE into `cl` and shared with
         * the transition — the byte is read once, and the structural check
         * for this rule has a single named thing to look at rather than an
         * expression to parse. */
        sb_printf(c, "        if (pos >= n) {\n"
                     "            if (%s_facc[%s]) last = pos;\n"
                     "            break;\n"
                     "        }\n", p, fsrc);
        sb_printf(c, "        {\n"
                     "            unsigned cl = %s_fcls[s[pos]];\n"
                     "            if (%s_facc2[%s * %d + cl]) last = pos;\n"
                     "            st = %s_ftr[%s * %d + cl];\n"
                     "            pos++;\n"
                     "        }\n",
                  p, p, fsrc, fd->ncls, p, fsrc, fd->ncls);
    } else {
        sb_puts(c,   "        if (pos >= n) break;\n");
        sb_printf(c, "        st = %s_ftr[%s * %d + %s_fcls[s[pos++]]];\n",
                  p, fsrc, fd->ncls, p);
    }
    sb_puts(c,   "        if (st < 0) break;\n"
                 "    }\n"
                 "    if (last == (size_t)-1) return 0;\n"
                 "    {\n"
                 "        size_t end = last;\n"
                 "        size_t sfound = (size_t)-1;\n"
                 "        size_t pp = end;\n");
    if (rseed) {
        /* MECHANISM 4, REVERSE INITIALIZATION (§3.8.3). The reverse walk
         * starts at `pp = end` and consumes LEFTWARD, so the byte that seeds
         * a TRAILING `\b`'s context is `s[end]` — one to the RIGHT of where
         * the walk begins, in the subject, and never consumed by the walk at
         * all. That site did not exist before this wave, and it cannot be a
         * compile-time constant the way the forward one nearly was: `end` is
         * produced by the forward loop, so this read is data-dependent and
         * has to happen HERE, after it.
         *
         * `end == n` is the out-of-subject case — no byte to the right —
         * which is a NON-word context and therefore the pre-wave constant. */
        sb_printf(c, "        int rst = (end < n) ? %s_rseed[%s_rcls[s[end]]]"
                     " : %d;\n", p, p, rs);
    } else {
        sb_printf(c, "        int rst = %d;\n", rs);
    }
    sb_puts(c,   "        for (;;) {\n");
    if (!views)
        sb_printf(c, "            if (%s_racc[rst]) sfound = pp;\n", p);
    {   /* same ordering rule as the forward loop, and `sfound` wants the
         * SMALLEST accepting position, which is where a reverse skip stops */
        const char *kw = "if";
        for (int k = 0; k < nrskip; k++) {
            int K = rskip[k];
            /* pp only ever DECREASES, so one entry guard is enough to keep the
             * whole skip below the EOL region */
            sb_printf(c, "            %s (rst == %d%s) {\n", kw, K,
                      views ? " && pp + 1 < n" : "");
            sb_printf(c, "                while (pp > startpos && %s_rs%d[s[pp - 1]]) pp--;\n", p, K);
            if (!views && rd->st[K].up[UPC_PLAIN].accept)
                sb_puts(c, "                sfound = pp;\n");
            sb_puts(c, "            }\n");
            kw = "else if";
        }
    }
    if (viewsel)
        emit_view_select(c, p, eol, endv, "pp", "rst", "erst", "rev", "rendv",
                         "            ");
    if (views && !racc2)
        sb_printf(c, "            if (%s_racc[%s]) sfound = pp;\n", p, rsrc);
    if (racc2) {
        /* MECHANISM 4, REVERSE TERMINATION (§3.8.3.1) — the site whose
         * absence is a LOST MATCH, and the site whose PLACEMENT is the whole
         * of R30 N9.
         *
         * At `pp == startpos` the walk breaks before ever reading
         * `s[startpos-1]`, so a LEADING `\b`/`\B` at the match start is
         * otherwise evaluated with no left context — the walk silently
         * assuming start-of-subject. `\b` is safe BY ACCIDENT there (its
         * blind assumption coincides with the cases the forward pass lets
         * through), which is exactly why a leading-`\b` sweep reports clean
         * against a design that throws matches away. `\B` inverts it: `\Bfoo`
         * on "xfoo" at startpos 1 is (1,4) in libpcre2 and no-match blind.
         *
         * ATTACHED TO THE BOUNDARY BREAK, NOT A PEELED EPILOGUE BELOW THE
         * LOOP. This loop has TWO exits — this one and the dead-state `rst <
         * 0` below — and code placed after the loop would run on both. On the
         * dead-state exit `pp > startpos` and `rst < 0`, so an epilogue would
         * record `sfound` at a position the walk never reached (a WRONG
         * ANSWER, worse than a lost match) and would index the accept table
         * with a NEGATIVE state (an out-of-bounds read in emitted code,
         * K27's class). This arm is entered only when `pp <= startpos` and
         * `rst` is live, so both are unreachable by construction.
         *
         * `pp == startpos` happens exactly once and the loop already tests
         * for it, so this costs one emitted site and ZERO per-byte work.
         *
         * `startpos == 0` is out-of-subject to the left — non-word — hence
         * the SCALAR accept, the mirror of §3.6.2's `pos == n` rule. Note the
         * pleasing asymmetry: the forward machine's terminal boundary needs a
         * scalar accept because no byte exists past `n`; this one needs a
         * CONTEXT-INDEXED accept because the byte exists and is merely
         * outside the window. */
        sb_printf(c, "            if (pp <= startpos) {\n"
                     "                if (startpos ? %s_racc2[%s * %d + "
                     "%s_rcls[s[startpos - 1]]]\n"
                     "                             : %s_racc[%s]) sfound = pp;\n"
                     "                break;\n"
                     "            }\n",
                  p, rsrc, rd->ncls, p, p, rsrc);
        sb_printf(c, "            {\n"
                     "                unsigned rcl = %s_rcls[s[pp - 1]];\n"
                     "                if (%s_racc2[%s * %d + rcl]) sfound = pp;\n"
                     "                rst = %s_rtr[%s * %d + rcl];\n"
                     "                pp--;\n"
                     "            }\n",
                  p, p, rsrc, rd->ncls, p, rsrc, rd->ncls);
    } else {
        sb_puts(c,   "            if (pp <= startpos) break;\n");
        sb_printf(c, "            rst = %s_rtr[%s * %d + %s_rcls[s[--pp]]];\n",
                  p, rsrc, rd->ncls, p);
    }
    sb_puts(c,   "            if (rst < 0) break;\n"
                 "        }\n"
                 "        if (sfound == (size_t)-1) return 0;\n"
                 "        if (caps) { caps[0][0] = (ptrdiff_t)sfound; caps[0][1] = (ptrdiff_t)end; }\n"
                 "        return 1;\n"
                 "    }\n"
                 "}\n");
}

/* ---- ENG_ATTEMPT: computed-goto per-start attempt loop ---- */

static void emit_target(StrBuf *c, const char *p, int tgt)
{
    if (tgt < 0) sb_printf(c, "&&%s_dead", p);
    else         sb_printf(c, "&&%s_s%d", p, tgt);
}

static void emit_attempt(Ctx *cx, const char *fn, const char *storage)
{
    Job *job = cx->job;
    Dfa *d = &job->dfa;
    StrBuf *c = &job->csb;
    const char *p = cx->opt->prefix;

    emit_search_head(c, fn, storage);

    if (d->n == 0) {
        /* no live start state: the pattern matches nothing */
        sb_puts(c, "    (void)s; (void)n; (void)startpos; (void)caps;\n"
                   "    return 0;\n}\n");
        return;
    }

    emit_u8_table(c, p, "cls", d->clsmap, 256);

    /* [M6.2 wave B] this engine's share of §3.6 and §3.8. `acc2` is the
     * class-indexed accept, needed wherever a state's accept depends on the
     * next byte; `seed` is mechanism 4's PER-ATTEMPT start dispatch.
     *
     * ON THIS ENGINE THE SEED IS NOT ONCE PER SEARCH (§3.8.2's own note).
     * ENG_ATTEMPT re-initializes at EVERY attempt — n+1 of them — and only
     * the first begins at `startpos`; the rest begin at `start > startpos`,
     * where the context byte `s[start-1]` is squarely INSIDE the window. So
     * the same dispatch serves both the outside-the-window case this wave
     * exists for and the ordinary interior one, and it composes with the
     * `start == 0` selection this engine already made rather than adding a
     * second. */
    bool acc2 = dfa_has_clsacc(d);
    bool seed = dfa_needs_seed(d);
    /* [M6.2 wave C] the class-axis context of a position whose next byte is a
     * newline: the EOL arms below know that byte from their own entry test,
     * so their accept bit is a COMPILE-TIME constant rather than a table read
     * (§3.6.2's composition with the position axis, both indices known). */
    int unl = upc_of_newline(d);
    if (acc2) emit_acc_cls_table(c, p, "acc2", d);

    for (int i = 0; i < d->n; i++) {
        sb_printf(c, "    static const void *const %s_t%d[%d] = { ",
                  p, i, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->st[i].tr[cl]);
        }
        sb_puts(c, " };\n");
    }
    if (seed) {
        sb_printf(c, "    static const void *const %s_seed[%d] = { ",
                  p, d->ncls);
        for (int cl = 0; cl < d->ncls; cl++) {
            if (cl) sb_puts(c, ", ");
            emit_target(c, p, d->s1u[upc_of_class(d, cl)]);
        }
        sb_puts(c, " };\n");
    }

    /* [D63] THE CANDIDATE-START PREFILTER, this engine's first instance.
     * Derived by the shared helper; only the LOOP INTEGRATION is here. */
    CandSet cand;
    bool cpre = attempt_cand(d, &cand);

    /* anchored fast path (M2.1): if every interior start state is dead, every
     * branch requires ^, so only start == 0 can ever match.
     * [M6.2 wave B] there is now more than one interior start state, and the
     * fast path needs ALL of them dead — `(?:^|\b)x` has a live one and a
     * dead one. [M6.2 wave C] `(?m)^x` has exactly one live (the newline
     * context), which is what D63's candidate prefilter above is for: the
     * fast path does not apply, and every attempt but the line starts is
     * still provably dead. */
    bool anchored = true;
    for (int u = 0; u < UPC_N; u++) if (d->s1u[u] >= 0) anchored = false;
    sb_printf(c, "    size_t start;\n"
                 "    const size_t start_max = %s;\n",
              anchored ? "0 /* fully ^-anchored */" : "n");
    sb_puts(c, "    for (start = startpos; start <= start_max; start++) {\n");
    if (cpre) {
        /* [D63] LOOP INTEGRATION, ENG_ATTEMPT's shape: an advance BETWEEN
         * attempts, not a skip inside one. It composes with the three-way
         * start dispatch below rather than replacing it — the dispatch still
         * decides WHICH start state an attempt enters; this only skips the
         * starts whose state would be the dead one.
         *
         * `start == 0` is never skipped: it enters `s0`, which this
         * derivation says nothing about (assertions_design.md §3.7.2's
         * "offset 0 or immediately after a newline" is exactly the shape of
         * the two branches here).
         *
         * SOUNDNESS is by construction rather than by argument: a skipped
         * `start` would have jumped straight to the dead label and fallen
         * through `%s_done` with `last == (size_t)-1`, i.e. done nothing at
         * all. This is the one scan-avoidance mechanism in the file that
         * needs no D11 bound, because it skips whole ATTEMPTS rather than
         * positions within a scan, and an attempt records nothing until it
         * runs.
         *
         * THE GUARD READS `s[start - offset]`, IN RANGE BECAUSE `offset >= 1`
         * here: a predecessor-byte candidate set (D63's one new case) and
         * `start > 0` together put that read at `start - 1 <= n - 1`. A
         * future ENG_ATTEMPT caller with `offset == 0` would be reading
         * `s[start]` and needs its own `start < n` bound — which is exactly
         * why the derivation carries `offset` as data instead of the two
         * shapes being two functions.
         *
         * The MEASURED target is the linear non-crossing arm (§3.7.2, R30
         * N3): `(?m)^ERROR` dies in a byte or two per attempt, so the cost is
         * visiting every offset, and this is what removes it. The quadratic
         * crossing arm (§3.7.1) is NOT rescued and D63 accepts that —
         * DD-7's reverse BOT variant is the sequenced fix. */
        sb_printf(c, "        if (start > 0 && s[start - %d] != %d) {\n"
                         "            const void *q = memchr(s + start, %d, "
                         "n - start);\n"
                         "            if (!q) break;\n"
                         "            start = (size_t)"
                         "((const unsigned char *)q - s) + %d;\n"
                         "        }\n",
                  cand.offset, cand.byte, cand.byte, cand.offset);
    }
    sb_puts(c, "        size_t pos = start;\n"
               "        size_t last = (size_t)-1;\n");

    if (seed) {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_printf(c, " : %s_seed[%s_cls[s[start - 1]]]);\n", p, p);
    } else if (d->s0 == d->s1u[UPC_PLAIN]) {
        sb_puts(c, "        goto ");
        if (d->s0 < 0) sb_printf(c, "*&&%s_dead;\n", p);
        else           sb_printf(c, "*&&%s_s%d;\n", p, d->s0);
    } else {
        sb_puts(c, "        goto *((start == 0) ? ");
        emit_target(c, p, d->s0);
        sb_puts(c, " : ");
        emit_target(c, p, d->s1u[UPC_PLAIN]);
        sb_puts(c, ");\n");
    }

    for (int i = 0; i < d->n; i++) {
        const DState *st = &d->st[i];
        /* labels marked unused: EOL-variant states are entered via their
         * transition tables only, never their own label */
        sb_printf(c, "%s_s%d: __attribute__((unused));\n", p, i);
        /* [M6.2 wave B] Does THIS state's accept depend on the next byte? A
         * per-state question, not a per-artifact one: a `\b` pattern's
         * artifact typically has a handful of such states and keeps the
         * pre-wave text at every other, which is what makes the byte-identity
         * property hold at state granularity rather than at file granularity. */
        bool wsplit = acc2 && state_acc_varies(st);
        if (wsplit) {
            /* THE ORDER FLIPS, and it has to. The pre-wave arms record the
             * accept and THEN test for `pos >= n`, which is sound while the
             * accept bit is a scalar; here the bit at `pos < n` is a function
             * of `s[pos]`, so the end-of-subject case has to be split off
             * first — it is the one position with no next byte, where §3.6.2
             * makes the accept SCALAR. That test is also what makes the
             * `s[pos]` below unreachable at `pos == n`. */
            int endview = st->endvar >= 0 ? st->endvar
                        : st->eolvar >= 0 ? st->eolvar : i;
            sb_puts(c, "        if (pos == n) {\n");
            if (d->st[endview].up[UPC_PLAIN].accept)
                sb_puts(c, "            last = pos;\n");
            sb_printf(c, "            goto %s_done;\n        }\n", p);
            if (st->eolvar >= 0) {
                /* [M6.2 wave C] THE EOL POSITION'S ACCEPT IS CLASS-INDEXED
                 * TOO, and wave B's note here said otherwise. Its reasoning
                 * was right for its own axis and its conclusion is now wrong:
                 * the byte at an EOL position is `\n`, which is indeed not a
                 * word character — so the WORD axis has nothing to add — but
                 * it IS the newline definition, which is precisely what
                 * `(?m)$` reads. `(?m)a(?:$|\Z)` is the shape that needs
                 * both: the `\Z` half makes an EOL view exist, and the
                 * `(?m)$` half makes that view's accept depend on the very
                 * byte the arm's entry test just pinned.
                 *
                 * Pinned, not read: both indices are compile-time facts here
                 * (the view from the position, the class from the arm's own
                 * `s[pos] == newline` test), so this is a constant, not a
                 * table lookup. `unl` is UPC_PLAIN on any machine without a
                 * newline refinement, which is what keeps the pre-wave text
                 * byte-identical. */
                const DState *v = &d->st[st->eolvar];
                sb_puts(c, "        if (pos + 1 == n && s[pos] == '\\n') {\n");
                if (v->up[unl].accept) sb_puts(c, "            last = pos;\n");
                sb_printf(c, "            goto *%s_t%d[%s_cls[s[pos++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            sb_printf(c, "        {\n"
                         "            unsigned cl = %s_cls[s[pos]];\n"
                         "            if (%s_acc2[%d + cl]) last = pos;\n"
                         "            pos++;\n"
                         "            goto *%s_t%d[cl];\n"
                         "        }\n",
                      p, p, i * d->ncls, p, i);
        } else if (st->endvar >= 0) {
            /* [M6.2 wave A] THE END VIEW (`\z`), reached on ENG_ATTEMPT only
             * when the pattern also carries a `^`/`\A` — `\Aa\z` is the
             * shape. Three arms in position order, most specific first:
             * `pos == n` takes the END view (and then there is no byte to
             * consume, so it always leaves), `pos + 1 == n && s[pos] == '\n'`
             * takes the EOL view, and everything else is the state itself.
             *
             * A state only reaches this branch when its END view DIFFERS from
             * its EOL view (`endvar >= 0` means exactly that, src/ir/dfa.c) —
             * which is why the `endvar < 0` else-branch below is still the
             * pre-wave text, unchanged, for every state of every pattern that
             * has no `\z`. */
            const DState *endv = &d->st[st->endvar];
            sb_puts(c, "        if (pos == n) {\n");
            if (endv->up[UPC_PLAIN].accept)
                sb_puts(c, "            last = pos;\n");
            sb_printf(c, "            goto %s_done;\n", p);
            sb_puts(c, "        }\n");
            if (st->eolvar >= 0) {
                const DState *v = &d->st[st->eolvar];
                sb_puts(c, "        if (pos + 1 == n && s[pos] == '\\n') {\n");
                if (v->up[unl].accept)
                    sb_puts(c, "            last = pos;\n");
                sb_printf(c, "            goto *%s_t%d[%s_cls[s[pos++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last = pos;\n");
            /* both arms above returned or consumed, so pos < n here */
            sb_printf(c, "        goto *%s_t%d[%s_cls[s[pos++]]];\n", p, i, p);
        } else if (st->eolvar >= 0) {
            const DState *v = &d->st[st->eolvar];
            /* at an EOL position ($ passable), use the EOL-view state:
             * its accept is correctly priority-pruned and its table
             * carries the $-gated continuations.
             *
             * [M6.2 wave C] THE TWO EOL POSITIONS CAN CARRY DIFFERENT ACCEPT
             * BITS and the pre-wave text merged them into one arm. They are
             * `pos == n` (no next byte: §3.6.2's SCALAR accept) and
             * `pos + 1 == n && s[pos] == '\n'` (next byte pinned to the
             * newline definition), and until `(?m)$` existed nothing could
             * tell them apart, because the EOL view's accept did not depend
             * on the next byte at all. `(?m)a$` on `"a\n"` is the witness:
             * the view accepts at the newline position and the merged arm
             * would have had to answer for both with one bit.
             *
             * The arms only SPLIT when the two bits differ, so a machine with
             * no newline refinement (`unl == UPC_PLAIN`) emits the pre-wave
             * text character for character. */
            bool a_end = v->up[UPC_PLAIN].accept;
            bool a_nl  = v->up[unl].accept;
            if (a_end == a_nl) {
                sb_puts(c, "        if (pos == n || (pos + 1 == n && "
                           "s[pos] == '\\n')) {\n");
                if (a_end)
                    sb_puts(c, "            last = pos;\n");
                sb_printf(c, "            if (pos >= n) goto %s_done;\n", p);
                sb_printf(c, "            goto *%s_t%d[%s_cls[s[pos++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            } else {
                sb_puts(c, "        if (pos == n) {\n");
                if (a_end)
                    sb_puts(c, "            last = pos;\n");
                sb_printf(c, "            goto %s_done;\n        }\n", p);
                sb_puts(c, "        if (pos + 1 == n && s[pos] == '\\n') {\n");
                if (a_nl)
                    sb_puts(c, "            last = pos;\n");
                sb_printf(c, "            goto *%s_t%d[%s_cls[s[pos++]]];\n",
                          p, st->eolvar, p);
                sb_puts(c, "        }\n");
            }
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last = pos;\n");
            /* not an EOL position implies pos < n: consume directly */
            sb_printf(c, "        goto *%s_t%d[%s_cls[s[pos++]]];\n", p, i, p);
        } else {
            if (st->up[UPC_PLAIN].accept)
                sb_puts(c, "        last = pos;\n");
            sb_printf(c, "        if (pos >= n) goto %s_done;\n", p);
            sb_printf(c, "        goto *%s_t%d[%s_cls[s[pos++]]];\n", p, i, p);
        }
    }

    sb_printf(c, "%s_dead: __attribute__((unused));\n", p);
    sb_printf(c, "%s_done:\n", p);
    sb_puts(c, "        if (__builtin_expect(last != (size_t)-1, 0)) {\n"
               "            if (caps) { caps[0][0] = (ptrdiff_t)start; caps[0][1] = (ptrdiff_t)last; }\n"
               "            return 1;\n"
               "        }\n"
               "    }\n"
               "    return 0;\n"
               "}\n");
}

/* ---- [M4.5b] the shared artifact surface ----------------------------------
 *
 * The VM emitter (src/gen/emit_vm.c) produces an artifact with the SAME
 * prologue, the SAME four entry points and — under the hybrid — the SAME DFA
 * engine body as this file's, differing only in what `<prefix>_search` does
 * with them. Everything below that both emitters need is exported through
 * these five functions rather than copied, which is the M2.12 rule ("M2.7
 * forked a second copy, and the fork is exactly how the prefilter and skip
 * loops went missing from the `$` path for a whole milestone") applied to a
 * fork that has not happened yet. */

void pcrec_gen_names(Ctx *cx, GenNames *g)
{
    g->searchfn     = engine_entry_name(cx);
    g->matchfn      = match_entry_name(cx);
    g->matchcapsfn  = match_caps_entry_name(cx);
    g->infoname     = info_entry_name(cx);
    prefix_upper(cx->opt->prefix, g->upper, sizeof g->upper);
}

void pcrec_emit_abi_types(StrBuf *sb) { emit_rx_abi_types(sb); }

void pcrec_emit_c_string_literal(StrBuf *sb, const char *s, size_t len)
{
    emit_c_string_literal(sb, s, len);
}

/* Everything from the pattern comment through the four declarations, in the
 * exact order pcrec_emit_dfa emitted it before this refactor — including the
 * `#include <string.h>` the unanchored engine's memchr prefilter needs, which
 * the VM's hybrid needs for the same reason and its VM-only mode does not. */
void pcrec_emit_prologue(Ctx *cx, const GenNames *g, int ncaps)
{
    StrBuf *c = &cx->job->csb;
    /* [M6.2 wave C] ENG_ATTEMPT joins the list of bodies that can call
     * `memchr`: D63's candidate-start prefilter. The test is `attempt_cand`,
     * the SAME function emit_attempt uses to decide whether to emit the loop
     * — never a restatement of its condition here. */
    bool dfa_body = cx->job->fit.chosen != ENGM_VM || cx->job->fit.prefilter;
    CandSet acand;
    bool need_string_h =
        dfa_body && (cx->job->engine == PCREC_ENG_UNANCH ||
                     (cx->job->engine == PCREC_ENG_ATTEMPT &&
                      attempt_cand(&cx->job->dfa, &acand) && acand.use_memchr));

    if (cx->opt->header_name)
        emit_header(cx, g->searchfn, g->matchfn, g->matchcapsfn, g->infoname,
                    g->upper, ncaps);

    emit_pattern_comment(c, cx->pat);
    emit_feature_comment(c);
    emit_feature_macros(c);
    emit_altcls_macros(c, g->upper, cx->job->altcls_merges, cx->job->altcls_factored);
    if (cx->opt->header_name) {
        sb_printf(c, "#include \"%s\"\n", cx->opt->header_name);
    } else {
        sb_puts(c, "#include <stddef.h>\n#include <stdint.h>\n\n");
        /* file-scope, shared by every engine here; per-engine below */
        emit_rx_abi_types(c);
        sb_putc(c, '\n');
        emit_ncaps_macros(c, g->upper, ncaps);
        sb_putc(c, '\n');
        emit_search_decl(c, g->searchfn);
        emit_match_decl(c, g->matchfn);
        emit_match_caps_decl(c, g->matchcapsfn);
        emit_info_decl(c, g->infoname);
        sb_putc(c, '\n');
        emit_residual_decls(cx, c);
    }
    if (need_string_h)
        sb_puts(c, "#include <string.h>\n");
    if (cx->opt->flags & PCREC_EMIT_MAIN)
        sb_puts(c, "#include <stdio.h>\n#include <string.h>\n");
    sb_puts(c, "\n");
}

