/* [M6.3] the sort key for rx_info.groups: strcmp on the NAME. Chosen to
 * match PCRE2's own PCRE2_INFO_NAMETABLE ordering — measured directly
 * (tests/probes/probe_named_groups.c: a 3-name pattern declared
 * zeta/alpha/mu by paren order comes back alpha/mu/zeta) rather than
 * invented, which is what makes the array bsearch-able by name exactly as
 * docs/spec/match_api.md §6 always said it would be, and settles the
 * paragraph that section left open (docs/dev/decisions.md's [M6.3] entry). */
/* [M6.5.2] THE NUMBER TIEBREAK, AND IT IS A CORRECTNESS REQUIREMENT rather
 * than the reproducibility nicety it would have been before `(?J)` existed.
 *
 * MEASURED (backrefs_design.md §8.2, `PCRE2_INFO_NAMETABLE` read for ten
 * patterns): libpcre2's own table is sorted (name ASCENDING, then number
 * ASCENDING) — `(?<z>1)(?<a>2)(?<z>3)(?<a>4)` comes back a/2, a/4, z/1, z/3 —
 * so this is a reproduction of an external precedent, not a pcrec convention.
 *
 * WHY WITHOUT IT THE TABLE ENCODES THE WRONG RULE, which is what R32's
 * re-check found by reading two sites together. `mod_named_groups.c` PREPENDS
 * each declaration onto `Ctx.named_groups` and the loop below walks that list
 * FROM THE HEAD, so the array reaching `qsort` is in DESCENDING group number.
 * Under a name-only comparator and a STABLE sort — glibc's is a merge sort —
 * the emitted rows for one name would come out (name asc, number DESC), and
 * `docs/spec/match_api.md` §6's caller algorithm (bsearch, walk BACK to the
 * run's first row, then FORWARD to the first participating one) would then
 * select the HIGHEST-numbered participating group. That is precisely the
 * "last set" rule §8.3's `"xyy"` cell rules out: `(?J)^(?<a>x)(?<a>y)\k<a>$`
 * matches "xyx" and NOT "xyy". The table would have encoded a resolution rule
 * the emitted matcher does not use, silently, on the platform pcrec is
 * developed on.
 *
 * The reproducibility argument — an unstable `qsort` leaves equal rows in
 * unspecified order — is also true, and is now the SECOND reason rather than
 * the first. D59 left the tiebreak unpinned; this module pins it.
 *
 * ITS DETECTOR IS STRUCTURAL, not behavioural: `tests/codegen`'s
 * [M6.5-DUPNAMES] check reads the emitted rows' order off the ARTIFACT and
 * asserts it is non-decreasing in (name, number), plus a comparator-TOTALITY
 * assertion (it returns 0 only for rows equal in BOTH fields). Neither depends
 * on `qsort`'s stability or on the list's direction, which is what a
 * behavioural row here would have depended on. Sabotage row S120. */
static int ng_cmp_name(const void *a, const void *b)
{
    const NamedGroup *const *pa = a;
    const NamedGroup *const *pb = b;
    int c = strcmp((*pa)->name, (*pb)->name);
    if (c != 0) return c;
    return (*pa)->number < (*pb)->number ? -1
         : (*pa)->number > (*pb)->number ?  1 : 0;
}

static void emit_info_def(Ctx *cx, StrBuf *c, const char *infoname,
                          const char *upper, const InfoStamp *st)
{
    /* [M6.3] the named-groups reflection table, emitted (as a file-scope
     * `static` array, so two differently-prefixed artifacts sharing a TU
     * cannot collide on its name) ONLY when the pattern text declared at
     * least one name — every pattern with none stays byte-identical to
     * before this module existed, the same "trivially empty" convention
     * every other late-populated rx_info field already follows. */
    const char *groups_name = NULL;
    if (cx->n_named_groups > 0) {
        NamedGroup **sorted =
            arena_alloc(&cx->arena, cx->n_named_groups * sizeof *sorted);
        unsigned idx = 0;
        for (NamedGroup *g = cx->named_groups; g; g = g->next)
            sorted[idx++] = g;
        qsort(sorted, cx->n_named_groups, sizeof *sorted, ng_cmp_name);

        groups_name = derived_name(cx, "_group_names");
        sb_printf(c, "static const rx_group_entry %s[] = {\n", groups_name);
        for (unsigned i = 0; i < cx->n_named_groups; i++) {
            /* `slot`: the caps[] index this entry delivers, or -1 if this
             * build delivers none. `sorted[i]->number` (the group's
             * capture NUMBER) is always set, regardless of want_caps —
             * mod_named_groups.c numbers a named group unconditionally,
             * the same lexical-fact tier `ngroups` is. Whether that
             * number ALSO addresses a live caps[] slot is the separate,
             * build-output question `cx->want_caps` answers.
             *
             * [DD-14 wave G] THE VALUE IS UNCHANGED AND THE REASON WAS
             * WRONG. This comment used to argue that a captures-wanted
             * build with any named group is UNCONDITIONALLY VM-selected,
             * so `want_caps == true` implied a VM artifact. The
             * dead-capture elision retired that implication:
             * `(?:(?<g>a)){0}(?&g)b` compiles to the DFA (`.engine = 1`)
             * with `RX_NCAPS 2` and a name table whose entry addresses
             * slot 1. **THE SLOT NUMBER IS STILL RIGHT**, and now for a
             * reason that does not mention the engine: `want_caps` says
             * the caller asked for capture slots, `ncaps` is
             * `ngroups + 1` on BOTH engines since this wave, and the
             * group's number IS its slot index in the array the caller
             * gets — whether any match can set it is a different question
             * and not this field's. See mod_named_groups.c's header. */
            int slot = cx->want_caps ? sorted[i]->number : -1;
            sb_printf(c, "    { \"%s\", %d, %d, NULL },\n",
                      sorted[i]->name, sorted[i]->number, slot);
        }
        sb_puts(c, "};\n");
    }

    sb_printf(c, "const struct rx_info %s = {\n", infoname);
    /* abi 2: `work_budget` joined the layout (D47 SECOND ADDENDUM's third
     * bound). The member is INSERTED beside `step_budget` rather than appended,
     * so every following offset moves — which is precisely what the version
     * member exists to announce, and what the pre-release ABI posture (D47
     * SECOND ADDENDUM's rider, D49) licenses on a struct D44.5 called final.
     *
     * [DD-14.FB] abi 2 -> 3: the caller-buffer sizing surface's four fields
     * (spec §10.4) are INSERTED after `subject_ceiling`, ahead of the three
     * pointer members, so every following offset moves again — the same
     * announced pre-v1 boundary D40 regime 1 governs, and the same reason
     * this member exists. P-4 of the design predicts nothing in-tree reads
     * the struct positionally; a vendored consumer is D40's problem, not a
     * silent one. */
    /* [DD-13] abi 3 -> 4 (D76/[TT-11]): the DFA artifact's D46 SELECTION
     * STAMPS (`<PREFIX>_ENGINE`, `_DFA_SCAN`, `_DFA_PREFILTER`, above) are
     * three new lines in its scaffolding — and, because `emit_info_def` is
     * SHARED, this member's own byte moves in every VM artifact too, which is
     * why the whole-file pin had to move for both kinds (r37 A12). They are
     * three new lines in every DFA artifact's `#define` block. They are pure
     * SCAFFOLDING — no table, no search-loop byte and no answer moves, which
     * `run_recursion_identity.sh`'s comparison (A) proves by comparing the
     * PROGRAM REGION against the unchanged pre-module pin — but D76's rule is
     * about the emitted scaffolding and not about behaviour: any change to it
     * is an `abi` bump AND a re-pin of that gate's comparison (B) to this
     * change's last src-touching commit, in the same change. */
    sb_puts(c,   "    .abi = 4,\n");
    /* [ENG-BREP] The STRATEGY-DENIAL bits are masked out of the stamp, and
     * the reason is the same one that makes them safe to ship.
     *
     * `rx_info.flags` is D43's record of the options the artifact was compiled
     * WITH, and its consumers read it to learn what the matcher DOES.
     * `-fno-possessify` changes what the matcher does by exactly nothing —
     * that is the claim the flag exists to test — so stamping it here would
     * make two artifacts that behave identically differ in their reflection
     * surface over a knob with no observable effect. It would also destroy the
     * byte-identity gate that is this pass's own safety argument: "a pattern
     * the analysis declines emits the bytes it emits today" is checkable only
     * while the flag itself leaves no trace, and a gate that has to FILTER a
     * known-differing line is the check-design failure this project has
     * recorded twice.
     *
     * What the ladder's choices ARE recorded in is `<PREFIX>_VM_STRATS`
     * (src/gen/emit_vm.c), which reports what the emitter actually DID rather
     * than what it was asked — the D46 half that a denial can be checked
     * against. Each further denial in D47.3's family joins this mask as it
     * lands.
     *
     * [M4.6f] `PCREC_NO_PREFILTER`/`PCREC_FORCE_PREFILTER` join the mask for
     * the identical reason, even though the PREFILTER axis is a FORCE pair
     * rather than a deny-only flag (lib/pcrec.h's comment on the two bits):
     * the rule this mask states is about the axis's OBSERVABLE EFFECT, not
     * about deny-vs-force spelling, and forcing the hybrid prefilter on or
     * off changes no answer, only how one is found (engine_m4.md §6.1). The
     * axis's own D46 record is `<PREFIX>_VM_PREFILTER` (src/gen/emit_vm.c),
     * VM-artifacts-only — but NOT for the reason this comment used to give
     * ("a DFA artifact has no separate prefilter decision to report", the
     * same premise §6.3's old VM-only rule rested on). [DD-13] falsified it:
     * a DFA artifact makes a real candidate-start prefilter decision and
     * stamps it as `<PREFIX>_DFA_PREFILTER` (`emit_dfa_stamps`, below). The
     * two stay SEPARATELY NAMED because their VALUE SETS are different
     * vocabularies — "hybrid"/"none" against five DFA loop shapes — which is
     * §6.3's (a)/(b) rule: the SELECTION FACT `RX_ENGINE` is unconditional
     * and shared, an engine's own vocabulary is neither.
     *
     * [OPT-ALTCLS] `PCREC_NO_ALTCLS_MERGE`/`PCREC_NO_ALTCLS_FACTOR` join the
     * mask too, and for the ORIGINAL deny-family reason rather than the
     * prefilter's force-pair exception: each is a per-alternation-run
     * selection point that changes no answer, only the emitted shape. Their
     * own D46 record is `<PREFIX>_ALTCLS_MERGES`/`<PREFIX>_ALTCLS_FACTORED`
     * (src/gen/emit_dfa.c's `pcrec_emit_prologue`, above — shared by both
     * engines since this pass runs before either is built). */
    {
        const uint64_t strategy_denials = PCREC_NO_POSSESSIFY | PCREC_NO_REVDET |
                                          PCREC_NO_COUNTER |
                                          PCREC_NO_LENGTH_PRUNE |
                                          PCREC_NO_PREFILTER | PCREC_FORCE_PREFILTER |
                                          PCREC_NO_ALTCLS_MERGE | PCREC_NO_ALTCLS_FACTOR;
        sb_printf(c, "    .flags = %lluULL,\n",
                  (unsigned long long)(cx->opt->flags & ~strategy_denials));
    }
    sb_printf(c, "    .encoding = %d,\n", cx->opt->encoding);
    sb_printf(c, "    .ncaps = %s_NCAPS,\n", upper);
    sb_printf(c, "    .ngroups = %d,\n", (int)cx->ncap);
    sb_printf(c, "    .nnames = %u,\n", cx->n_named_groups);
    /* [ABI-NS] (D60 addendum): the comment names the emitted PCREC_ENGINE_*
     * constants (emit_rx_abi_types), not the internal ENGM_* enum. */
    sb_printf(c, "    .engine = %d, /* %s */\n", st->engine,
              st->engine == 2 ? "PCREC_ENGINE_VM" : "PCREC_ENGINE_DFA");
    sb_printf(c, "    .step_budget = %lld,\n", st->step_budget);
    sb_printf(c, "    .work_budget = %lld,\n", st->work_budget);
    sb_printf(c, "    .frame_capacity = %lld,\n", st->frame_capacity);
    sb_printf(c, "    .subject_ceiling = %lld,\n", st->subject_ceiling);
    sb_printf(c, "    .resume_frames = %lld,\n", st->bufs->resume_frames);
    sb_printf(c, "    .trail_frames = %lld,\n", st->bufs->trail_frames);
    sb_printf(c, "    .resume_frame_size = %d,\n", st->bufs->resume_frame_size);
    sb_printf(c, "    .trail_frame_size = %d,\n", st->bufs->trail_frame_size);
    sb_puts(c,   "    .pattern = ");
    emit_c_string_literal(c, cx->pat, cx->patlen);
    sb_puts(c,   ",\n");
    sb_printf(c, "    .pattern_len = %zu,\n", cx->patlen);
    if (groups_name)
        sb_printf(c, "    .groups = %s,\n", groups_name);
    else
        sb_puts(c, "    .groups = NULL,\n");
    if (st->engine_why) {
        sb_puts(c, "    .engine_why = ");
        emit_c_string_literal(c, st->engine_why, strlen(st->engine_why));
        sb_puts(c, ",\n");
    } else {
        sb_puts(c, "    .engine_why = NULL,\n");
    }
    sb_puts(c,   "};\n");
}

/* [M5-SEAM] (D58, DD-12 (7)) THE RESIDUAL EMBED. The artifact's ONE encoding
 * is a per-compile scalar (`cx->opt->encoding`), and these two calls are the
 * whole of what the emitter knows about encodings: it asks the registry for
 * the backend and copies that backend's own text, prefix-substituted. There
 * is no encoding test here and there must never be one — the "switch" DD-12
 * allows is WHICH backend text got embedded, never a branch in shared code.
 *
 * Placement mirrors the four entry points exactly: declarations wherever a
 * consumer's declarations live (the .h when split, the .c when
 * self-contained), definitions in the .c. `pcrec_enc_ready` cannot be false
 * here — src/core/compile.c refuses an unimplemented encoding before any
 * emission — but the lookup is still checked rather than assumed, because a
 * NULL text pointer reaching this far would otherwise emit a truncated
 * artifact instead of failing. */
/* [M6.5.2] BOTH TAKE THE ARTIFACT'S MASK, which is D58's revisit clause being
 * honoured — see enc.h for why a per-entry mask and not two more string
 * fields. `Job.enc_mask` is set by whichever emitter is running BEFORE the
 * prologue, so an entry reaches the artifact iff something in it is emitted
 * that calls the entry. */
static void emit_residual_decls(Ctx *cx, StrBuf *sb)
{
    const PcrecEnc *enc = pcrec_enc_by_id(cx->opt->encoding);
    if (!pcrec_enc_ready(enc)) return;
    pcrec_enc_emit_decls(sb, enc, cx->job->enc_mask, cx->opt->prefix);
}

static void emit_residual_defs(Ctx *cx, StrBuf *sb)
{
    const PcrecEnc *enc = pcrec_enc_by_id(cx->opt->encoding);
    if (!pcrec_enc_ready(enc)) return;
    pcrec_enc_emit_defs(sb, enc, cx->job->enc_mask, cx->opt->prefix);
}

static void emit_header(Ctx *cx, const char *fn, const char *matchfn,
                         const char *matchcapsfn, const char *infoname,
                         const char *upper, int ncaps, const BufSurface *bs)
{
    StrBuf *h = &cx->job->hsb;
    const char *p = cx->opt->prefix;
    char guard[80];
    size_t gi = 0;
    for (const char *q = p; *q && gi < sizeof(guard) - 1; q++)
        guard[gi++] = (char)(isalnum((unsigned char)*q) ? toupper((unsigned char)*q) : '_');
    guard[gi] = 0;

    emit_pattern_comment(h, cx->pat);
    emit_feature_comment(h);
    sb_printf(h, "#ifndef PCREC_GEN_%s_H\n#define PCREC_GEN_%s_H\n\n", guard, guard);
    sb_puts(h, "#include <stddef.h>\n#include <stdint.h>\n\n");
    emit_rx_abi_types(h);
    sb_putc(h, '\n');
    emit_ncaps_macros(h, upper, ncaps);
    emit_buffers_surface(h, upper, cx->opt->prefix, bs);
    sb_putc(h, '\n');
    emit_search_decl(h, fn);
    emit_match_decl(h, matchfn);
    emit_match_caps_decl(h, matchcapsfn);
    emit_info_decl(h, infoname);
    /* [DD-14.FB] The three `_in` entries join the header UNCONDITIONALLY,
     * beside the siblings they mirror -- spec §10.4's "the three `_in`
     * entries, the `<prefix>_buffers` type and all five macros are emitted on
     * EVERY artifact", so a consumer's code does not stop compiling when the
     * same pattern selects the other engine. */
    emit_search_in_decl(h, fn, cx->opt->prefix);
    emit_match_in_decl(h, matchfn, cx->opt->prefix);
    emit_match_caps_in_decl(h, matchcapsfn, cx->opt->prefix);
    sb_putc(h, '\n');
    emit_residual_decls(cx, h);
    sb_printf(h, "\n#endif /* PCREC_GEN_%s_H */\n", guard);
}

