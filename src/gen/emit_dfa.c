/* The standalone main(), shared verbatim: it drives `<prefix>_search` through
 * the caps array and prints caps[0], which is engine-independent.
 *
 * [K21 fix] `<prefix>_search`'s return is THREE-VALUED (match_api_m4.md
 * §4.5): 1 match, 0 no-match, or a negative give-up sentinel
 * (PCREC_ERR_STEPS/PCREC_ERR_FRAMES) when a VM artifact exhausts its step budget
 * or backtrack-frame capacity — DFA artifacts never return the sentinels.
 * The prior version tested the result as a boolean, so C truthiness took
 * the match branch on a negative return and printed `caps`, which the
 * give-up path never wrote — uninitialized-stack output reported as a
 * confident match (K21, docs/dev/known_issues.md). Branch on the actual
 * value instead, mirroring tests/fuzz/fuzz_driver.c's three-way
 * discrimination, and give the give-up case its own exit code (3) so it
 * cannot be mistaken for either match (0) or no-match (1) — or for this
 * main()'s own usage error, which already claims 2. */
void pcrec_emit_main(Ctx *cx, const GenNames *g)
{
    sb_puts(&cx->job->csb, "\n");
    sb_printf(&cx->job->csb,
        "int main(int argc, char **argv)\n{\n"
        "    ptrdiff_t caps[%s_NCAPS][2];\n"
        "    if (argc < 2) { fprintf(stderr, \"usage: %%s <subject>\\n\", argv[0]); return 2; }\n"
        "    int rc = %s((const unsigned char *)argv[1], strlen(argv[1]), 0, caps);\n"
        "    if (rc == 1) {\n"
        "        printf(\"match %%td %%td\\n\", caps[0][0], caps[0][1]);\n"
        "        return 0;\n"
        "    }\n"
        "    if (rc == 0) {\n"
        "        printf(\"nomatch\\n\");\n"
        "        return 1;\n"
        "    }\n"
        /* [counter-K] One arm PER CODE, and a fallthrough that does not claim
         * to know. This block used to end `printf("frames")` for everything
         * that was not a match, a no-match or ERR_STEPS — so when the third
         * bound landed, a work give-up was reported as a FRAME overflow. That
         * is precisely the failure DD-2's "different failures, different
         * diagnoses" exists to prevent, reached from inside our own harness,
         * and it is why the last arm now reports the code instead of guessing
         * at its meaning. */
        "    if (rc == PCREC_ERR_STEPS) {\n"
        "        printf(\"steps\\n\");\n"
        "        return 3;\n"
        "    }\n"
        "    if (rc == PCREC_ERR_FRAMES) {\n"
        "        printf(\"frames\\n\");\n"
        "        return 3;\n"
        "    }\n"
        "    if (rc == PCREC_ERR_WORK) {\n"
        "        printf(\"work\\n\");\n"
        "        return 3;\n"
        "    }\n"
        "    printf(\"giveup %%d\\n\", rc);\n"
        "    return 3;\n"
        "}\n", g->upper, g->searchfn);
}

void pcrec_emit_dfa(Ctx *cx)
{
    StrBuf *c = &cx->job->csb;
    GenNames g;
    pcrec_gen_names(cx, &g);

    /* RX_NCAPS is 1 on every artifact this emitter produces (D42.2): a
     * DFA-compiled pattern never promises more than the whole-match slot,
     * capture-bearing or not. RX_NCAPS > 1 implies the VM — one checkable
     * line, and tests/codegen checks it. */
    pcrec_emit_prologue(cx, &g, 1);
    pcrec_emit_dfa_engine(cx, g.searchfn, "");

    sb_puts(c, "\n");
    emit_match_def(c, g.matchfn, g.searchfn, g.upper);
    sb_puts(c, "\n");
    emit_match_caps_def(c, g.matchcapsfn, g.searchfn, g.upper);
    sb_puts(c, "\n");
    pcrec_emit_residual(cx);
    {
        /* The DFA artifact's stamp: it cannot backtrack, cut, or scan
         * frameless, so NONE of the three bounds applies to it and all read
         * as absent rather than as some notional large number. `work_budget`
         * joins `step_budget` in that reading for exactly the same reason —
         * a bound an engine structurally cannot reach is not a bound of 0. */
        InfoStamp st = { 1, NULL, -1, -1, -1, 0 };
        emit_info_def(cx, c, g.infoname, g.upper, &st);
    }

    if (cx->opt->flags & PCREC_EMIT_MAIN)
        pcrec_emit_main(cx, &g);
}
