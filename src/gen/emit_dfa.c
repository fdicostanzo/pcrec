/* M2.1 self-loop skip: pick up to 4 states (excluding `exclude`) that stay
 * put on >= 192 of 256 bytes — their scan degenerates to a SIMD-friendly
 * skip loop. Motivated by compare case h (`.*=.*`): the post-'=' state
 * self-loops on everything but '\n' in both machines.
 *
 * M2.10 tried replacing this absolute byte count with a fraction of the
 * state's LIVE bytes, so that narrow-alphabet patterns like `[01]*1[01]{8}`
 * (2 live bytes, 100% stay) would qualify — R2-A5 had described that case as
 * having "no skip-eligible states". The reasoning was sound and the result
 * was a REGRESSION: it gives case (f) one reverse skip table and measures
 * 158.6/159.1 -> 118.7 MB/s on the compare harness and 159.1/157.5 ->
 * 115.9/115.8 MB/s on bdriver, spreads 1.01-1.02x, i.e. ~27% slower on the
 * exact case it was meant to fix. Reverted; see D13 and the 2026-08-09
 * journal entry. Do not re-attempt without measuring the REVERSE machine
 * specifically — the suspicion is that a backward byte-at-a-time skip loop
 * loses to the reverse table walk, but that is untested. */
static int pick_skip_states(const Dfa *d, int exclude, int out[4])
{
    int cls_size[256] = {0};
    for (int b = 0; b < 256; b++) cls_size[d->clsmap[b]]++;
    int nout = 0;
    for (int pass = 0; pass < 4; pass++) {
        int best = -1, bestcnt = 191;
        for (int i = 0; i < d->n; i++) {
            if (i == exclude) continue;
            /* [M6.2 wave B] A STATE WHOSE ACCEPT DEPENDS ON THE NEXT BYTE IS
             * NOT SKIP-ELIGIBLE, and this is the D11-rule-1 hazard §3.6.1
             * describes, resolved by declining rather than by intersecting.
             *
             * A skip advances without consulting accept flags and records
             * only its LANDING position. That is sound while the accept bit
             * is constant across the run — which the pre-wave scalar accept
             * made true unconditionally, and a class-indexed one does not.
             * The concrete loss: a forward skip whose run's bytes all accept
             * landing on a byte whose class does not, with `last` wanting the
             * LARGEST accepting position, throws away every position it just
             * passed.
             *
             * §3.6.1 argues from §3.5 that `\b` cannot reach this, on the
             * ground that a skip set is a union of classes and therefore
             * pins next-is-word across the run. THE SECOND HALF DOES NOT
             * FOLLOW: a union of classes may perfectly well contain both word
             * and non-word classes (a state that stays put on both `a` and
             * ` ` has exactly such a stay set). So the argument is not
             * available and this declines instead. Declining is always safe
             * and costs nothing on any pattern without a next-byte-sensitive
             * accept — i.e. nothing in the pre-wave corpus, where this test
             * is false at every state. */
            if (state_acc_varies(&d->st[i])) continue;
            bool taken = false;
            for (int k = 0; k < nout; k++)
                if (out[k] == i) taken = true;
            if (taken) continue;
            int stay = 0;
            for (int cl = 0; cl < d->ncls; cl++)
                if (d->st[i].tr[cl] == i) stay += cls_size[cl];
            if (stay > bestcnt) { bestcnt = stay; best = i; }
        }
        if (best < 0) break;
        out[nout++] = best;
    }
    return nout;
}

static void emit_stay_table(StrBuf *c, const char *p, const char *tag,
                            int idx, const Dfa *d)
{
    uint8_t stay[256];
    for (int b = 0; b < 256; b++)
        stay[b] = (uint8_t)(d->st[idx].tr[d->clsmap[b]] == idx);
    /* [K38's rule, [ENG-FORM]] The one fixed buffer this function owns is
     * sized by the SHARED emitted-name constant, not by a hand guess: `tag`
     * reaches here from a caller's own `PCREC_MAX_EMIT_NAME_LEN` buffer now,
     * and 32 was a number that happened to fit the two literals it used to
     * be handed. */
    char name[PCREC_MAX_EMIT_NAME_LEN + 16];   /* + the state number */
    snprintf(name, sizeof(name), "%s%d", tag, idx);
    emit_u8_table(c, p, name, stay, 256);
}

/* ---------------------------------------------------------------------
 * [M6-READ] LEGENDS: the block comments that make a table readable.
 *
 * Both are computed from the very data this file is about to write -- the
 * class map and the transition table themselves -- so neither can drift from
 * the table it describes. That is the plan row's engineering note (iv), "the
 * emitter tags what it emits, no after-the-fact inference", satisfied without
 * a tagging pass: a walk over emitter-owned data IS the tag.
 * --------------------------------------------------------------------- */

/* One byte rendered for a human: printable ASCII quoted, everything else as a
 * number. Legend text only; never emitted as code. */
static void legend_byte(StrBuf *c, int b)
{
    if (b == '\'')      sb_puts(c, "'\\''");
    else if (b == '\\') sb_puts(c, "'\\\\'");
    else if (b >= 0x20 && b < 0x7f) sb_printf(c, "'%c'", b);
    else                sb_printf(c, "%d", b);
}

/* WHICH BYTES EACH CLASS HOLDS, as ranges. Class 0 is named rather than
 * enumerated: it is the catch-all, and listing its ranges is pages of noise
 * that tells the reader nothing. */
static void emit_class_legend(StrBuf *c, const Dfa *d)
{
    sb_printf(c, "     * Class legend (%d classes; every byte not listed is class 0):\n",
              d->ncls);
    sb_puts(c, "     *   0  every other byte\n");
    for (int cl = 1; cl < d->ncls; cl++) {
        sb_printf(c, "     *   %d  ", cl);
        int shown = 0, b = 0;
        while (b < 256 && shown < 8) {
            if (d->clsmap[b] != cl) { b++; continue; }
            int a = b;
            while (b + 1 < 256 && d->clsmap[b + 1] == cl) b++;
            if (shown) sb_puts(c, ", ");
            legend_byte(c, a);
            if (b != a) { sb_puts(c, "-"); legend_byte(c, b); }
            shown++; b++;
        }
        if (b < 256) sb_puts(c, ", ...");
        sb_puts(c, "\n");
    }
}

/* WHAT EACH STATE MEANS, as the SHORTEST INPUT THAT REACHES IT -- a
 * breadth-first search over the transition table below, using each class's
 * representative byte.
 *
 * The example string IS the state's meaning, and it needs no knowledge of the
 * pattern's syntax: a reader comparing two adjacent states sees exactly what
 * the machine just consumed. On the reverse machine the walk consumes the
 * match right-to-left, so the examples read backwards and the banner says so.
 *
 * Capped: past LEGEND_MAX_STATES a full listing is noise rather than
 * orientation, so only the start and the accepting states are named and the
 * comment says what it left out. */
#define LEGEND_MAX_STATES 48
/* A state deep in the machine has an example as long as its distance from
 * the start; past this many bytes the string stops orienting anyone. */
#define LEGEND_MAX_EXAMPLE 40

static void emit_state_legend(StrBuf *c, const Dfa *d, bool reverse)
{
    int *dist  = malloc((size_t)d->n * sizeof(int));
    int *from  = malloc((size_t)d->n * sizeof(int));
    int *via   = malloc((size_t)d->n * sizeof(int));
    int *queue = malloc((size_t)d->n * sizeof(int));
    int *path  = malloc((size_t)d->n * sizeof(int));
    if (!dist || !from || !via || !queue || !path) {
        free(dist); free(from); free(via); free(queue); free(path);
        return;                    /* a legend is never worth failing a compile over */
    }
    for (int i = 0; i < d->n; i++) { dist[i] = -1; from[i] = -1; via[i] = -1; }
    int head = 0, tail = 0;
    if (d->s0 >= 0 && d->s0 < d->n) { dist[d->s0] = 0; queue[tail++] = d->s0; }
    while (head < tail) {
        int s = queue[head++];
        for (int cl = 0; cl < d->ncls; cl++) {
            int nx = d->st[s].tr[cl];
            if (nx < 0 || nx >= d->n || dist[nx] >= 0) continue;
            dist[nx] = dist[s] + 1; from[nx] = s; via[nx] = cl;
            queue[tail++] = nx;
        }
    }

    /* How many states accept? In a big machine this decides whether a listing
     * is orientation or noise -- `((a)|b){0,4000}c` has 4002 accepting states,
     * and naming them all cost 4000 lines and tripled the artifact. Caught by
     * the [ENG-BREP] emitted-size check, which is exactly what it is for. */
    int nacc = 0;
    for (int i = 0; i < d->n; i++) if (d->st[i].up[UPC_PLAIN].accept) nacc++;

    bool brief = d->n > LEGEND_MAX_STATES;
    if (brief) {
        /* A SUMMARY, not a truncated list. Which particular states accept is
         * not orientation once there are thousands of them; how many there
         * are, and what the shortest accepted input looks like, is. */
        int shortest = -1;
        for (int i = 0; i < d->n; i++)
            if (d->st[i].up[UPC_PLAIN].accept && dist[i] >= 0 &&
                (shortest < 0 || dist[i] < dist[shortest])) shortest = i;
        sb_printf(c, "     * State legend -- %d states, %d of them accepting: too many\n"
                     "     * to name individually. The start state is %d",
                  d->n, nacc, d->s0);
        if (shortest >= 0)
            sb_printf(c, ", and the\n"
                         "     * shortest input reaching an accepting state is %d byte(s) long",
                      dist[shortest]);
        sb_puts(c, ".\n");
        free(dist); free(from); free(via); free(queue); free(path);
        return;
    }
    if (reverse)
        sb_puts(c, "     * State legend -- the bytes this walk consumes, IN WALK\n"
                   "     * ORDER, i.e. the match read backwards:\n");
    else
        sb_puts(c, "     * State legend -- the shortest input that reaches each state:\n");
    for (int i = 0; i < d->n; i++) {
        bool acc = d->st[i].up[UPC_PLAIN].accept != 0;
        /* NOT "unreachable": this walk follows the plain transitions only, and
         * a state can also be selected by a POSITION VIEW (end of subject, end
         * of line) that has no edge in the table below. Saying what the walk
         * actually established is the honest claim; saying the state is dead
         * would be wrong, and is wrong on `^ab(c|d)e$` today. */
        if (dist[i] < 0) {
            sb_printf(c, "     *  %3d  (no path through the transitions above;\n"
                         "     *       a position view can still select it)\n", i);
            continue;
        }
        sb_printf(c, "     *  %3d  ", i);
        if (dist[i] == 0) sb_puts(c, "(start) nothing consumed yet");
        else {
            int len = dist[i], k = len, s = i;
            while (k > 0) { path[--k] = via[s]; s = from[s]; }
            sb_puts(c, "\"");
            int shown = len < LEGEND_MAX_EXAMPLE ? len : LEGEND_MAX_EXAMPLE;
            for (k = 0; k < shown; k++) {
                int b = d->rep[path[k]];
                if (b >= 0x20 && b < 0x7f && b != '"' && b != '\\')
                    sb_printf(c, "%c", b);
                else sb_printf(c, "\\x%02x", b);
            }
            sb_puts(c, "\"");
            if (shown < len) sb_printf(c, "... (%d bytes)", len);
        }
        if (acc) sb_puts(c, "   ACCEPTING");
        sb_puts(c, "\n");
    }
    free(dist); free(from); free(via); free(queue); free(path);
}

/* M2.7 put `$`-bearing patterns on this engine; M2.12 gave them back the
 * scan-avoidance M2.7 had traded away. Both live in ONE emitter on purpose:
 * M2.7 forked a second copy, and the fork is exactly how the prefilter and
 * skip loops went missing from the `$` path for a whole milestone.
 *
 * EOL handling: both machines switch to a state's EOL variant exactly at EOL
 * positions (end of subject, or before a final newline), guarded by
 * `pos + 1 >= n` — false for every byte but the last two, so the scan stays a
 * tight table walk.
 *
 * Scan avoidance under EOL (M2.12): a prefilter or self-loop skip advances
 * `pos` WITHOUT consulting accept flags, which is unsound when a state can
 * accept at an EOL position. The fix is to bound every skip at `n - 1` rather
 * than `n` and let the stepped loop handle the last two positions. That also
 * keeps the EOL-variant lookup correct for free: a skip can only run when
 * `pos + 1 < n`, and in that case `est == st` by construction, so the state
 * used for the transition is never stale. The forward prefilter additionally
 * must NOT keep its `return 0` early-out, since the start state's EOL variant
 * may still accept at n-1 or n. */
/* =========================================================================
 * [ENG-FORM] THE REPRESENTATION OBJECTS AND THE ONE SCAN LOOP
 *
 * docs/design/emitter_form.md is the note; D82 the ruling. What used to be a
 * 459-line function carrying ~14 loose form booleans — every one of them a
 * forward/reverse PAIR — is six candidate lists, one loop skeleton and one
 * table emitter, each called twice.
 *
 * READ `DfaForm` FIRST: it is one machine's whole form, and every emitter
 * below takes nothing else. The two `DfaForm`s an artifact builds differ in
 * their DIRECTION object, their machine, and whichever candidates that
 * machine's own dimensions selected.
 * ========================================================================= */

typedef struct DfaDir DfaDir;

/* AXIS B — THE PREFILTER, forward only. Five objects and not three: the D11
 * `-bounded` half of `<PREFIX>_DFA_PREFILTER`'s value is a DIFFERENT EMITTED
 * LOOP (the skip stops at n-1 and loses its `return 0` early-out), so it is a
 * different form, and making it one is what turns the stamp into `c.name`. */
typedef struct DfaPf {
    DfaCand c;
    /* [OPT-K] `bool table` became a METHOD when the offset-k forms landed, and
     * that is the object owning what it emits rather than the assembly asking
     * a boolean. The byte-class forms emit `can_begin_match` and nothing else,
     * exactly as before; the offset-set forms emit that table only when offset
     * 0's set is genuinely a bitmap, plus one table per multi-byte VERIFY
     * offset. A boolean cannot express "which of my offsets need a table",
     * and a second boolean beside it would be the parallel mechanism the
     * house rule forbids. NULL == this form emits no table. */
    void  (*emit_tables)(StrBuf *c, const DfaForm *f);
    /* [OPT-K] LAYER 2, the accessor block, at FILE SCOPE beside the state
     * token's — the offset-k skip is a loop over the subject and belongs in a
     * function, not inlined three levels deep in the scan. NULL == no block.
     * It is emitted from the same place `repr->emit_token` is, so the VM
     * hybrid's inlined prefilter gets it by construction. */
    void  (*emit_block)(StrBuf *c, const DfaForm *f);
    void  (*emit)(StrBuf *c, const DfaForm *f); /* NULL == emits nothing */
} DfaPf;

/* AXIS C — VIEW HANDLING. `emit_view_select`'s three branches, plus the
 * "not called at all" case that used to be an `if (viewsel)` at each of the
 * two call sites. */
typedef struct DfaView {
    DfaCand c;
    void  (*emit)(StrBuf *c, const DfaForm *f); /* NULL == emits nothing */
} DfaView;

/* AXIS D — THE START SEED (mechanism 4). The object owns whether the
 * initializer reads a context byte; the DIRECTION owns which byte, which
 * guard, and where the range check goes relative to it. */
typedef struct DfaSeed {
    DfaCand c;
    bool    table;                              /* the <M>_seed_state table */
    void  (*emit_init)(StrBuf *c, const DfaForm *f);
} DfaSeed;

/* AXIS E — WHERE THE ACCEPT IS RECORDED, which is one axis with three forms
 * and not two booleans. `by_class` records inside the step arm (§3.6.2's
 * composition); `scalar_viewed` records AFTER the view selector, because the
 * position a skip landed on is not the position whose accept was evaluated
 * (D11); `scalar_plain` records at the top of the loop, which is measurably
 * the right order when nothing can move under it (D11's note: hoisting the
 * prefilter above it costs 43% on `[01]*1[01]{8}`). Exactly one of the three
 * `emit_*` slots is non-NULL per object, which is why the skeleton calls them
 * through null checks instead of branching on a form. */
typedef struct DfaAcc {
    DfaCand c;
    bool    wide_table;                         /* the by-class accept table */
    void  (*emit_top)(StrBuf *c, const DfaForm *f);
    void  (*emit_after_view)(StrBuf *c, const DfaForm *f);
    void  (*emit_tail)(StrBuf *c, const DfaForm *f);
} DfaAcc;

/* AXIS F — THE SCAN DIRECTION, the axis that collapses the duplication. It is
 * a representation axis in the same sense as the others: a direction is how a
 * scan spells its position, its bound, the answer it records and the byte it
 * reads, and every one of those has exactly two emitted forms. */
struct DfaDir {
    DfaCand     c;
    const char *title;        /* "Forward" / "Reverse", for comments */
    const char *label;        /* "FORWARD" / "REVERSE", for headings */
    const char *statev;       /* the emitted state variable */
    const char *viewv;        /* the emitted view-state variable */
    const char *posv;         /* the emitted position variable */
    const char *recv;         /* the emitted answer variable */
    const char *ind;          /* indent of the state declaration */
    const char *bind;         /* indent of the loop body */
    bool        reverse;      /* for emit_state_legend */
    const char *tbl_hdr;      /* the table section's block comment */
    const char *acc_meaning;  /* what a 1 in the accept table means */
    const char *range_guard;  /* emitted beside the initializer, or NULL */
    const char *seed_cond;    /* "a context byte exists" */
    const char *seed_byte;    /* that byte */
    const char *at_bound;     /* "there is no byte left to consume" */
    const char *peek;         /* the byte to consume, WITHOUT consuming it */
    const char *consume;      /* the byte to consume, consuming it */
    const char *advance;      /* the statement that consumes it */
    void      (*emit_skip)(StrBuf *c, const DfaForm *f, int K, const char *kw);
    void      (*emit_bound_accept)(StrBuf *c, const DfaForm *f);
};

/* ONE MACHINE'S FORM. Everything an emitter below is allowed to read. */
struct DfaForm {
    /* [OPT-K] the Ctx, for `ctx_fail` alone. Two arms of the offset-k skip's
     * emitter are UNREACHABLE by construction (an empty verify chain; a
     * non-singleton scan offset), and this file's standing preference is a
     * loud internal error over a silent fallback that would emit a correct
     * matcher with the optimization quietly switched off. */
    Ctx           *cx;
    const Dfa     *d;
    const char    *p;              /* the artifact prefix */
    const DfaDir  *dir;
    const DfaRepr *repr;
    const DfaPf   *pf;
    const DfaView *view;
    const DfaSeed *seed;
    const DfaAcc  *acc;
    bool           views;          /* the D11 bound: a skip may pass a
                                    * position whose accept was not evaluated */
    bool           viewsel;        /* the position-view indirection exists */
    const char    *src;            /* the state the accept and the step read:
                                    * `statev`, or `viewv` under `viewsel` */
    int            nskip, skip[4];
    CandSet        cand;
    /* [OPT-K] BY POINTER into the caller's `UnanchStart`, which outlives every
     * use: the selection carries 24 byte-sets and copying it into a stack
     * struct twice per artifact would put 13 KB on the emitter's frame for a
     * value nothing mutates. */
    const PrefixKSets *ofsk;
};

/* THE SELECTION WALK, written ONCE for all six axes. Every object struct
 * begins with a `DfaCand`, so the address of the i'th entry of any of the
 * lists is the address of a `DfaCand` — no punning, just the first member.
 *
 * Returning NULL is UNREACHABLE and deliberately not defended against: every
 * list's last entry's `applies` returns true unconditionally, which is the
 * property §9.3 of the note names as the failure mode a total fallback
 * removes. A missing fallback would crash here rather than emit a machine
 * with a hole in it. */
static const void *dfa_select(const void *list, size_t n, size_t sz,
                              const DfaSel *s, unsigned flags)
{
    const char *base = (const char *)list;
    for (size_t i = 0; i < n; i++) {
        const DfaCand *cand = (const DfaCand *)(const void *)(base + i * sz);
        if (cand->deny & flags) continue;
        if (cand->applies(s)) return (const void *)(base + i * sz);
    }
    return NULL;
}
#define DFA_SELECT(T, list, sel, flags)                                       \
    ((const T *)dfa_select((list), sizeof(list) / sizeof((list)[0]),          \
                           sizeof((list)[0]), (sel), (flags)))

static bool cand_always(const DfaSel *s) { (void)s; return true; }

/* ---- AXIS A: the table representations ---------------------------------- */

static bool repr_premul_applies(const DfaSel *s) { return dfa_premul(s->cx, s->d); }
static int  cell_premul(int st, const Dfa *d) { return st * d->ncls; }
static int  cell_indexed(int st, const Dfa *d) { (void)d; return st; }

/* LAYER 2 — THE OPAQUE STATE TOKEN. One block per machine per form, emitted
 * at file scope immediately above the search function, so the VM hybrid's
 * inlined `static <prefix>_prefilter` gets it BY CONSTRUCTION: that body is
 * this same emitter call (`pcrec_emit_dfa_engine`), not a second copy.
 *
 * AN ACCESSOR TAKES THE TABLE IT READS AS A PARAMETER. The tables stay
 * function-local `static const` arrays, where they have always been; the
 * token abstracts the STATE REPRESENTATION and nothing else, and gcc folds a
 * block-scope array's address through an inline call. That folding is the
 * whole design (D82 bound 1) and it is MEASURED, not assumed: the objdump of
 * `<prefix>_search` after this change is instruction-for-instruction the
 * sequence the hand-written loop produced.
 *
 * ONLY THE ACCESSORS THIS MACHINE USES ARE EMITTED — `accepts_class` under
 * axis E's `by_class`, `row`/`view_live`/`view_take` under a view — so no
 * artifact carries a dead one. */
static void token_premul(StrBuf *c, const DfaForm *f)
{
    const char *p = f->p, *m = f->dir->c.name;
    int nc = f->d->ncls;
    sb_printf(c,
        "/* ---- THE %s SCAN'S STATE, AS AN OPAQUE TOKEN --------------------\n"
        " * The scan carries its state in a `%s_%s_state`. Everything that\n"
        " * depends on how a state is REPRESENTED is in this block: the loop\n"
        " * only steps the token, asks whether it is dead, probes its accept\n"
        " * bit and -- at most twice per search -- asks which table ROW it\n"
        " * names.\n"
        " *\n"
        " * THIS IS THE PRE-MULTIPLIED FORM: the token is the state's row\n"
        " * number times %d, so a step is one add and one load, and %d is the\n"
        " * reserved value meaning \"dead, stop\".\n"
        " */\n", f->dir->label, p, m, nc, PREMUL_DEAD);
    sb_printf(c, "typedef unsigned %s_%s_state;\n", p, m);
    sb_printf(c, "static inline %s_%s_state %s_%s_step(const unsigned short *transitions, %s_%s_state s, unsigned cl)\n"
                 "{ return transitions[s + cl]; }\n", p, m, p, m, p, m);
    sb_printf(c, "static inline int %s_%s_is_dead(%s_%s_state s) { return s == %d; }\n",
              p, m, p, m, PREMUL_DEAD);
    sb_printf(c, "static inline int %s_%s_accepts(const unsigned char *accepting, %s_%s_state s)\n"
                 "{ return accepting[s]; }\n", p, m, p, m);
    if (f->acc->wide_table)
        sb_printf(c, "static inline int %s_%s_accepts_class(const unsigned char *accepting, %s_%s_state s, unsigned cl)\n"
                     "{ return accepting[s + cl]; }\n", p, m, p, m);
    if (f->viewsel) {
        /* THE ONE UN-MULTIPLY, and the reason it is a function rather than a
         * hoisted local at the call site: under this form it is a DIVISION.
         * Its callers spell it inside the second operand of a `&&` whose
         * first operand is `__builtin_expect(pos + 1 >= n, 0)`, so it runs at
         * most twice per search and never per byte. A tidier
         * `unsigned row = <M>_row(s);` above the `if` changes no answer,
         * passes every identity gate, and puts a divide on the hot path. */
        sb_printf(c, "static inline unsigned %s_%s_row(%s_%s_state s) { return s / %d; }\n",
                  p, m, p, m, nc);
        sb_printf(c, "static inline int %s_%s_view_live(const unsigned short *view, unsigned row)\n"
                     "{ return view[row] != %d; }\n", p, m, PREMUL_DEAD);
        sb_printf(c, "static inline %s_%s_state %s_%s_view_take(const unsigned short *view, unsigned row)\n"
                     "{ return view[row]; }\n", p, m, p, m);
    }
    sb_puts(c, "\n");
}

static void token_indexed(StrBuf *c, const DfaForm *f)
{
    const char *p = f->p, *m = f->dir->c.name;
    int nc = f->d->ncls;
    sb_printf(c,
        "/* ---- THE %s SCAN'S STATE, AS AN OPAQUE TOKEN --------------------\n"
        " * The scan carries its state in a `%s_%s_state`. Everything that\n"
        " * depends on how a state is REPRESENTED is in this block: the loop\n"
        " * only steps the token, asks whether it is dead, probes its accept\n"
        " * bit and -- at most twice per search -- asks which table ROW it\n"
        " * names.\n"
        " *\n"
        " * THIS IS THE INDEXED FORM: the token IS the row number, a step\n"
        " * scales it by the %d columns, and a negative value means \"dead,\n"
        " * stop\".\n"
        " */\n", f->dir->label, p, m, nc);
    sb_printf(c, "typedef int %s_%s_state;\n", p, m);
    sb_printf(c, "static inline %s_%s_state %s_%s_step(const short *transitions, %s_%s_state s, unsigned cl)\n"
                 "{ return transitions[s * %d + cl]; }\n", p, m, p, m, p, m, nc);
    sb_printf(c, "static inline int %s_%s_is_dead(%s_%s_state s) { return s < 0; }\n",
              p, m, p, m);
    sb_printf(c, "static inline int %s_%s_accepts(const unsigned char *accepting, %s_%s_state s)\n"
                 "{ return accepting[s]; }\n", p, m, p, m);
    if (f->acc->wide_table)
        sb_printf(c, "static inline int %s_%s_accepts_class(const unsigned char *accepting, %s_%s_state s, unsigned cl)\n"
                     "{ return accepting[s * %d + cl]; }\n", p, m, p, m, nc);
    if (f->viewsel) {
        sb_printf(c, "static inline unsigned %s_%s_row(%s_%s_state s) { return (unsigned)s; }\n",
                  p, m, p, m);
        sb_printf(c, "static inline int %s_%s_view_live(const short *view, unsigned row)\n"
                     "{ return view[row] >= 0; }\n", p, m);
        sb_printf(c, "static inline %s_%s_state %s_%s_view_take(const short *view, unsigned row)\n"
                     "{ return view[row]; }\n", p, m, p, m);
    }
    sb_puts(c, "\n");
}

