/* The definition's signature, kept next to the declaration it must match.
 *
 * [M4.5b] `storage` is "" for the exported entry and "static " for the VM
 * hybrid's PREFILTER (engine_m4.md §6.1), which is this same engine emitted
 * under a private name inside a VM artifact. Passing the storage class rather
 * than forking the emitter is the M2.12 lesson applied ahead of time: the `$`
 * fork is exactly how the prefilter and skip loops silently went missing from
 * one path for a whole milestone. `emit_search_head`'s two callers below both
 * pass it straight through from their own caller, so the DFA-only path's
 * output is unchanged byte for byte (storage == "").
 *
 * [K24] `noclone` IS THE FIX FOR K24 AND MUST NOT BE DELETED — it is not
 * decoration and it is not a micro-optimization. Full evidence chain:
 * docs/dev/known_issues.md K24 (closure entry) and
 * docs/design/k24bisect_impl/ (the bisect note plus this lane's head-to-head).
 *
 * WHAT IT PREVENTS: gcc -O2's partial-inlining pass (`-fpartial-inlining`,
 * on by default) sees this function's cheap entry guard in front of a large
 * scan body and SPLITS it into a trampoline plus a separately-placed
 * `<prefix>_search.part.0` clone carrying the loop. The split loop's
 * instructions are IDENTICAL — the cost is pure code placement, and it is
 * real and reproducible: MEASURED at 1.33x on the compare.sh case-(c) shape
 * (`(alpha|beta|gamma|delta|epsilon)`, 8 MB nomatch subject: 293.5 MB/s split
 * vs 391.6 unsplit, pinned, 10 trials, <1% spread), which is what took that
 * case's D12 floor red for three days. `noclone` forbids exactly the one
 * thing the pass needs — duplicating this body — and the emitted assembly is
 * then BYTE-IDENTICAL to the same source compiled `-O2
 * -fno-partial-inlining`, which is the causal control the bisect used.
 *
 * WHY THIS ATTRIBUTE AND NOT ANOTHER, all measured head-to-head on that same
 * case (the table is in the K24 closure entry):
 *   - `noipa`/`noinline` on the two COLD WRAPPERS (`<prefix>_match`,
 *     `<prefix>_match_caps`) do NOT work — 292.7 and 295.3 MB/s, the split
 *     still present in `nm`. This refutes the obvious theory: gcc's
 *     `pass_split_functions` runs on the CALLEE and does not consult its
 *     callers' attributes, so severing IPA at the call site leaves the clone
 *     standing. It has to be denied at THIS function.
 *   - `hot` here, or `cold` on the wrappers, recovers the number (397) while
 *     LEAVING the split in place — luck about placement in one particular
 *     link, not a fix. The two combined measured 288.7, WORSE than doing
 *     nothing: layout steering is exactly as unpredictable as the mechanism
 *     it would be steering around, and a stranger's link is not this one.
 *   - `optimize("no-partial-inlining")` works (390.9) but replaces this
 *     function's whole optimization environment to fix one pass.
 *   - `noipa` works (390.8) but is far wider than needed, and would forbid
 *     the VM hybrid's inlining of this same emitter's static prefilter into
 *     `<prefix>_search`, which is a real inline gcc performs today.
 * `noclone` is the smallest denial that is about the mechanism rather than
 * about this box's layout. It cannot be moved to the caller side, and a
 * user's CFLAGS cannot be dictated, which is why the lever lives here in the
 * emitted text.
 *
 * PORTABILITY: `noclone` is documented in GCC's manual since 4.5, and is
 * inside the gcc-dialect mandate this emitter already lives under (computed
 * goto, `__builtin_expect`). MEASURED, because a silently-IGNORED attribute
 * would make this fix a no-op that still looks landed: gcc 15.2.0 accepts it
 * under `-Wattributes -Werror` without an ignored-attribute diagnostic. It
 * also rides the STATIC prefilter, deliberately — measured neutral on the
 * VM+prefilter case (j), and the prefilter is the same split-eligible
 * shape. */
/* [DD-14 wave G] HOW MANY CAPTURE PAIRS THIS ARTIFACT PROMISES, in ONE place
 * both emitters read (`src/gen/emit_vm.c` had the only copy and now calls
 * this). `ncaps` is `ngroups + 1` — group 0 is the whole match — or 1 when the
 * caller asked for no captures.
 *
 * IT USED TO BE THE CONSTANT 1 ON THE DFA PATH, and the comment that said so
 * ("RX_NCAPS > 1 implies the VM — one checkable line") was true only while
 * every capture-bearing pattern forced the VM. Wave G's DEAD-CAPTURE ELISION
 * broke that implication in the direction that matters: a group whose only
 * lexical occurrence sits under a zero-count repeat can never be WRITTEN, so
 * it cannot force an engine — but PCRE2 still COUNTS it and still reports it
 * UNSET (MEASURED on 10.46: `(?(DEFINE)(?<g>a))(?&g)` has CAPTURECOUNT 1 and
 * answers g1 = unset after a match), so the artifact must still promise it.
 * A DFA artifact with `ncaps > 1` is exactly that pattern: every group above 0
 * is PERMANENTLY unset, which `emit_search_head` writes once at entry. */
static int dfa_artifact_ncaps(Ctx *cx)
{
    return cx->want_caps ? (int)cx->ncap + 1 : 1;
}

static void emit_search_head(Ctx *cx, StrBuf *c, const char *fn,
                             const char *storage)
{
    sb_puts(c, "/* K24: noclone denies gcc's partial-inlining pass the\n"
               "   .part clone of this function -- the split costs a\n"
               "   measured 1.33x on a scan-bound pattern, with identical\n"
               "   instructions, purely from code placement. Do not remove;\n"
               "   see pcrec docs/dev/known_issues.md K24. */\n"
               "__attribute__((noclone))\n");
    sb_printf(c, "%sint %s(const unsigned char *subject, size_t subject_length, "
                 "size_t search_from, ptrdiff_t (*capture_spans)[2])\n{\n", storage, fn);
    /* [DD-14 wave G] THE DEAD GROUPS, DECLARED AND PERMANENTLY UNSET. Emitted
     * only when this artifact promises more than the whole match, which on
     * this engine means every promised group is dead (a live one would have
     * forced the VM), so the honest value for all of them is the same constant
     * and it can be written once at entry rather than on each exit. Writing it
     * HERE rather than in `rx_match_caps` is what makes it true for a caller
     * that drives `rx_search` directly, which tests/codegen's K27 fixture
     * does. The failure paths below cast `capture_spans` to void; that stays
     * correct — a redundant cast is not a diagnostic.
     *
     * `fit.chosen == ENGM_DFA` IS LOAD-BEARING AND WAS MEASURED THE HARD WAY.
     * This emitter has TWO customers: it writes the artifact's own engine, and
     * it writes the VM hybrid's internal DFA PREFILTER (`pcrec_emit_dfa_engine`
     * with `static` storage). The prefilter's search function takes the same
     * `capture_spans` parameter and never reports a group — the VM does that —
     * so filling there would put this loop into every capture-bearing VM
     * artifact in the corpus. It did: the first version of this line moved 558
     * of the identity gate's 2442 call-free patterns, including `(((a)))`,
     * which has nothing to do with wave G. The gate caught it on its first
     * run, which is the argument for the gate. */
    if (cx->job->fit.chosen == ENGM_DFA && dfa_artifact_ncaps(cx) > 1) {
        GenNames gn;
        pcrec_gen_names(cx, &gn);
        sb_printf(c,
            "    if (capture_spans)\n"
            "        for (int rx_g = 1; rx_g < %s_NCAPS; rx_g++) {\n"
            "            /* every group this artifact promises is reached only\n"
            "               through a subroutine call or sits under a {0}, so no\n"
            "               match can set it (PCRE2 reports the same) */\n"
            "            capture_spans[rx_g][0] = PCREC_UNSET;\n"
            "            capture_spans[rx_g][1] = PCREC_UNSET;\n"
            "        }\n", gn.upper);
    }
}

