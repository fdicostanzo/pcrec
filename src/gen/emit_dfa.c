/* DFA -> C code generation, two engines (see docs/dev/decisions.md D3/D7):
 *
 * ENG_UNANCH (patterns without `^`, including `$`-bearing ones since M2.7):
 * one O(n) forward pass over the
 * subject with the unanchored priority DFA (finds the leftmost-first match
 * END), then a backward pass with the non-pruning reverse DFA (earliest
 * accepting position = match START). Emitted TABLE-DRIVEN — int16 transition
 * tables + a generic loop — because gcc's compile time on huge computed-goto
 * functions is superlinear (R1 A-3) while data initializers stay flat. A
 * memchr (single escape byte) or bitmap skip loop runs while the machine is
 * parked in the start state (M2.1 prefilter).
 *
 * ENG_ATTEMPT (patterns containing `^`): per-start-position computed-goto
 * attempt loop with EOL-variant states (R1 S-C1/S-C2). `^` needs a
 * position-dependent BOT variant in the REVERSE machine, which the DFA does
 * not build yet, so these stay here; fully-anchored patterns get the
 * start_max=0 fast path, so the slow shape is `^` on only SOME branches.
 *
 * Generated code is self-contained: no dependency on pcrec at build or run
 * time.
 *
 * [M4.4] (docs/design/match_api_m4.md, the MATCH-API FREEZE): the API BREAK
 * lands mechanically here. `<prefix>_span`/`emit_span_typedef` are RETIRED
 * (D44.2) in favor of a caps-array `<prefix>_search` parameter that is
 * already its FINAL shape; the fixed-literal ABI types (`rx_ctx`,
 * `rx_matchfn`, `rx_callout_ref`, `rx_group_entry`, `rx_info`,
 * `rx_renderfn`) are emitted once per file; `<prefix>_match` and
 * `<prefix>_match_caps` are new unconditional exports, retrofitted onto the
 * existing DFA matchers by calling through `<prefix>_search` rather than by
 * building a second, genuinely-anchored automaton (nothing at [M4.4]
 * requires the VM); and `<prefix>_info` is a new `.rodata` reflection
 * structure. See that document's §11 for the itemized checklist this file
 * discharges. */

