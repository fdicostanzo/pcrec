/* The standalone main(), shared verbatim: it drives `<prefix>_search` through
 * the caps array and prints caps[0], which is engine-independent.
 *
 * [K21 fix] `<prefix>_search`'s return is THREE-VALUED (match_api_m4.md
 * §4.5): 1 match, 0 no-match, or a negative give-up sentinel
 * (PCREC_ERR_STEPS/PCREC_ERR_FRAMES) when a VM artifact exhausts its step budget
 * or backtrack-frame capacity — DFA artifacts never return the sentinels.
 * The prior version tested the result as a boolean, so C truthiness took
 * the match branch on a negative return and printed `caps`, which the
 * give-up path never wrote — uninitialized-stack output reported as a
 * confident match (K21, docs/dev/known_issues.md). Branch on the actual
 * value instead, mirroring tests/fuzz/fuzz_driver.c's three-way
 * discrimination, and give the give-up case its own exit code (3) so it
 * cannot be mistaken for either match (0) or no-match (1) — or for this
 * main()'s own usage error, which already claims 2. */
void pcrec_emit_main(Ctx *cx, const GenNames *g)
{
    sb_puts(&cx->job->csb, "\n");
    sb_printf(&cx->job->csb,
        "int main(int argc, char **argv)\n{\n"
        "    /* Initialized: gcc -O1 false maybe-uninitialized (pcrec K28). */\n"
        "    ptrdiff_t capture_spans[%s_NCAPS][2] = {{0}};\n"
        "    if (argc < 2) { fprintf(stderr, \"usage: %%s <subject>\\n\", argv[0]); return 2; }\n"
        "    int rc = %s((const unsigned char *)argv[1], strlen(argv[1]), 0, capture_spans);\n"
        "    if (rc == 1) {\n"
        "        printf(\"match %%td %%td\\n\", capture_spans[0][0], capture_spans[0][1]);\n"
        "        return 0;\n"
        "    }\n"
        "    if (rc == 0) {\n"
        "        printf(\"nomatch\\n\");\n"
        "        return 1;\n"
        "    }\n"
        /* [counter-K] One arm PER CODE, and a fallthrough that does not claim
         * to know. This block used to end `printf("frames")` for everything
         * that was not a match, a no-match or ERR_STEPS — so when the third
         * bound landed, a work give-up was reported as a FRAME overflow. That
         * is precisely the failure DD-2's "different failures, different
         * diagnoses" exists to prevent, reached from inside our own harness,
         * and it is why the last arm now reports the code instead of guessing
         * at its meaning. */
        "    if (rc == PCREC_ERR_STEPS) {\n"
        "        printf(\"steps\\n\");\n"
        "        return 3;\n"
        "    }\n"
        "    if (rc == PCREC_ERR_FRAMES) {\n"
        "        printf(\"frames\\n\");\n"
        "        return 3;\n"
        "    }\n"
        "    if (rc == PCREC_ERR_WORK) {\n"
        "        printf(\"work\\n\");\n"
        "        return 3;\n"
        "    }\n"
        "    printf(\"giveup %%d\\n\", rc);\n"
        "    return 3;\n"
        "}\n", g->upper, g->searchfn);
}

/* [DD-13] (plan.md [DD-13] "BENCH-DISCOVERED CANDIDATES" (a); pcrec-bench
 * inbox I-3) THE DFA ARTIFACT'S SELECTION FACTS.
 *
 * THE GAP THIS CLOSES. D46 rules every selection point observable. A VM
 * artifact says which engine it is, which prefilter it took and which rungs it
 * used; a DFA artifact said only `RX_ALTCLS_MERGES`/`_FACTORED` — so its
 * candidate-start prefilter, which is the email specimen's headline ~23x
 * mechanism on a megabyte with no `@` in it, was invisible to any consumer
 * that was not reading the emitted loop. pcrec-bench, the optimization loop's
 * customer, bucketed every DFA row by `rx_info.engine` alone until this
 * landed.
 *
 * WHY THE OLD RULE SAID NO, AND WHY IT NO LONGER DOES. §6.3 ruled the D46
 * macros VM-only on the premise that "a DFA artifact has nothing to report"
 * (emit_vm.c's own comment adds the §5.4 byte-identity worry). The premise is
 * false since wave G: this engine makes real, artifact-wide decisions — the
 * scan shape and the prefilter form — and the byte-identity worry is an
 * argument FOR an unconditional stamp rather than against it, because §6.3's
 * own closing warning is that "a consumer that `#if`s on `RX_ENGINE` is
 * writing code that does not compile against half the artifacts". A macro that
 * exists on EVERY artifact is the only shape that warning can be answered
 * with. The identity gates pay for it once, as an `abi` bump and a re-pin
 * (D76/[TT-11]); they do not pay for it again.
 *
 * SCALARS, NOT MASKS, and the test is emit_vm.c's: a mask is for an axis
 * decided PER QUANTIFIER, where a scalar would lie on a mixed artifact. Both
 * facts below are decided ONCE per artifact — `job->engine` at src/core/
 * compile.c's `nfa_has_bot` fork, the prefilter at `unanch_start`/
 * `attempt_cand` — so there is no mixing axis and nothing for a mask to say.
 *
 * THE VALUES ARE READ OFF THE SAME DERIVATIONS THE LOOP IS EMITTED FROM,
 * never a second copy of their conditions: `unanch_start` (ENG_UNANCH) and
 * `attempt_cand` (ENG_ATTEMPT) are each ONE function with two readers, and
 * each says so in its own header. That is what makes the stamp checkable
 * rather than decorative — it cannot disagree with the loop unless the
 * derivation itself is wrong, in which case the loop is wrong too. */
/* [DD-13c] WHICH SCAN SHAPE THE EMITTED BODY IS, in the three words §6.3
 * documents. `"empty"` is FIRST and not a fallback: a body that is one
 * `return 0` has neither of the other two loops in it, whichever emitter wrote
 * it, so answering "which emitter ran" before "is there a loop at all" is the
 * inversion that produced r37 #5. */
static const char *dfa_scan_name(Ctx *cx)
{
    if (dfa_engine_is_empty(cx)) return "empty";
    return cx->job->engine == PCREC_ENG_ATTEMPT ? "attempt" : "unanchored";
}

static const char *dfa_prefilter_name(Ctx *cx)
{
    /* [DD-13c] THE EMPTY ENGINE HAS NO PREFILTER TO NAME, and it does not need
     * a clause here to say so: `attempt_cand` refuses on `d->n == 0` and
     * `unanch_start` returns with `kind == DFA_PF_NONE` on `empty`, so both
     * arms below already answer "none" for exactly the artifacts
     * `dfa_engine_is_empty` identifies. An `if` here would be a THIRD statement
     * of that fact, and the check (tests/codegen/run_dfa_stamps.sh) asserts it
     * from the emitted text instead. */
    if (cx->job->engine == PCREC_ENG_ATTEMPT) {
        /* ENG_ATTEMPT skips whole ATTEMPTS rather than positions inside one
         * (D63's loop-integration split), so it needs no D11 bound and has no
         * bounded form: `attempt_cand` is memchr-or-nothing by charter, and
         * the derivation's own comment says the bitmap instance would be
         * emitted code no pattern reaches. `<PREFIX>_DFA_SCAN` below is the
         * other half of the key: it tells a reader WHICH loop this memchr is
         * in. */
        CandSet acand;
        return attempt_cand(&cx->job->dfa, &acand) ? "memchr" : "none";
    }
    UnanchStart us;
    unanch_start(cx, &us);
    /* THE BOUND IS PART OF THE VALUE, and that is plan.md [DD-13] (b) made
     * readable rather than a distinction invented here. Under `views` — a
     * `$`/`\Z`/`\z` view or a word context — every skip is bounded at `n - 1`
     * and the memchr arm loses its `return 0` early-out, so the SAME
     * candidate table buys measurably less: the bench measured the `(?:P)\z`
     * spelling's skip loop as strictly weaker than the plain form's, and a
     * consumer that could not tell the two apart would attribute the
     * difference to the pattern. The emitter CAN tell (`us.views` is the same
     * flag the emitted `fbound` string is built from), so it says so. */
    /* [ENG-FORM] THE STAMP IS THE CHOSEN OBJECT'S NAME, and the five values
     * are five OBJECTS: the `-bounded` half is a genuinely different emitted
     * loop, not a suffix this function appends, so it cannot disagree with
     * the loop the emitter wrote. */
    return dfa_pf_of(cx, &us)->c.name;
}

/* [DD-13c] WHICH DFA SCAN THIS ARTIFACT CARRIES — the two lines, emitted from
 * ONE place for the TWO artifact kinds that contain a DFA scan.
 *
 * WHICH DFA. The ENG_UNANCH/ENG_ATTEMPT fork is a genuine per-artifact
 * selection point — [OS-4] calls it "already a cartesian split" and is the row
 * that will one day measure it — and it is not derivable from anything else a
 * consumer can read: both shapes stamp `RX_ENGINE "dfa"` and both set
 * `rx_info.engine` to PCREC_ENGINE_DFA. A bench row that times a `^`-anchored
 * pattern and one that times an unanchored one are timing two different loops,
 * and until this line existed the report could not say which. Read off
 * `job->engine` (the field compile.c sets at the fork) through
 * `dfa_scan_name`, so it cannot disagree with which emitter ran, plus
 * `dfa_engine_is_empty` for the body that has no loop at all (r37 #5).
 *
 * WHY A SHARED EMITTER AND NOT TWO CALL SITES, which is `pcrec_emit_engine_stamp`'s
 * argument one level down and r37 #6's finding one level up. The §6.1 HYBRID —
 * a VM artifact whose `fit.prefilter` is on — inlines THIS FILE'S scan as
 * `static <prefix>_prefilter` and carries the whole mechanism: the tables, the
 * memchr/bitmap candidate-start filter, the D11 bound. Until [DD-13c] it
 * stamped nothing about any of it, so the artifact kind that actually ships the
 * specimen's ~23x mechanism was the one kind that could not say so. It now
 * stamps these same two lines, from the same `unanch_start`/`attempt_cand`
 * derivations the inlined loop is emitted from — ONE derivation, THREE readers
 * (the loop, the DFA artifact's stamp, the hybrid's stamp), never a
 * restatement. A NON-hybrid VM artifact contains no DFA scan and stamps
 * neither; docs/spec/match_api.md §6.3 states that iff and
 * tests/codegen/run_dfa_stamps.sh asserts it in both directions.
 *
 * `upper` IS A PARAMETER rather than re-derived here because the two callers
 * already hold it (`GenNames.upper` on the DFA side, `v.up` on the VM side)
 * and they are the same string — the artifact's prefix, upper-cased, once. */
/* [OPT-K] THE OFFSET-k SET, AS A STAMP — and it is a SECOND stamp rather than
 * a widening of `<PREFIX>_DFA_PREFILTER` for one reason. [ENG-FORM]'s rule is
 * that `DFA_PREFILTER`'s value IS the chosen object's `name`, a static string
 * that cannot disagree with the loop because it is the loop's own selection;
 * a value computed from THIS MACHINE's k-set is a different kind of fact and
 * folding it in would put a `stamp()` method back on axis B, which
 * `emitter_form.md` §3's revision deliberately removed.
 *
 * `"none"` on every artifact whose forward scan carries no offset-k skip,
 * which is every DFA artifact before this row and most after it, so the value
 * set is countable by the form census. The scan offset is marked `*`. */
static void dfa_prefilter_offsets(Ctx *cx, StrBuf *out)
{
    /* NO EMPTY-ENGINE CLAUSE, for `dfa_prefilter_name`'s reason one function
     * up: `unanch_start` returns `kind == DFA_PF_NONE` on an empty engine, the
     * selection is then never asked, and `nsel` is zero — so the arm below
     * already answers "none" for exactly those artifacts. A clause here would
     * be a fourth statement of that fact. ENG_ATTEMPT needs its own arm
     * because `unanch_start` is not the derivation it uses. */
    if (cx->job->engine == PCREC_ENG_ATTEMPT) { sb_puts(out, "none"); return; }
    UnanchStart us;
    unanch_start(cx, &us);
    if (dfa_pf_of(cx, &us)->emit_block == NULL) { sb_puts(out, "none"); return; }
    for (int i = 0; i < us.ofsk.nsel; i++)
        sb_printf(out, "%s%d%s", i ? "," : "", us.ofsk.k[us.ofsk.sel[i]].k,
                  i == us.ofsk.scan ? "*" : "");
}

void pcrec_emit_dfa_scan_stamps(Ctx *cx, StrBuf *c, const char *upper)
{
    sb_printf(c, "#define %s_DFA_SCAN \"%s\"\n", upper, dfa_scan_name(cx));
    sb_printf(c, "#define %s_DFA_PREFILTER \"%s\"\n", upper,
              dfa_prefilter_name(cx));
    sb_printf(c, "#define %s_DFA_PREFILTER_OFFSETS \"", upper);
    dfa_prefilter_offsets(cx, c);
    sb_puts(c, "\"\n");
    sb_printf(c, "#define %s_DFA_TABLE \"%s\"\n", upper, dfa_table_name(cx));
}

static void emit_dfa_stamps(Ctx *cx, StrBuf *c, const char *upper)
{
    sb_puts(c, "/* Engine: dfa */\n");
    pcrec_emit_engine_stamp(c, upper, "dfa");
    pcrec_emit_dfa_scan_stamps(cx, c, upper);
    sb_puts(c, "\n");
}

void pcrec_emit_dfa(Ctx *cx)
{
    StrBuf *c = &cx->job->csb;
    GenNames g;
    pcrec_gen_names(cx, &g);

    /* RX_NCAPS WAS 1 ON EVERY ARTIFACT THIS EMITTER PRODUCED (D42.2), on the
     * argument that a DFA-compiled pattern never promises more than the
     * whole-match slot. [DD-14 wave G] retires the argument, not the rule
     * behind it: a capture-bearing pattern still forces the VM, but a group
     * that no emitted code can WRITE is not capture-bearing in that sense —
     * PCRE2 counts it and reports it UNSET, and this engine can promise
     * exactly that. `RX_NCAPS > 1` on a DFA artifact therefore means "every
     * promised group is permanently unset", which is the line tests/codegen
     * now checks instead. See `dfa_artifact_ncaps`. */
    /* A DFA artifact can carry no backreference — the construct is VM_ONLY by
     * its twelve registry rows and SR-8 refuses `--engine=dfa` on it by name —
     * so its mask is the unconditional entry alone. */
    cx->job->enc_mask = PCREC_ENCE_NEXT_POS;
    {
        /* [DD-14.FB] spec §10.4: the surface is emitted on a DFA artifact
         * too, INERT. This engine has no resume stack and no trail, so the
         * four sizing facts are 0 and the three `_in` entries below accept a
         * descriptor and ignore it. */
        BufSurface bs = pcrec_bufsurface_inert();
        pcrec_emit_prologue(cx, &g, dfa_artifact_ncaps(cx), &bs);
    }
    /* [DD-13] The selection stamps, in the SAME PLACE the VM writes its own —
     * immediately after the shared prologue and before the engine body — so
     * the two artifact kinds put their engine line at the same point of the
     * file and a reader (or a grep) finds it in one place. */
    emit_dfa_stamps(cx, c, g.upper);
    pcrec_emit_dfa_engine(cx, g.searchfn, "");

    sb_puts(c, "\n");
    emit_match_def(c, g.matchfn, g.searchfn, g.upper);
    sb_puts(c, "\n");
    emit_match_caps_def(c, g.matchcapsfn, g.searchfn, g.upper);
    sb_puts(c, "\n");
    emit_in_entry_defs(c, g.searchfn, g.matchfn, g.matchcapsfn, cx->opt->prefix);
    sb_puts(c, "\n");
    pcrec_emit_residual(cx);
    {
        /* The DFA artifact's stamp: it cannot backtrack, cut, or scan
         * frameless, so NONE of the three bounds applies to it and all read
         * as absent rather than as some notional large number. `work_budget`
         * joins `step_budget` in that reading for exactly the same reason —
         * a bound an engine structurally cannot reach is not a bound of 0. */
        BufSurface bs = pcrec_bufsurface_inert();
        InfoStamp st = { 1, NULL, -1, -1, -1, 0, &bs };
        emit_info_def(cx, c, g.infoname, g.upper, &st);
    }

    if (cx->opt->flags & PCREC_EMIT_MAIN)
        pcrec_emit_main(cx, &g);
}
