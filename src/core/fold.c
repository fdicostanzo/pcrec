/* fold.c — THE ASCII CASE-FOLD PARTITION, as one object ([M6.5.2], D23).
 *
 * WHY IT EXISTS AT ALL, and it is not tidiness. Until this module, pcrec's
 * caseless fold had exactly one consumer: `cls_casefold` in src/parse/parse.c,
 * which WIDENS a 32-byte class bitmap at parse time so the emitted matcher has
 * no flag, no branch and no `tolower()` in it (D23's rule that an option
 * compiles away). A CASELESS BACKREFERENCE cannot fold at parse time — its
 * operand is subject text nobody has seen yet — so the fold has to exist a
 * second time, in the ENCODING RESIDUAL entry `$_bref_match_caseless`
 * (src/gen/enc/enc_byte.c), which is TEXT compiled by someone else's toolchain.
 *
 * TWO SPELLINGS OF ONE FACT WITH NOTHING BETWEEN THEM is the shape this
 * project keeps cataloguing, and R32 E8 named it here: the first draft said
 * the module would "reuse the same table as `\b`", which is not available —
 * `cls_casefold` is a bitmap WIDENER, not a byte-to-byte map, and nothing in
 * src/gen/enc/ can call a `static` function in src/parse anyway.
 *
 * SO THE FOLD BECOMES A TABLE, and the table is what the AGREEMENT CHECK reads.
 * `cls_casefold` derives its widening from it (so the parse-time fold IS this
 * table by construction), and `tests/backrefs/fold_agreement_check.c` walks all
 * 65,536 byte pairs asserting that the SHIPPED residual entry — compiled out of
 * an artifact pcrec actually emitted, not out of this file — induces exactly
 * the partition this table does. That is a control with two independent
 * sources, which is the only kind this project counts. Sabotage row S-BR11
 * moves the residual's fold by one byte and the check goes red.
 *
 * WHAT IS IN IT — MEASURED, not assumed (backrefs_design.md §4.1, axis A over
 * all 256 bytes against libpcre2 10.46's 8-bit NON-UTF build): a caseless
 * backreference compare folds EXACTLY the 52 ASCII letters, each with exactly
 * one partner, and NO non-ASCII byte folds at all — 0xB5, 0xDF and 0xFF do
 * not. Axis A' re-measured the same 256 bytes against the SHIPPED compiler's
 * class fold and found ZERO disagreements, so this table is pcrec's existing
 * behaviour written down rather than a new decision.
 *
 * ASCII-ONLY IS DELIBERATE and D23's scope note says why: in the C locale
 * bytes >= 0x80 have no case. A `tolower()` in the emitted artifact would be
 * LOCALE-DEPENDENT at the CALLER's run time, in a locale pcrec does not
 * control, and an artifact whose answers change with `setlocale` is not the
 * self-contained matcher APPROACH promises. UTF-8's fold is a different
 * question with a different answer (one-to-many foldings, partners of
 * different byte lengths) and belongs to M5's backend, whose residual entry
 * replaces the byte one's body without the emitter changing a character. */

#include "core/internal.h"

