C(r"x[ab]?\z", "B: bounded with an optional tail", S("xa", "x", "xab", "xb\n"))

def esc(ch_s):
    out = []
    for ch in ch_s:
        if ch == "\n": out.append("\\n")
        elif ch == '"': out.append('\\"')
        elif ch == "\\": out.append("\\\\")
        elif 32 <= ord(ch) < 127: out.append(ch)
        else: out.append("".join("\\x%02x" % x for x in ch.encode("utf-8")))
    return "".join(out)

def oracle(binp, scratch, pat, utf8, subj, sp):
    f = os.path.join(scratch, "rsubj")
    with open(f, "wb") as h:
        h.write(subj.encode("utf-8"))
    r = subprocess.run([binp, ("(*UTF)" if utf8 else "") + pat, f, str(sp)],
                       capture_output=True, timeout=60)
    return r.stdout.decode().split()

def main():
    binp, scratch = sys.argv[1:3]
    os.makedirs(scratch, exist_ok=True)
    print(HEADER)
    for pat, utf8, why, subs in CELLS:
        print()
        print("# " + why)
        print("# pcre2-only")
        print("pattern " + pat)
        if utf8: print("encoding utf8")
        fs = []
        if any(t in pat for t in ("\\z", "\\Z", "\\b", "\\B", "\\G", "\\K", "(?m)")): fs.append("assertions")
        if any(t in pat for t in ("\\d", "\\w", "\\s", "[")): fs.append("classes")
        if "(?=" in pat or "(?!" in pat: fs.append("lookaround")
        if "(?m)" in pat: fs.append("modifiers")
        if fs: print("features " + ",".join(fs))
        for sp, s in subs:
            ans = oracle(binp, scratch, pat, utf8, s, sp)
            if not ans or ans[0] not in ("match", "nomatch"):
                sys.exit("oracle: %r on %r at %d: %s" % (pat, s, sp, ans))
            pre = "" if sp == 0 else "%d " % sp
            if ans[0] == "nomatch":
                print('%s %s"%s"' % ("n" if sp == 0 else "ns", pre, esc(s)))
            else:
                print('%s %s"%s" %s %s' % ("m" if sp == 0 else "ms", pre, esc(s), ans[1], ans[2]))
                v = ans[1:]
                for k in range(1, len(v) // 2):
                    print("g %d %s %s" % (k, v[2 * k], v[2 * k + 1]))

main()
