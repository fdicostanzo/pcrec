import os, subprocess, sys

CELLS = []

def C(pat, why, subs, utf8=False):
    CELLS.append((pat, utf8, why, subs))

def S(*xs):
    return [(0, x) for x in xs]

def SP(s, *sps):
    return [(sp, s) for sp in sps]

