#!/usr/bin/env python3
"""tests/utf8/gen_landing_illformed.py -- writes landing_illformed.rxt, the
[START-LANDING] ill-formed-landing cells (docs/design/start_landing.md §7.3
§6; lane slbuild).

The RECOVER row `landing` reads the match start off the position the forward
scan last landed on; under the invalid-tolerant contract the character there
may not decode, and §2.5's post-loop skip steps to the first position after it
that does. Every pattern below takes `landing` with the guard (a first byte
above the one-byte repertoire); every subject puts an ill-formed or truncated
sequence where a landing falls.

THE ORACLE IS libpcre2 (the system's 10.46 on the Linux dev box) under
PCRE2_UTF|PCRE2_MATCH_INVALID_UTF -- the barrier semantics pcrec promises (an
ill-formed sequence matches nothing) -- through a C helper compiled here and
linked with -lpcre2-8, at EVERY startpos pcrec accepts (0, n, and every
position that is not a continuation byte: a mid-character startpos is K50's
refusal, which libpcre2 answers differently, K75). The expectations are
written FROM the oracle, never from pcrec; tests/codegen/run_start_landing.sh
runs the file under every deny arm.

Run from the repo root: python3 tests/utf8/gen_landing_illformed.py
(needs gcc and libpcre2-8). Scratch goes under build/. The output is
committed; this generator is the record of how it was made.
"""
import os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCR = os.path.join(ROOT, "build", "gen_landing")
os.makedirs(SCR, exist_ok=True)
HELPER = r'''
#define PCRE2_CODE_UNIT_WIDTH 8
#include <pcre2.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
static int unhex(int c){return c<='9'?c-'0':(c|32)-'a'+10;}
int main(int argc, char **argv){
    int en; PCRE2_SIZE eo;
    pcre2_code *re = pcre2_compile((PCRE2_SPTR)argv[1], PCRE2_ZERO_TERMINATED,
                                   PCRE2_UTF|PCRE2_MATCH_INVALID_UTF, &en, &eo, NULL);
    if (!re) { printf("ERR\n"); return 1; }
    const char *h = argv[2]; size_t n = strlen(h)/2;
    unsigned char *s = malloc(n+1);
    for (size_t i=0;i<n;i++) s[i]=(unsigned char)(unhex(h[2*i])*16+unhex(h[2*i+1]));
    pcre2_match_data *md = pcre2_match_data_create_from_pattern(re, NULL);
    long sp = atol(argv[3]);
    int rc = pcre2_match(re, s, n, (PCRE2_SIZE)sp, 0, md, NULL);
    if (rc >= 0) { PCRE2_SIZE *ov = pcre2_get_ovector_pointer(md);
        printf("M %zu %zu\n", (size_t)ov[0], (size_t)ov[1]); }
    else if (rc == PCRE2_ERROR_NOMATCH) printf("N\n");
    else printf("E %d\n", rc);
    return 0; }
'''
src = os.path.join(SCR, "oracle.c"); exe = os.path.join(SCR, "oracle")
open(src, "w").write(HELPER)
subprocess.run(["gcc", "-O1", "-o", exe, src, "-lpcre2-8"], check=True)

PATTERNS = [".", r"\p{L}+", "[a-zé]+", ".x?"]
TOKENS = [b"\xc3a", b"\xc3\xc3\xa9", b"\xe2\x82a", b"\xf0\x9f\x98a",
          b"\xed\xa0\x80a", b"\xc0\x80a", b"\xc3", b"\xe2\x82", b"\xff\xfea",
          b"\xc3\xa9", b"a\xc3a", b"\x80\xc3\xa9"]

def esc(b):
    return "".join(chr(c) if 0x20 <= c < 0x7f and c not in (0x22, 0x5c) else "\\x%02x" % c for c in b)

def boundary(s, p):
    return p == 0 or p >= len(s) or (s[p] & 0xC0) != 0x80

out = ["# tests/utf8/landing_illformed.rxt -- GENERATED by gen_landing_illformed.py",
       "# ([START-LANDING], lane slbuild): the RECOVER row `landing` with its",
       "# post-loop guard, on subjects whose landing falls on an ill-formed or",
       "# truncated sequence, at every startpos pcrec accepts. Oracle: libpcre2",
       "# under PCRE2_UTF|PCRE2_MATCH_INVALID_UTF (an ill-formed sequence matches",
       "# nothing). Do not edit by hand; re-run the generator.", ""]
ncell = 0
for pat in PATTERNS:
    pb = pat.encode("utf8")
    out.append("# pcre2-only")
    out.append("pattern " + pat)
    out.append("encoding utf8")
    for t in TOKENS:
        for p in range(len(t) + 1):
            if not boundary(t, p): continue
            r = subprocess.run([exe, pb, t.hex(), str(p)], capture_output=True, text=True).stdout.split()
            if r[0] == "M":
                out.append('ms %d "%s" %s %s' % (p, esc(t), r[1], r[2]))
            elif r[0] == "N":
                out.append('ns %d "%s"' % (p, esc(t)))
            else:
                sys.exit("oracle error %r on %r %r %d" % (r, pat, t, p))
            ncell += 1
    out.append("")
open(os.path.join(ROOT, "tests", "utf8", "landing_illformed.rxt"), "w").write("\n".join(out))
print("wrote %d cells" % ncell)
