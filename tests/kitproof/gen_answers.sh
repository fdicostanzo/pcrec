#!/usr/bin/env bash
# tests/kitproof/gen_answers.sh — regenerate answers.tsv from cases.tsv's
# `answer` rows through libpcre2 (oracle.c). NOT run by `make test`: the
# answers are committed so the check needs no libpcre2. Run it when a case is
# added, on a box whose libpcre2-8 is 10.46 (the version is checked).
#
# Usage: bash tests/kitproof/gen_answers.sh [ROOT]
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
root="${1:-$(cd "$here/../.." && pwd)}"
out="$root/build/kitproof"
mkdir -p "$out"
ver="$(pcre2-config --version)"
[ "$ver" = "10.46" ] || { echo "gen_answers: libpcre2 is $ver, the expectations are 10.46's" >&2; exit 1; }
gcc -O2 -std=gnu11 -o "$out/oracle" "$here/oracle.c" -lpcre2-8
python3 -I - "$here/cases.tsv" > "$out/oracle_in.tsv" <<'EOF'
import sys
for ln in open(sys.argv[1], encoding='latin-1'):
    if ln.startswith('#') or not ln.strip():
        continue
    k, fl, pat, val, _ = ln.rstrip('\n').split('\t')
    if k == 'answer':
        print('%s\t%s\t%s' % (fl, pat.encode('latin-1').hex(), val))
EOF
{
    echo "# tests/kitproof/answers.tsv -- GENERATED by gen_answers.sh from cases.tsv through"
    echo "# oracle.c over libpcre2 $ver; do not edit. FLAGS<TAB>PATTERN_HEX<TAB>SUBJECT_HEX<TAB>ANSWER"
    "$out/oracle" < "$out/oracle_in.tsv"
} > "$here/answers.tsv"
echo "gen_answers: $(grep -vc '^#' "$here/answers.tsv") answers written"
