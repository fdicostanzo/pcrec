r"""tests/oracle/case_map_check.py -- [SUBST-CASE] the generated case map held
to Unicode's simple case mappings, and to libpcre2 10.46 except a pinned list.

WHAT IS CHECKED (D180): src/core/case_tables.inc (an output of
third_party/ucd-16.0.0/generate.py) for EVERY scalar value U+0000-10FFFF minus
the surrogates -- presence AND absence:
  (1) it equals the UCD: UnicodeData.txt field 12 (upper) / 13 (lower),
      parsed HERE, never through the generator;
  (2) it equals libpcre2 10.46's answers (oracle_store/libpcre2-10.46-utf/
      case-map.tsv, captured by build_casemap_store.py) EXCEPT at the code
      points of tests/oracle/case_map_pcre2_diff.tsv, whose count is pinned
      below (EXPECTED_DIFF).  A 151st difference, or one listed point that
      stops differing, fails.

THE CONTROLS ARE INDEPENDENT OF WHAT THEY CONTROL: the UCD is parsed here
from the vendored file, the stored answers come from running libpcre2, and
the worst-growth constants are re-derived here from the UCD.

Prints `checks passed: N` / `checks failed: M` (the section's own contract),
exit 1 on any failure. `--sabotage-selftest` flips one parsed entry in memory
and requires the comparison to fail (the check can fail at all).
`--write-diff` rewrites the pinned list from the two sources (a developer
step; the count it prints is then re-pinned by hand, deliberately).

Usage: python3 -I tests/oracle/case_map_check.py [--sabotage-selftest|--write-diff]
"""
import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.normpath(os.path.join(_HERE, "..", ".."))
sys.path.insert(0, _HERE)

import oracle_store as os_  # noqa: E402

INC = os.path.join(_ROOT, "src", "core", "case_tables.inc")
STORE = os.path.join(_ROOT, "oracle_store")
UCD = os.path.join(_ROOT, "third_party", "ucd-16.0.0", "UnicodeData.txt")
DIFF = os.path.join(_HERE, "case_map_pcre2_diff.tsv")
EXPECTED_DIFF = 150      # code points where libpcre2 10.46 differs from the UCD
OID = os_.OracleId("libpcre2", "10.46", utf=True)

passed = failed = 0


def check(ok, what):
    global passed, failed
    if ok:
        passed += 1
    else:
        failed += 1
        print("FAIL: %s" % what)


def utf8_len(cp):
    return 1 if cp < 0x80 else 2 if cp < 0x800 else 3 if cp < 0x10000 else 4


def parse_inc(text):
    """{'upper': [(cp, to)...], 'lower': [...]} plus the two growth defines."""
    out = {}
    for d in ("upper", "lower"):
        m = re.search(r"pcrec_case_%s_map\[\] = \{\n(.*?)\n\};" % d, text, re.S)
        if not m:
            raise SystemExit("case_tables.inc: no %s array" % d)
        out[d] = [(int(a, 16), int(b, 16)) for a, b in
                  re.findall(r"\{0x([0-9A-Fa-f]+),0x([0-9A-Fa-f]+)\}", m.group(1))]
        c = re.search(r"#define PCREC_CASE_%s_COUNT (\d+)" % d.upper(), text)
        out[d + "_count"] = int(c.group(1)) if c else None
        g = re.search(r"#define PCREC_CASE_%s_MAX_GROWTH (\d+)" % d.upper(), text)
        out[d + "_growth"] = int(g.group(1)) if g else None
    return out


def ucd_maps():
    """{'upper': {cp: to}, 'lower': {cp: to}} from fields 12/13, identity out."""
    out = {"upper": {}, "lower": {}}
    with open(UCD, "r", encoding="utf-8") as f:
        for line in f:
            fl = line.rstrip("\n").split(";")
            if len(fl) != 15:
                continue
            cp = int(fl[0], 16)
            for d, t in (("upper", fl[12]), ("lower", fl[13])):
                if t and int(t, 16) != cp:
                    out[d][cp] = int(t, 16)
    return out


def diff_points(ucd, want):
    """[(cp, direction, pcre2 answer, ucd answer)] over every scalar value."""
    out = []
    for d in ("upper", "lower"):
        for cp in sorted(set(ucd[d]) | set(want[d])):
            if ucd[d].get(cp, cp) != want[d].get(cp, cp):
                out.append((cp, d, want[d].get(cp, cp), ucd[d].get(cp, cp)))
    return out


def read_diff():
    rows = []
    with open(DIFF, "r", encoding="utf-8") as f:
        for ln in f:
            if ln.startswith("#") or not ln.strip():
                continue
            a, d, b, c = ln.split()
            rows.append((int(a, 16), d, int(b, 16), int(c, 16)))
    return rows


def stored(d):
    afields = os_.lookup(STORE, OID, "case-map", direction=d, encoding="utf8")
    if afields is None:
        raise SystemExit("no stored %s row: run build_casemap_store.py" % d)
    pairs = {}
    for tok in afields[0].split():
        a, b = tok.split(">")
        pairs[int(a, 16)] = int(b, 16)
    return pairs


def main():
    sabotage = "--sabotage-selftest" in sys.argv[1:]
    ucd = ucd_maps()
    want = {d: stored(d) for d in ("upper", "lower")}
    if "--write-diff" in sys.argv[1:]:
        rows = diff_points(ucd, want)
        with open(DIFF, "w", encoding="utf-8") as f:
            f.write("# GENERATED by case_map_check.py --write-diff: the code points where libpcre2\n"
                    "# 10.46 (oracle_store/libpcre2-10.46-utf/case-map.tsv) differs from the UCD 16.0.0\n"
                    "# simple case mappings (D180). Columns: cp, direction, libpcre2 result, UCD result.\n"
                    "# Count: %d\n" % len(rows))
            for cp, d, p, u in rows:
                f.write("%04X\t%s\t%04X\t%04X\n" % (cp, d, p, u))
        print("wrote %d rows" % len(rows))
        return
    with open(INC, "r", encoding="utf-8") as f:
        tab = parse_inc(f.read())
    pinned = {(cp, d): (p, u) for cp, d, p, u in read_diff()}
    check(len(pinned) == EXPECTED_DIFF,
          "pinned list has %d rows, want %d" % (len(pinned), EXPECTED_DIFF))
    actual = {(cp, d): (p, u) for cp, d, p, u in diff_points(ucd, want)}
    check(actual == pinned,
          "libpcre2 vs UCD differences are not the pinned %d: %d now, extra %s, missing %s"
          % (EXPECTED_DIFF, len(actual),
             " ".join("U+%04X/%s" % k for k in sorted(set(actual) - set(pinned))[:8]),
             " ".join("U+%04X/%s" % k for k in sorted(set(pinned) - set(actual))[:8])))
    for d in ("upper", "lower"):
        have = dict(tab[d])
        if sabotage:
            cp = sorted(have)[0]
            have[cp] += 1
        check(len(have) == len(tab[d]), "%s: duplicate keys in the table" % d)
        check([c for c, _ in tab[d]] == sorted(have) or sabotage,
              "%s: table not sorted by cp" % d)
        check(tab[d + "_count"] == len(tab[d]),
              "%s: COUNT define %r != entries %d"
              % (d, tab[d + "_count"], len(tab[d])))
        bad = []
        n = 0
        for cp in range(0x110000):
            if 0xD800 <= cp < 0xE000:
                continue
            n += 1
            if have.get(cp, cp) != ucd[d].get(cp, cp):
                bad.append(cp)
        check(n == 0x110000 - 0x800, "%s: swept %d scalar values" % (d, n))
        check(not bad, "%s: %d of %d scalar values disagree with the UCD, "
              "first: %s" % (d, len(bad), n, " ".join(
                  "U+%04X(table %X, ucd %X)"
                  % (c, have.get(c, c), ucd[d].get(c, c)) for c in bad[:8])))
        # and with libpcre2 everywhere except the pinned points
        worse = [cp for cp in range(0x110000)
                 if not 0xD800 <= cp < 0xE000
                 and have.get(cp, cp) != want[d].get(cp, cp)
                 and (cp, d) not in pinned]
        check(not worse, "%s: %d scalar values differ from libpcre2 outside the "
              "pinned list, first: %s" % (d, len(worse), " ".join(
                  "U+%04X" % c for c in worse[:8])))
        print("%s: %d scalar values compared, %d mapped by the UCD, "
              "%d in table, %d disagree with the UCD, %d pinned libpcre2 differences"
              % (d, n, len(ucd[d]), len(have), len(bad),
                 sum(1 for k in pinned if k[1] == d)))
        g = max(utf8_len(t) - utf8_len(c) for c, t in ucd[d].items())
        check(tab[d + "_growth"] == g,
              "%s: MAX_GROWTH define %r != %d derived from the UCD"
              % (d, tab[d + "_growth"], g))
        check(len(ucd[d]) > 1000, "%s: the UCD maps only %d" % (d, len(ucd[d])))
    up, lo = ucd["upper"], ucd["lower"]
    check(0xDF not in up and want["upper"].get(0xDF) == 0x1E9E,
          "witness: U+00DF has no UCD upper; libpcre2 maps it to U+1E9E")
    check(lo.get(0x23A) == 0x2C65, "witness: U+023A lower is U+2C65 (2->3 bytes)")
    check(lo.get(0x212A) == 0x6B and up.get(0x17F) == 0x53,
          "witness: KELVIN and LONG S map into ASCII")
    check(lo.get(0x130) == 0x69 and up.get(0x131) == 0x49,
          "witness: U+0130 lower is i, U+0131 upper is I")
    check(up.get(0x1C5) == 0x1C4 and want["upper"].get(0x1C5) == 0x1C6,
          "witness: U+01C5 upper is U+01C4 (libpcre2: U+01C6)")
    check(up.get(0x6B) == 0x4B and lo.get(0x4B) == 0x6B, "witness: k <-> K")
    print("checks passed: %d" % passed)
    print("checks failed: %d" % failed)
    if sabotage:
        sys.exit(0 if failed else 1)      # the self-test wants the red
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
