def esc(ch_s):
    out = []
    for ch in ch_s:
        if ch == "\n": out.append("\\n")
        elif ch == '"': out.append('\\"')
        elif ch == "\\": out.append("\\\\")
        elif 32 <= ord(ch) < 127: out.append(ch)
        else: out.append("".join("\\x%02x" % x for x in ch.encode("utf-8")))
    return "".join(out)

def oracle(binp, scratch, pat, utf8, subj, sp):
    f = os.path.join(scratch, "b3subj")
    with open(f, "wb") as h:
        h.write(subj)
    r = subprocess.run([binp, ("(*UTF)" if utf8 else "") + pat, f, str(sp)],
                       capture_output=True, timeout=60)
    return r.stdout.decode().split()

def next_pos(b, p, utf8):
    """match_api.md §3.1.1's one-character step: from p + 1, past every
    continuation byte under a multi-byte encoding."""
    p += 1
    if utf8:
        while p < len(b) and 0x80 <= b[p] <= 0xBF:
            p += 1
    return p

def findall(binp, scratch, pat, utf8, subj):
    """match_api.md §3.1.3: resume at a non-empty match's end, one character
    past an empty match's REPORTED start."""
    b = subj.encode("utf-8")
    n, pos = 0, 0
    while pos <= len(b):
        a = oracle(binp, scratch, pat, utf8, b, pos)
        if a[0] != "match":
            break
        n += 1
        s, e = int(a[1]), int(a[2])
        pos = e if e > s else next_pos(b, s, utf8)
    return n

def main():
    binp, scratch = sys.argv[1:3]
    os.makedirs(scratch, exist_ok=True)
    print(HEADER)
    for pat, utf8, why, subs, mc in CELLS:
        print()
        print("# " + why)
        print("# pcre2-only")
        print("pattern " + pat)
        if utf8: print("encoding utf8")
        fs = []
        if any(t in pat for t in ("\\z", "\\Z", "\\b", "\\B", "\\G", "\\K", "(?m)")): fs.append("assertions")
        if any(t in pat for t in ("\\d", "\\w", "\\s", "[")): fs.append("classes")
        if "(?m)" in pat: fs.append("modifiers")
        if fs: print("features " + ",".join(fs))
        for sp, s in subs:
            ans = oracle(binp, scratch, pat, utf8, s.encode("utf-8"), sp)
            if not ans or ans[0] not in ("match", "nomatch"):
                sys.exit("oracle: %r on %r at %d: %s" % (pat, s, sp, ans))
            pre = "" if sp == 0 else "%d " % sp
            if ans[0] == "nomatch":
                print('%s %s"%s"' % ("n" if sp == 0 else "ns", pre, esc(s)))
            else:
                print('%s %s"%s" %s %s' % ("m" if sp == 0 else "ms", pre, esc(s), ans[1], ans[2]))
                v = ans[1:]
                for k in range(1, len(v) // 2):
                    print("g %d %s %s" % (k, v[2 * k], v[2 * k + 1]))
        for s in mc:
            print('mc "%s" %d' % (esc(s), findall(binp, scratch, pat, utf8, s)))

main()
