#!/usr/bin/env python3
"""tests/endmark/gen_b3_census.py -- D164 B3 (lane b3build): the probe's
committed per-artifact answers (docs/design/endmark/b3rev/results/census.json,
b3rev_probe.c at e8ca1252: an INDEPENDENT construction of the tagged machine
as the Moore product of two untagged builds, endmark.md §R.6.2 item 2) as the
TSV tests/endmark/run_b3_checks.sh compares the built compiler against.

One row per census artifact: id, pop, enc, icase, pattern (\\t \\n \\\\
escaped), the probe's form row, its mark_prio class (`-` where the probe did
not model it: the context-atom artifacts), and the post-scan-edge state counts
today/tagged for the reverse, forward and anchored machines with today's
emitted bytes per state for each (the G1-G3 expectations, §R.6.1).

Usage: python3 -I gen_b3_census.py CENSUS_JSON > b3_census.tsv"""
import json, sys

MPC = {0: 'none', 1: 'const0', 2: 'const1', 3: 'state-dependent'}

def esc(s):
    return s.replace('\\', '\\\\').replace('\t', '\\t').replace('\n', '\\n')

def per_state(m, role):
    x = m.get(role)
    if not x or not x.get('states'): return '-'
    return '%.1f' % (x['bytes'] / x['states'])

d = json.load(open(sys.argv[1]))
print('# D164 B3: the b3rev probe census (docs/design/endmark/b3rev/results/census.json, at e8ca1252), GENERATED by gen_b3_census.py.')
print('#id\tpop\tenc\ticase\tpattern\trow\tmark_prio\tr_today\tr_tag\tf_today\tf_tag\ta_today\ta_tag\tr_bps\tf_bps\ta_bps')
for r in d:
    p = r['probe']
    m = r['emit']['today']['m']
    mf = r['emit']['today_norev']['m']
    mp = MPC.get(p.get('mp_cls')) if p.get('mp_ok') == 1 else '-'
    print('\t'.join(str(x) for x in [
        r['id'], r['pop'], r['enc'], int(bool(r['icase'])), esc(r['pat']), r['row'], mp,
        p.get('r_today_post', '-'), p.get('r_tag_post', '-'),
        p.get('f_today_post', '-'), p.get('f_tag_post', '-'),
        p.get('a_today_post', '-') if p.get('a_ok') == 1 else '-',
        p.get('a_tag_post', '-') if p.get('a_ok') == 1 else '-',
        per_state(m, 'reverse'), per_state(mf, 'forward'), per_state(mf, 'anchored')]))
