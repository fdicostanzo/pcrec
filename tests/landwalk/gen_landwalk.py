#!/usr/bin/env python3
"""tests/landwalk/gen_landwalk.py -- [LANDWALK] stage 1 (lane p1build): write
tests/landwalk/landwalk.rxt FROM libpcre2's answers (oracle first: every
m/n/ms/ns line is the oracle's answer, never pcrec's), the answer net of the
`landmark-walk` LOCATE row (docs/spec/tuning.md §2.54): hits that lead to no
start, several hits before the match, a walk floored at the start position,
the reach guard's relocation (family R), word context at the walked-to start,
utf8 prefixes, and the declines beside them (family D, the same answers by
another scan).

Usage: gen_landwalk.py ORACLE_BIN SCRATCH_DIR > tests/landwalk/landwalk.rxt
ORACLE_BIN is tests/fuzz/pcre2_oracle.c built against libpcre2-8 (options=0:
`encoding utf8` is carried as a (*UTF) prefix). Re-check the written file
with `tests/revend/verify_stage2.py ORACLE_BIN SCRATCH tests/landwalk/landwalk.rxt`,
which shares no code with this table. tests/landwalk/run_landwalk.sh checks
which of these patterns take the walk (the stamp), so a cell that silently
stops reaching the row is caught there, not here."""
import os, subprocess, sys

CELLS = []

def C(pat, why, subs, utf8=False):
    CELLS.append((pat, utf8, why, subs))

def S(*xs):
    return [(0, x) for x in xs]

def SP(s, *sps):
    return [(sp, s) for sp in sps]

HEADER = """# [LANDWALK] stage 1 THE `landmark-walk` ANSWER NET (lane p1build;
# docs/spec/tuning.md §2.54, docs/dev/lanes/p1build_report.md). GENERATED by
# tests/landwalk/gen_landwalk.py from libpcre2 10.46's answers (every
# m/n/ms/ns line is the oracle's, never pcrec's); tests/revend/verify_stage2.py
# re-reads this file and re-asks the oracle, so every block is `# pcre2-only`.
# Families W, R and U take the walk in the default build
# (`<PREFIX>_DFA_SCAN "landmark-walk"`, held by tests/landwalk/run_landwalk.sh);
# the axes sweep runs the same cells under `-fno-landmark-walk` and
# `-fno-anchored-dfa` (the forward-then-reverse search) and `--engine=vm`.
#
# FAMILIES: W the walk (dead hits, several hits, the floor at the start
# position, the landmark at 0 and at the end); R the reach guard (an anchored
# run that reads past the next landmark relocates); B word context and
# lookbehind at the walked-to start; U utf8 prefixes; D declines (the same
# answers by another scan)."""

EMAIL = r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"
# ---- W: the walk -------------------------------------------------------------
C(r"[a-z]+@x", "W: dead hits (no prefix before @, or no x after), then the match",
  S("@x", "a@x", "@@a@x", "1@x a@y b@x", "ab@xy", "AB@x", "abc@", "", "@", "zz@x@x"))
C(r"[a-z]+@x", "W: the start position floors the walk (a match starting before it is not reported)",
  SP("abc@x", 0, 1, 2, 3, 4) + SP("ab@x cd@x", 1, 4, 5, 6, 9))
C(r"a+b", "W: the landmark is the last byte; runs of a before and between hits",
  S("b", "ab", "aab", "bab", "cbaab", "aaaa", "ba", "aaba ab"))
C(r"a+b", "W: a+b from a start position inside the run",
  SP("aaab", 0, 1, 2, 3, 4) + SP("ab aab", 2, 3, 4, 6))
C(r"[0-9]*aa[bc]", "W: the walk's smallest start is reached over a nullable run",
  S("aab", "12aac", "aaab", "a1aab", "aa", "aabaac", "9aa9aab"))
C(r"[0-9]*aa[bc]", "W: T3 (r5 SOUND-2): a landmark inside the last verify's span; a non-overlapping hit stream answers NOMATCH",
  S("00000aaabb", "aaabb", "0aab0aac"))
C(r"[0-9]*aa[bc]", "W: the nullable run from a start position",
  SP("123aab", 0, 2, 3, 4) + SP("aaab", 1, 2))
C(EMAIL, "W: the 5b population row (mask-email), the walk on @",
  S("x@y.zz", "mail me at a.b@c.de now", "@@@", "a@b", "a@b.c", "a@b.cd.e",
    "first@x second@y.org", "a@@b.cd", ".@-.co", "a b@c.de"))
C(EMAIL, "W: mask-email from start positions",
  SP("ab@cd.ef gh@ij.kl", 0, 1, 2, 3, 9, 12, 17))
C(r"(?:ab|cd)+@x", "W: a prefix of alternated pairs: the walk recovers the pair boundary",
  S("ab@x", "cdab@x", "b@x", "xab@x", "abc@x", "acd@x ab@x"))
C(r"[a-z]++@x", "W: a possessive prefix (the walk's start is the run's first byte)",
  S("ab@x", "@x", "a1b@x", "ab@y cd@x"))
C(r"(?>[a-z]+)@x", "W: an atomic prefix discharged to the same machine",
  S("ab@x", "@x", "a1b@x", "ab@y cd@x"))
C(r"(?i)[a-z]+@X", "W: a caseless landmark and prefix",
  S("Ab@x", "ab@X", "1@x", "AB@Y cd@x"))
C(r"[^@ ]+@x", "W: a negated prefix class (every byte but the landmark and a space)",
  S("a@x", "a b@x", "@x", "\x01\x7f@x", "a@y b@x"))
# ---- R: the reach guard ------------------------------------------------------
C(r"[a-z]+@(?:[a-z]+@)*[a-z]+ ", "R: the anchored run reads past the next @, so a later hit relocates",
  S("a@b ", "a@b@c ", "a@b@c@d", "a@b@c@d ", "a@b@@c ", "@a@b ", "ab@cd@ef@gh@ ij@kl "))
C(r"[a-z]+@(?:[a-z]+@)*[a-z]+!", "R: T6 (rev 1 cell 4): `!` is the landmark, every verify of (a@)^8 reads to the end",
  S("a@" * 8, "a@" * 8 + "a!", "a@b!"))
C(r"[a-z]+@...x", "R: a failed verify reads past the next landmark, whose match starts after the first one (the guard relocates; a hit stream resumed at the reach loses it)",
  S("a@b@cdex", "a@b@cdey", "ab@c@defx", "a@bcdx", "a@@@@x"))
C(r"[a-z]+@(?:[a-z]+@)*[a-z]+ ", "R: the relocation from start positions",
  SP("a@b@c d@e ", 0, 1, 2, 3, 4, 6, 7))
# ---- B: word context and lookbehind at the start ------------------------------
C(r"\b[a-z]+@x\b", "B: \\b at the walked-to start and after the landmark's tail",
  S("ab@x", "1ab@x", "ab@xy", "ab@x1", "_a@x", "a@x b@x"))
C(r"\b[a-z]+@x\b", "B: \\b from a start position inside the word",
  SP("ab@x", 0, 1, 2) + SP("cd ab@x", 1, 3, 4))
C(r"\B[a-z]+@x", "B: \\B: the start is never at a word start",
  S("ab@x", "1ab@x", "aab@x", "a b@x"))
C(r"[a-z]+(?<=a)@x", "B: a lookbehind before the landmark",
  S("ba@x", "ab@x", "a@x", "b@x ca@x"))
# ---- U: utf8 prefixes ----------------------------------------------------------
C(r"[a-zé]+@x", "U: a multi-byte prefix member: the walk lands on a code-point boundary",
  S("é@x", "aé@x", "éé@x", "Ké@x", "€é@x", "é@y é@x"), utf8=True)
C(r"[^@ ]+@x", "U: a negated prefix over multi-byte text",
  S("€@x", "a€b@x", "€ é@x", "@x"), utf8=True)
C(EMAIL, "U: mask-email under utf8 (ASCII landmark, multi-byte text around it)",
  S("é a@b.cd", "€@b.cd", "a@é.cd", "x€y@b.cd"), utf8=True)
# ---- D: declines (the same answers by another scan) ----------------------------
C(r"[^@]+@x", "D: rarity: the prefix is almost every byte, the expected walk is long",
  S("abc@x", "@x", "a@y@x"))
C(r"a.*b@c", "D: exclusion: the prefix can consume the landmark",
  S("ab@c", "a@b@c", "ab@d b@c"))
C(r"x*@y", "D: rarity: a nullable prefix as rare as the landmark",
  S("@y", "xx@y", "x@z@y"))
C(r"[a-z]{2,5}@x", "D: next-landmark: the start filter already hands off to a landmark",
  S("ab@x", "a@x", "abcdef@x"))
C(r"a+b", "D: utf8 has no byte-rate prior, so b is no rarer than a",
  S("aab", "b", "aaa"), utf8=True)
C(r"(*UCP)a\sb", "D: the cls-s-ucp population row under utf8 (rarity)",
  S("a b", "a b", "ab"), utf8=True)
C(r"\Ga+b", "D: \\G (an attempt scan)", SP("aab", 0, 1) + SP("xab", 0, 1))
C(r"a+\Kb", "D: \\K (a VM finisher)", S("aab", "b", "ab"))
# g1's \G and \K are found ANYWHERE in R (lane p1kind): a \G only reaches the
# walk's rows dead (a `{0}` body erases it from the NFA; a live one is an
# attempt scan), nested here in each child-bearing kind; a \K never does (VM).
C(r"[a-z]+@x(?:\G){0}", "D: g1/gstart: \\G in a {0} body (a suffix)",
  S("a@x", "@x", "1@x ab@x") + SP("ab@x", 1, 2))
C(r"(?:\G){0}[a-z]+@x", "D: g1/gstart: \\G in a {0} body (the prefix head)",
  S("a@x", "@x", "1@x ab@x") + SP("ab@x", 1, 2))
C(r"[a-z]+@x(?(DEFINE)(?<g>y\G))", "D: g1/gstart: \\G in a named group in a DEFINE body",
  S("a@x", "y@x", "1@x ab@xy") + SP("ab@x", 1))
C(r"[a-z]+@x(?:(y|\G)+){0}", "D: g1/gstart: \\G in an alternation in a repeated capture in a {0} body",
  S("a@x", "@x", "ab@xy") + SP("ab@x", 1))
C(r"[a-z]+@x(?:[yz]\G){0}", "D: g1/gstart: \\G after a class in a {0} body",
  S("a@x", "@x", "ab@xz") + SP("ab@x", 1))
C(r"[a-z]+@x(?(DEFINE)(?<k>\K))", "D: \\K in a DEFINE body (a VM finisher, never the g1 row)",
  S("a@x", "@x", "ab@x") + SP("ab@x", 1))
C(r"(?![a-z]*b)[a-z]+@x", "D: T1 (r5 SLOT-4): a VM hybrid's erased prefilter body declines at finisher-dfa",
  S("ba@x", "ab@x", "bb@x", "cab@x"))
C(r"ab|cd", "D: branches", S("ab", "xcd", "ac"))

def esc(ch_s):
    out = []
    for ch in ch_s:
        if ch == "\n": out.append("\\n")
        elif ch == '"': out.append('\\"')
        elif ch == "\\": out.append("\\\\")
        elif 32 <= ord(ch) < 127: out.append(ch)
        else: out.append("".join("\\x%02x" % x for x in ch.encode("utf-8")))
    return "".join(out)

def oracle(binp, scratch, pat, utf8, subj, sp):
    f = os.path.join(scratch, "lwsubj")
    with open(f, "wb") as h:
        h.write(subj.encode("utf-8"))
    r = subprocess.run([binp, ("(*UTF)" if utf8 else "") + pat, f, str(sp)],
                       capture_output=True, timeout=60)
    return r.stdout.decode().split()

def main():
    binp, scratch = sys.argv[1:3]
    os.makedirs(scratch, exist_ok=True)
    print(HEADER)
    for pat, utf8, why, subs in CELLS:
        print()
        print("# " + why)
        print("# pcre2-only")
        print("pattern " + pat)
        if utf8: print("encoding utf8")
        print("features all")
        for sp, s in subs:
            ans = oracle(binp, scratch, pat, utf8, s, sp)
            if not ans or ans[0] not in ("match", "nomatch"):
                sys.exit("oracle: %r on %r at %d: %s" % (pat, s, sp, ans))
            pre = "" if sp == 0 else "%d " % sp
            if ans[0] == "nomatch":
                print('%s %s"%s"' % ("n" if sp == 0 else "ns", pre, esc(s)))
            else:
                print('%s %s"%s" %s %s' % ("m" if sp == 0 else "ms", pre, esc(s), ans[1], ans[2]))

main()
