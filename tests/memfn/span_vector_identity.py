#!/usr/bin/env python3
"""tests/memfn/span_vector_identity.py -- the vector span's IDENTITY GATE
(R-47 unit U2, docs/design/memfn/block_span.md rev 4.2 §10.2 G-4).

WHAT IT CHECKS. The deny `--memfn=no-span-vector` restores the bytes of the
build before the vector span, at every layer: each artifact the U2 binary
emits under the deny equals the artifact a REFERENCE binary (the lane's
merge base, built once, never "main", which moves) emits with no deny, after
the DECLARED mask below and nothing else. A second arm reads the default
(undenied) artifact against the same reference and reports its movers, and
holds three things of them (r75 CHECKS-1..3):
  (1) FLOOR: each cell's mover count is at least its declared floor
      (FLOORS: the V sites of the committed tests/memfn/span_seed.rxt, 28
      byte / 20 utf8 at width 32 and 31 at width 4095; c-vm has none), so a
      dead V row cannot pass by moving nothing. A cell with population 0 fails.
  (2) EVERY mover holds a vector span call, every artifact holding one moves.
  (3) AT a mover the default-vs-deny diff (same binary, same flags) is
      limited to the declared shape: one pure-insertion hunk per site (the
      `<p>_mf<h>_vs<j>__body` and selector definitions) and one single-line
      walk hunk per site whose only change is the stretch replaced by exactly
      one `<p>_mf<h>_vs<j>(S, C)`; one call per site, one definition pair per
      call. An extra byte, a doubled or a moved call at a V site fails.
      AT THE w32 LAYER (-fmemfn-simd=x86-64-v3; U3, block_span.md §4.1, §5)
      the site's insertion also holds its level block (`__w32_b`, `__w32`,
      their lines as §4.1 spells them), its selector calls `__w32`, the
      `<immintrin.h>` line may be inserted once, and the `MEMFN_FORMS` and
      `SIMD_GUARDED_BYTES` stamp lines change: one `span-vector@w32` token
      per site more, nothing else in the token list.

THE MASK, DECLARED BEFORE DATA (§10.2, drilled on real artifacts and a real
bump, §16 item 11): nine anchored spellings of the abi number, selected BY
NAME, each replacing a number group ONLY when it equals that side's own abi
number (read from the side's probe artifact, M1 and M2 agreeing); a group
holding any other number is left in place and shows as a difference. The
per-row hit counts are printed for each side. Out of the mask on purpose:
the support unit's `pcrec_subst_support_id` hash (no population here reaches
the support unit).

POPULATION. Every distinct pattern of every `.rxt` under tests/ (the
emit_sweep corpus enumeration, span_seed.rxt always included, even at
--every K, so the floors hold at any sampling), at the default engine and at
--engine=vm, byte and utf8, at -fno-memfn-simd, at -fmemfn-simd=x86-64
(the w16-only target) and at -fmemfn-simd=x86-64-v3; plus span_seed.rxt's
own patterns (pcrec --list-source) at --window-search-width=4095, byte, all
three layers. Both sides compile with `-o -` (the -o basename trap:
emit_sweep.compile_stream_c).

The control (the reference binary) shares no source with the subject: it is
a separate build of an earlier commit. This gate is a DELIVERY step (like
U2b's census), not a make target: its reference is a build of the lane's
merge base, which cannot exist after the merge; what repeats at make tier is
tests/axes/memfn_arm.py's span-vector DIFFER rows (design §10.1, §14 U1).

Usage: span_vector_identity.py --ref-bin REF --ref-abi N --bin BIN --abi N [--root TREE]
       [--jobs N] [--every K] [--cells LIST]
Exit 0 iff every cell's deny arm shows 0 differences, its movers hold the
floor and the shape above, on a non-empty population.
"""
import argparse
import collections
import concurrent.futures as cf
import os
import re
import subprocess
import sys
import tempfile

# The mask: (name, anchored regex). Rows are SELECTED BY NAME (MASK_ROWS) and
# applied first-match in this order; the number group(s) of a row are replaced
# by `N` only where the group equals the side's own abi number.
MASK = [
    ("M1", r"^/\* Generated by pcrec \S+ \(abi (\d+)\)\. "),
    ("M2", r"^    \.abi = (\d+),$"),
    ("M3", r"^#if defined\(PCREC_RX_ABI_H\) && \(PCREC_RX_ABI_H \+ 0\) != (\d+)$"),
    ("M4", r"^#error \"pcrec: this artifact \(abi (\d+)\) shares a translation unit "),
    ("M5", r"^#define PCREC_RX_ABI_H (\d+)$"),
    ("M6", r"^#if !defined\(PCREC_RX_ABI_H\) \|\| \(PCREC_RX_ABI_H \+ 0\) != (\d+)$"),
    ("M7", r"^#error \"pcrec: this subst code \(abi (\d+)\) needs the rx shared block of abi (\d+); "),
    ("M8", r"^#define PCREC_SUBST_H (\d+)$"),
]
MASK_RE = [(n, re.compile(r)) for n, r in MASK]
# M9 as declared is `^#define (pcrec_subst_\w+) \1_v(N)$`: a back-reference.
M9 = ("M9", re.compile(r"^#define (pcrec_subst_\w+) (\w+)_v(\d+)$"))
MASK_NAMES = [n for n, _ in MASK] + [M9[0]]

# the call of a V stretch's selector in a walk (block_span.md §10.2's spelling)
VCALL = re.compile(rb"(\w+_mf\d+_vs\d+)\((\w+_mf\d+_s), (\w+_mf\d+_c)\)")
# the definition lines a V site may add (the file-scope __body + the selector)
DEF_HEAD = re.compile(r"^static inline __attribute__\(\(always_inline(?:, unused)?\)\) int "
                      r"(\w+_mf\d+_vs\d+)(__body)?\(const unsigned char \*\w+, size_t \w+\)$")
DEF_OTHER = re.compile(r"^(?:\{|\}|    return [^\n]*;|)$")
# the w32 layer's level block (§4.1), spelled HERE from the design, never read off the kit
LEVEL_HEAD = re.compile(r"^static inline __attribute__\(\(always_inline\)\) int (\w+_mf\d+_vs\d+)__w32(_b)?"
                        r"\((?:const unsigned char \*p|const unsigned char \*\w+, size_t \w+)\)$")
LEVEL_BODY = [re.compile(r) for r in (
    r"^    const __m(?:256|128)i (?:x|b0|b1|bm|hn|bit) = _mm(?:256)?_\w+\(.*\);$",
    r"^    const unsigned char \*p = \w+ \+ \w+(?: [+-] \d+)?;$",
    r"^    size_t i = 0;$",
    r"^    for \(; i \+ (?:16|32) < \d+; i \+= (?:16|32)\) if \(!\w+__w32_b\(p \+ i\)\) return 0;$")]
LEVEL_INCLUDE = "#include <immintrin.h>"
LEVEL_STAMP = re.compile(r"^#define \w+_(MEMFN_FORMS|SIMD_GUARDED_BYTES) (.*)$")
LEVEL_TOKEN = "span-vector@w32"
HUNK = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")

LAYERS = {"off": [], "x8664": ["-fmemfn-simd=x86-64"], "v3": ["-fmemfn-simd=x86-64-v3"]}
LEVEL_LAYERS = ("v3",)          # the layers whose V sites carry the w32 level block (U3)
ENCS = {"byte": [], "utf8": ["-e", "utf8"]}
STREAMS = {"c-default": None, "c-vm": "vm"}
DENY = ["--memfn=no-span-vector"]

# THE FLOORS: the default arm's mover count per cell is at least this. They are
# the V sites of the committed tests/memfn/span_seed.rxt (41 patterns: 28 byte /
# 20 utf8 are eligible at the default width 32, 31 at --window-search-width=4095),
# measured on U2 at every layer (r75 checks lens: 28/20 and 31, off and v3;
# x86-64 31). c-vm emits no V call. A tighter number is a re-pin with its reason.
FLOORS = {("c-default", "byte"): 28, ("c-default", "utf8"): 20,
          ("c-vm", "byte"): 0, ("c-vm", "utf8"): 0, ("seed4095", "byte"): 31}
SEED_PATTERNS = 41


def mask_line(line, abi, hits):
    """`line` with each declared spelling's number group(s) equal to the side's
    own `abi` replaced by `N`; `hits` counts the rows that replaced."""
    m = M9[1].match(line)
    if m and m.group(2) == m.group(1) and m.group(3) == abi:
        hits[M9[0]] += 1
        return line[:m.start(3)] + "N" + line[m.end(3):]
    for name, r in MASK_RE:
        m = r.match(line)
        if m:
            if any(m.group(g) != abi for g in range(1, (m.lastindex or 0) + 1)):
                return line          # another number: it stays and shows
            out, last = [], 0
            for g in range(1, (m.lastindex or 0) + 1):
                out.append(line[last:m.start(g)])
                out.append("N")
                last = m.end(g)
            hits[name] += 1
            return "".join(out) + line[last:]
    return line


def masked(text, abi, hits):
    return "\n".join(mask_line(l, abi, hits)
                     for l in text.decode("utf-8", "surrogateescape").split("\n"))


def side_abi(es, binp, timeout, stated):
    """The side's abi number: the one the operator STATES (--ref-abi / --abi,
    an independent source), which its probe artifact's M1 and M2 spellings
    must both equal (a binary spelling another number, as a plant does, is
    refused here instead of being masked)."""
    ok, txt, _ = es.compile_stream_c(binp, "a", timeout)
    if not ok:
        sys.exit(f"span_vector_identity: {binp} cannot compile the probe pattern")
    t = txt.decode("utf-8", "surrogateescape")
    m1 = re.search(r"^/\* Generated by pcrec \S+ \(abi (\d+)\)\. ", t, re.M)
    m2 = re.search(r"^    \.abi = (\d+),$", t, re.M)
    if not (m1 and m2 and m1.group(1) == stated and m2.group(1) == stated):
        sys.exit(f"span_vector_identity: {binp}: the probe's abi spellings "
                 f"(M1 {m1 and m1.group(1)}, M2 {m2 and m2.group(1)}) are not the stated abi {stated}")
    return stated


def walk_diff(deny, dflt, level=False):
    """The default-vs-deny diff at a mover, in the declared shape (with the w32
    level block where `level`). Returns (problems, calls, defs): `calls` the vs
    names called in the walk hunks, `defs` the selector names whose __body and
    selector heads were added."""
    probs, calls, defs = [], [], []
    tokens, includes, top_calls = 0, 0, set()
    with tempfile.TemporaryDirectory() as td:
        a, b = os.path.join(td, "deny.c"), os.path.join(td, "dflt.c")
        open(a, "wb").write(deny)
        open(b, "wb").write(dflt)
        out = subprocess.run(["diff", "-U0", a, b], capture_output=True).stdout
    lines = out.decode("utf-8", "surrogateescape").split("\n")
    i = 0
    while i < len(lines):
        m = HUNK.match(lines[i])
        if not m:
            i += 1
            continue
        oc = 1 if m.group(2) is None else int(m.group(2))
        nc = 1 if m.group(4) is None else int(m.group(4))
        old, new = [], []
        i += 1
        while i < len(lines) and not lines[i].startswith("@@"):
            if lines[i].startswith("-"):
                old.append(lines[i][1:])
            elif lines[i].startswith("+"):
                new.append(lines[i][1:])
            i += 1
        if oc == 0:                      # a pure insertion: the definitions
            heads = {}
            for l in new:
                dm = DEF_HEAD.match(l)
                lm = LEVEL_HEAD.match(l) if level else None
                if dm:
                    heads.setdefault(dm.group(1), []).append("body" if dm.group(2) else "sel")
                elif lm:
                    heads.setdefault(lm.group(1), []).append("w32_b" if lm.group(2) else "w32")
                elif level and l == LEVEL_INCLUDE:
                    includes += 1
                elif level and any(r.match(l) for r in LEVEL_BODY):
                    pass
                elif not DEF_OTHER.match(l):
                    probs.append(f"inserted line outside the definitions: {l[:80]!r}")
                tm = re.match(r"^    return (\w+)__w32\((\w+), (\w+)\);$", l) if level else None
                if tm:
                    top_calls.add(tm.group(1))
            want = ["body", "sel", "w32", "w32_b"] if level else ["body", "sel"]
            for nm, kinds in heads.items():
                if sorted(kinds) != want:
                    probs.append(f"{nm}: definitions are {sorted(kinds)}, not {want}")
                defs.append(nm)
        elif level and oc == nc and all(LEVEL_STAMP.match(x) for x in old + new) and \
                [LEVEL_STAMP.match(x).group(1) for x in old] == [LEVEL_STAMP.match(x).group(1) for x in new]:
            for o, n in zip(old, new):           # the moved stamps
                mo, mn = LEVEL_STAMP.match(o), LEVEL_STAMP.match(n)
                if mo.group(1) == "MEMFN_FORMS":
                    to = [t for t in mo.group(2).strip('"').split(",") if t != "none"]
                    tn = mn.group(2).strip('"').split(",")
                    rest = list(tn)
                    for t in to:
                        if t in rest:
                            rest.remove(t)
                    if len(tn) != len(to) + len(rest) or any(t != LEVEL_TOKEN for t in rest):
                        probs.append(f"MEMFN_FORMS {mo.group(2)} -> {mn.group(2)}: not tokens of {LEVEL_TOKEN} added")
                    tokens += len(rest)
        elif oc == 1 and nc == 1:        # the walk line: stretch -> one call
            o, n = old[0].encode("utf-8", "surrogateescape"), new[0].encode("utf-8", "surrogateescape")
            ms = VCALL.findall(n)
            if len(ms) != 1:
                probs.append(f"a changed line holds {len(ms)} vector calls, not 1")
                continue
            mm = VCALL.search(n)
            pre, suf = n[:mm.start()], n[mm.end():]
            if not (o.startswith(pre) and o.endswith(suf) and len(o) > len(pre) + len(suf)
                    and not VCALL.search(o)):
                probs.append("the walk line changes more than the stretch -> one call")
            calls.append(mm.group(1).decode())
        else:
            probs.append(f"a hunk of {oc} old / {nc} new lines is not a V-site change")
    if sorted(calls) != sorted(defs) or len(set(calls)) != len(calls):
        probs.append(f"calls {sorted(calls)} vs definitions {sorted(defs)}: "
                     "not one call per defined site")
    if level and (tokens != len(defs) or top_calls != set(defs) or includes > 1):
        probs.append(f"w32 layer: {tokens} {LEVEL_TOKEN} token(s), selectors calling __w32 "
                     f"{sorted(top_calls)}, {includes} include line(s), for sites {sorted(defs)}")
    return probs, calls, defs


def one(es, ref, binp, abis, pat, stream, flags, timeout, level=False):
    """(pattern, ref_ok, deny_same, default_moves, vcalls, shape problems,
    ref mask hits, subject mask hits) for one cell."""
    eng = STREAMS[stream]
    rh, sh = collections.Counter(), collections.Counter()
    rok, rtxt, _ = es.compile_stream_c(ref, pat, timeout, engine=eng, extra=flags)
    dok, dtxt, _ = es.compile_stream_c(binp, pat, timeout, engine=eng, extra=flags + DENY)
    wok, wtxt, _ = es.compile_stream_c(binp, pat, timeout, engine=eng, extra=flags)
    if not rok:
        # a pattern the reference refuses must be refused by both U2 arms too
        return pat, False, (not dok and not wok), False, 0, [], rh, sh
    mref = masked(rtxt, abis[0], rh)
    deny_same = dok and masked(dtxt, abis[1], sh) == mref
    moves = (not wok) or masked(wtxt, abis[1], sh) != mref
    vcalls = len(VCALL.findall(wtxt)) if wok else -1
    probs = []
    if moves and wok and dok:
        probs, _, _ = walk_diff(dtxt, wtxt, level)
    return pat, True, deny_same, moves, vcalls, probs, rh, sh


def run_cell(es, args, abis, name, pats, stream, flags, floor, level=False):
    deny_bad, mover_bad, movers, refused, n = [], [], 0, 0, 0
    rh, sh = collections.Counter(), collections.Counter()
    with cf.ThreadPoolExecutor(args.jobs) as ex:
        futs = [ex.submit(one, es, args.ref_bin, args.bin, abis, p, stream, flags, args.timeout, level)
                for p in pats]
        for f in futs:
            pat, rok, same, moves, vc, probs, r1, s1 = f.result()
            rh.update(r1)
            sh.update(s1)
            n += 1
            if not rok:
                refused += 1
                if not same:
                    deny_bad.append((pat, "the reference refuses, a U2 arm compiles"))
                continue
            if not same:
                deny_bad.append((pat, "deny differs after the mask"))
            if moves:
                movers += 1
            if moves != (vc > 0):
                mover_bad.append((pat, f"moves={moves} vcalls={vc}"))
            for pr in probs:
                mover_bad.append((pat, f"V-site diff shape: {pr}"))
    fl_bad = []
    if n - refused == 0:
        fl_bad.append(("-", "population 0: the cell compiled nothing"))
    if movers < floor:
        fl_bad.append(("-", f"default movers {movers} below the floor {floor}"))
    fmt = lambda h: " ".join(f"{k}={h[k]}" for k in MASK_NAMES)
    print(f"cell {name} stream={stream} flags={' '.join(flags) or '-'}: population={n} "
          f"refused={refused} deny_differs={len(deny_bad)} default_movers={movers} "
          f"floor={floor} mover_not_vsite={len(mover_bad)} floor_fail={len(fl_bad)}")
    print(f"  mask hits ref(abi {abis[0]}): {fmt(rh)}")
    print(f"  mask hits subject(abi {abis[1]}): {fmt(sh)}")
    for p, why in (deny_bad + mover_bad + fl_bad)[:8]:
        print(f"  {why}: {p!r}")
    return n - refused, len(deny_bad), len(mover_bad) + len(fl_bad), movers


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--ref-bin", required=True)
    ap.add_argument("--bin", required=True)
    ap.add_argument("--ref-abi", required=True, help="the reference build's abi number")
    ap.add_argument("--abi", required=True, help="the subject build's abi number")
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__)))))
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--every", type=int, default=1)
    ap.add_argument("--timeout", type=int, default=60)
    ap.add_argument("--cells", default="corpus,seed4095")
    args = ap.parse_args()
    sys.path.insert(0, os.path.join(args.root, "scripts"))
    import emit_sweep as es

    cells = args.cells.split(",")
    total = bad = 0
    abis = (side_abi(es, args.ref_bin, args.timeout, args.ref_abi),
            side_abi(es, args.bin, args.timeout, args.abi))
    print(f"abi: reference {abis[0]}, subject {abis[1]}")
    seed = os.path.join(args.root, "tests/memfn/span_seed.rxt")
    seed_pats = sorted(set(p for _, p in es.list_source_patterns(args.bin, seed, 60)))
    if len(seed_pats) < SEED_PATTERNS:
        print(f"span_vector_identity: FAIL: {len(seed_pats)} span_seed.rxt patterns, "
              f"fewer than the committed {SEED_PATTERNS}")
        return 1
    if "corpus" in cells:
        pats = es.distinct_patterns(es.enumerate_corpus(args.bin, args.root, 60), args.every)
        pats = sorted(set(pats) | set(seed_pats))      # the floors hold at any --every
        print(f"corpus: {len(pats)} distinct patterns (every {args.every}, + span_seed.rxt)")
        for ly, lf in LAYERS.items():
            for en, ef in ENCS.items():
                for st in STREAMS:
                    ok, d, m, _ = run_cell(es, args, abis, f"{ly}_{en}", pats, st, ef + lf,
                                           FLOORS[(st, en)], ly in LEVEL_LAYERS)
                    total += ok
                    bad += d + m
    if "seed4095" in cells:
        print(f"seed4095: {len(seed_pats)} distinct span_seed.rxt patterns")
        for ly, lf in LAYERS.items():
            ok, d, m, _ = run_cell(es, args, abis, f"seed4095_{ly}", seed_pats, "c-default",
                                   ["--window-search-width=4095"] + lf,
                                   FLOORS[("seed4095", "byte")], ly in LEVEL_LAYERS)
            total += ok
            bad += d + m
    print(f"span_vector_identity: compiled={total} failures={bad}")
    if total == 0:
        print("span_vector_identity: FAIL: empty population")
        return 1
    print("span_vector_identity: " + ("PASS" if bad == 0 else "FAIL"))
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
