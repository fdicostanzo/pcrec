#!/usr/bin/env python3
"""tests/memfn/span_vector_identity.py -- the vector span's IDENTITY GATE
(R-47 unit U2, docs/design/memfn/block_span.md rev 4.1 §10.2 G-4).

WHAT IT CHECKS. The deny `--memfn=no-span-vector` restores the bytes of the
build before the vector span, at every layer: each artifact the U2 binary
emits under the deny equals the artifact a REFERENCE binary (the lane's
merge base, built once, never "main", which moves) emits with no deny, after
the DECLARED mask below and nothing else. A second arm reads the default
(undenied) artifact against the same reference and reports its movers; every
mover must hold a vector span call and every artifact holding one must move
(the movers are exactly the V sites, §11), and the mover count is printed per
cell (K35: a gate that saw no mover could not tell a dead row from a sound one).

THE MASK, DECLARED BEFORE DATA (§10.2, drilled on real artifacts and a real
bump, §16 item 11): nine anchored spellings of the abi number, each replacing
ONLY its number group(s). Out of the mask on purpose: the support unit's
`pcrec_subst_support_id` hash (no population here reaches the support unit).

POPULATION. Every distinct pattern of every `.rxt` under tests/ (the
emit_sweep corpus enumeration, span_seed.rxt included), at the default
engine and at --engine=vm, byte and utf8, at -fno-memfn-simd and at
-fmemfn-simd=x86-64-v3; plus span_seed.rxt's own patterns (pcrec
--list-source) at --window-search-width=4095, byte, both layers. Both sides
compile with `-o -` (the -o basename trap: emit_sweep.compile_stream_c).

The control (the reference binary) shares no source with the subject: it is
a separate build of an earlier commit.

Usage: span_vector_identity.py --ref-bin REF --bin BIN [--root TREE]
       [--jobs N] [--every K] [--cells LIST]
Exit 0 iff every cell's deny arm shows 0 differences and the default arm's
movers are exactly its V sites, on a non-empty population.
"""
import argparse
import concurrent.futures as cf
import os
import re
import sys

MASK = [
    r"^/\* Generated by pcrec \S+ \(abi (\d+)\)\. ",                                    # M1
    r"^    \.abi = (\d+),$",                                                             # M2
    r"^#if defined\(PCREC_RX_ABI_H\) && \(PCREC_RX_ABI_H \+ 0\) != (\d+)$",             # M3
    r"^#error \"pcrec: this artifact \(abi (\d+)\) shares a translation unit ",          # M4
    r"^#define PCREC_RX_ABI_H (\d+)$",                                                   # M5
    r"^#if !defined\(PCREC_RX_ABI_H\) \|\| \(PCREC_RX_ABI_H \+ 0\) != (\d+)$",          # M6
    r"^#error \"pcrec: this subst code \(abi (\d+)\) needs the rx shared block of abi (\d+); ",  # M7
    r"^#define PCREC_SUBST_H (\d+)$",                                                    # M8
    r"^#define (?:pcrec_subst_\w+) pcrec_subst_\w+_v(\d+)$",                             # M9 (see below)
]
MASK_RE = [re.compile(m) for m in MASK]
# M9 as declared is `^#define (pcrec_subst_\w+) \1_v(N)$`: a back-reference,
# which the replace below keeps by checking it explicitly.
M9 = re.compile(r"^#define (pcrec_subst_\w+) (\w+)_v(\d+)$")

# the call of a V stretch's selector in a walk (block_span.md §10.2's spelling)
VCALL = re.compile(rb"_mf\d+_vs\d+\(\w+_mf\d+_s, \w+_mf\d+_c\)")

LAYERS = {"off": [], "v3": ["-fmemfn-simd=x86-64-v3"]}
ENCS = {"byte": [], "utf8": ["-e", "utf8"]}
STREAMS = {"c-default": None, "c-vm": "vm"}
DENY = ["--memfn=no-span-vector"]


def mask_line(line):
    """`line` with each declared spelling's number group(s) replaced by `N`."""
    m = M9.match(line)
    if m and m.group(2) == m.group(1):
        return line[:m.start(3)] + "N" + line[m.end(3):]
    for r in MASK_RE[:8]:
        m = r.match(line)
        if m:
            out, last = [], 0
            for g in range(1, (m.lastindex or 0) + 1):
                out.append(line[last:m.start(g)])
                out.append("N")
                last = m.end(g)
            return "".join(out) + line[last:]
    return line


def masked(text):
    return "\n".join(mask_line(l) for l in text.decode("utf-8", "surrogateescape").split("\n"))


def one(es, ref, binp, pat, stream, flags, timeout):
    """(pattern, ref_ok, deny_same, default_moves, vcalls) for one cell."""
    eng = STREAMS[stream]
    rok, rtxt, _ = es.compile_stream_c(ref, pat, timeout, engine=eng, extra=flags)
    dok, dtxt, _ = es.compile_stream_c(binp, pat, timeout, engine=eng, extra=flags + DENY)
    wok, wtxt, _ = es.compile_stream_c(binp, pat, timeout, engine=eng, extra=flags)
    if not rok:
        # a pattern the reference refuses must be refused by both U2 arms too
        return pat, False, (not dok and not wok), False, 0
    deny_same = dok and masked(dtxt) == masked(rtxt)
    moves = (not wok) or masked(wtxt) != masked(rtxt)
    vcalls = len(VCALL.findall(wtxt)) if wok else -1
    return pat, True, deny_same, moves, vcalls


def run_cell(es, args, name, pats, stream, flags):
    deny_bad, mover_bad, movers, refused, n = [], [], 0, 0, 0
    with cf.ThreadPoolExecutor(args.jobs) as ex:
        futs = [ex.submit(one, es, args.ref_bin, args.bin, p, stream, flags, args.timeout)
                for p in pats]
        for f in futs:
            pat, rok, same, moves, vc = f.result()
            n += 1
            if not rok:
                refused += 1
                if not same:
                    deny_bad.append((pat, "the reference refuses, a U2 arm compiles"))
                continue
            if not same:
                deny_bad.append((pat, "deny differs after the mask"))
            if moves:
                movers += 1
            if moves != (vc > 0):
                mover_bad.append((pat, f"moves={moves} vcalls={vc}"))
    print(f"cell {name} stream={stream} flags={' '.join(flags) or '-'}: population={n} "
          f"refused={refused} deny_differs={len(deny_bad)} default_movers={movers} "
          f"mover_not_vsite={len(mover_bad)}")
    for p, why in (deny_bad + mover_bad)[:8]:
        print(f"  {why}: {p!r}")
    return n - refused, len(deny_bad), len(mover_bad), movers


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--ref-bin", required=True)
    ap.add_argument("--bin", required=True)
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__)))))
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--every", type=int, default=1)
    ap.add_argument("--timeout", type=int, default=60)
    ap.add_argument("--cells", default="corpus,seed4095")
    args = ap.parse_args()
    sys.path.insert(0, os.path.join(args.root, "scripts"))
    import emit_sweep as es

    cells = args.cells.split(",")
    total = bad = 0
    if "corpus" in cells:
        pats = es.distinct_patterns(es.enumerate_corpus(args.bin, args.root, 60), args.every)
        print(f"corpus: {len(pats)} distinct patterns (every {args.every})")
        for ly, lf in LAYERS.items():
            for en, ef in ENCS.items():
                for st in STREAMS:
                    ok, d, m, _ = run_cell(es, args, f"{ly}_{en}", pats, st, ef + lf)
                    total += ok
                    bad += d + m
    if "seed4095" in cells:
        seed = os.path.join(args.root, "tests/memfn/span_seed.rxt")
        pats = sorted(set(p for _, p in es.list_source_patterns(args.bin, seed, 60)))
        print(f"seed4095: {len(pats)} distinct span_seed.rxt patterns")
        for ly, lf in LAYERS.items():
            ok, d, m, _ = run_cell(es, args, f"seed4095_{ly}", pats, "c-default",
                                   ["--window-search-width=4095"] + lf)
            total += ok
            bad += d + m
    print(f"span_vector_identity: compiled={total} failures={bad}")
    if total == 0:
        print("span_vector_identity: FAIL: empty population")
        return 1
    print("span_vector_identity: " + ("PASS" if bad == 0 else "FAIL"))
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
