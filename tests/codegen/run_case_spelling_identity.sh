#!/usr/bin/env bash
# tests/codegen/run_case_spelling_identity.sh -- the CASELESS SPELLING
# IDENTITY check: patterns that differ ONLY in the letter case of their
# caseless text emit the same matcher. Letter case inside a caseless region
# is spelling, not meaning; if it reaches the generated code (a table, a
# literal, a class, a comment-free line) the emitter is reading the spelling
# where it should read the folded set.
#
# Per SPELLING GROUP (three spellings of one caseless pattern), per engine
# (dfa, vm) and encoding (byte, utf8), the emitted .c and .h must be
# IDENTICAL after the DECLARED MASK, and gcc -O2 .text must be byte-identical.
# A cell the engine refuses must be refused by all three spellings alike.
#
# THE MASK is the three places the emitter writes the pattern text back
# (src/gen/emit_dfa.c's provenance line, once in .c and once in .h; the
# rx_info `.pattern` initialiser; and its `.pattern_len`, the spelling's
# byte length), applied by EXACT whole-line comparison
# against the line rebuilt from the spelling (the artifact's version and abi
# are the only free part of the provenance line). Every mask entry must fire
# exactly its declared count per artifact (a stale mask is a failure), and a
# line that merely LOOKS like an echo but is not the exact rebuilt text is
# not masked, so it shows up as a difference. The three outputs are built
# under the SAME basename in different directories, so the `#include` name
# never differs and needs no mask.
#
# POSITIVE CONTROLS: a pair that differs in letters ((?i)hello vs (?i)hellp)
# and a case-SENSITIVE pair (hello vs HELLO) must NOT compare equal through
# the same comparison; the check fails if either does.
set -u
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
PCREC="${PCREC:-$ROOT_DIR/build/pcrec}"
CC="${CC:-cc}"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
. "$ROOT_DIR/tests/lib/gen_timeout.sh"

pass=0; fail=0
ok()  { printf 'PASS: %s\n' "$1"; pass=$((pass+1)); }
bad() { printf 'FAIL: %s\n' "$1"; fail=$((fail+1)); }

# label # encodings # spelling1 # spelling2 # spelling3   ('#' never occurs in a pattern here)
GROUPS_=(
  "literal#byte utf8#(?i)hello#(?i)HeLLo#(?i)HELLO"
  "class#byte utf8#(?i)h[ae]llo#(?i)H[AE]LLO#(?i)H[aE]lLo"
  "wordb#byte utf8#(?i)\\bfoo\\b#(?i)\\bFOO\\b#(?i)\\bFoO\\b"
  "utf8-letter#utf8#(?i)éa#(?i)ÉA#(?i)éA"
  "alternation#byte utf8#(?i)cat|dog#(?i)CAT|DOG#(?i)Cat|dOg"
  "flag-spelling#byte utf8#(?i:abc)#(?i:ABC)#(?i:aBc)"
)
CONTROLS=(
  "ctl-letters#byte#(?i)hello#(?i)hellp"
  "ctl-case-sensitive#byte#hello#HELLO"
)

# Comment form of a spelling: bytes >= 0x80 as \xhh, the rest raw.
# String form: the C initialiser: \ and " escaped, ? as \?, bytes >= 0x80 as \ooo.
esc_forms() {
    local s="$1" i c cm="" st="" n
    LC_ALL=C
    for ((i = 0; i < ${#s}; i++)); do
        c="${s:i:1}"
        n=$(printf '%d' "'$c")
        if [ "$n" -lt 0 ]; then n=$((n + 256)); fi
        if [ "$n" -ge 128 ]; then
            cm+=$(printf '\\x%02x' "$n"); st+=$(printf '\\%03o' "$n")
        else
            cm+="$c"
            case "$c" in
                '\') st+='\\' ;;
                '"') st+='\"' ;;
                '?') st+='\?' ;;
                *)   st+="$c" ;;
            esac
        fi
    done
    CM_FORM="$cm"; ST_FORM="$st"
}

# mask FILE SPELLING -> FILE.m ; prints "H=n P=n" fire counts.
mask() {
    local f="$1" sp="$2"
    esc_forms "$sp"
    CM="$CM_FORM" ST="$ST_FORM" LEN="${#sp}" awk '
      BEGIN { cm = ENVIRON["CM"]; st = ENVIRON["ST"]
              hpre = "/* Generated by pcrec "
              hsuf = ". Pattern: " cm " */"
              pline = "    .pattern = \"" st "\","
              lline = "    .pattern_len = " ENVIRON["LEN"] "," }
      { if (substr($0, 1, length(hpre)) == hpre && length($0) > length(hsuf) &&
            substr($0, length($0) - length(hsuf) + 1) == hsuf) { print "<MASK-HDR>"; h++ }
        else if ($0 == pline) { print "<MASK-PATTERN>"; p++ }
        else if ($0 == lline) { print "<MASK-PATTERN-LEN>"; l++ }
        else print }
      END { printf "H=%d P=%d L=%d\n", h + 0, p + 0, l + 0 > "/dev/stderr" }' "$f" >"$f.m" 2>"$f.cnt"
    cat "$f.cnt"
}

text_of() { objcopy -O binary -j .text "$1" "$2" 2>/dev/null; }

# compare_cell LABEL ENG ENC SP1 SP2 SP3 -> sets CELL_EQ=1/0/refused ; CELL_NOTE
compare_cell() {
    local label="$1" eng="$2" enc="$3"; shift 3
    local i sp d rc=() n=0
    local base="$WORK/$label.$eng.$enc"
    for sp in "$@"; do
        d="$base/$n"; mkdir -p "$d"
        pcrec_run "$PCREC" -p rx --features all --engine="$eng" -e "$enc" --emit-main \
            -o "$d/x.c" --pattern "$sp" >"$d/log" 2>&1
        rc[$n]=$?
        n=$((n + 1))
    done
    CELL_NOTE=""
    if [ "${rc[0]}" != "${rc[1]}" ] || [ "${rc[0]}" != "${rc[2]}" ]; then
        CELL_EQ=diff; CELL_NOTE="exit codes differ across spellings: ${rc[*]}"; return
    fi
    if [ "${rc[0]}" != 0 ]; then CELL_EQ=refused; CELL_NOTE="refused alike (rc ${rc[0]})"; return; fi
    n=0
    for sp in "$@"; do
        d="$base/$n"
        local cnt
        cnt="$(mask "$d/x.c" "$sp")"
        [ "$cnt" = "H=1 P=1 L=1" ] || { CELL_EQ=diff; CELL_NOTE="stale mask in x.c of spelling $n: $cnt"; return; }
        cnt="$(mask "$d/x.h" "$sp")"
        [ "$cnt" = "H=1 P=0 L=0" ] || { CELL_EQ=diff; CELL_NOTE="stale mask in x.h of spelling $n: $cnt"; return; }
        n=$((n + 1))
    done
    CELL_EQ=same
    for n in 1 2; do
        for f in x.c x.h; do
            if ! cmp -s "$base/0/$f.m" "$base/$n/$f.m"; then
                CELL_EQ=diff
                CELL_NOTE="$f differs beyond the mask (spelling 0 vs $n): $(diff "$base/0/$f.m" "$base/$n/$f.m" | head -4 | tr '\n' ' ')"
                return
            fi
        done
    done
    # gcc -O2 .text
    for n in 0 1 2; do
        d="$base/$n"
        if ! (gen_cc "$label.$eng.$enc" "$CC" -O2 -c -I"$d" -o "$d/x.o" "$d/x.c") >"$d/cc.log" 2>&1; then
            CELL_EQ=diff; CELL_NOTE="cc failed: $(head -2 "$d/cc.log" | tr '\n' ' ')"; return
        fi
        text_of "$d/x.o" "$d/x.text"
        [ -s "$d/x.text" ] || { CELL_EQ=diff; CELL_NOTE="empty .text"; return; }
    done
    for n in 1 2; do
        cmp -s "$base/0/x.text" "$base/$n/x.text" || { CELL_EQ=diff; CELL_NOTE=".text differs (spelling 0 vs $n)"; return; }
    done
}

accepted=0
for g in "${GROUPS_[@]}"; do
    IFS='#' read -r label encs s1 s2 s3 <<<"$g"
    gacc=0
    for enc in $encs; do
        for eng in dfa vm; do
            compare_cell "$label" "$eng" "$enc" "$s1" "$s2" "$s3"
            case "$CELL_EQ" in
                same)    ok "[$label/$eng/$enc] identical after the declared mask, .text identical"
                         gacc=$((gacc+1)); accepted=$((accepted+1)) ;;
                refused) ok "[$label/$eng/$enc] $CELL_NOTE" ;;
                *)       bad "[$label/$eng/$enc] $CELL_NOTE" ;;
            esac
        done
    done
    [ "$gacc" -gt 0 ] && ok "[$label] at least one cell was compared (not all refused)" ||
        bad "[$label] every cell was refused -- the group compared nothing"
done

# Positive controls: the comparison must be able to fail.
for c in "${CONTROLS[@]}"; do
    IFS='#' read -r label encs s1 s2 <<<"$c"
    compare_cell "$label" dfa "$encs" "$s1" "$s2" "$s1"
    if [ "$CELL_EQ" = diff ] && case "$CELL_NOTE" in *"differs beyond the mask"*|*".text differs"*) true;; *) false;; esac; then
        ok "[$label] control differs as it must: $CELL_NOTE"
    else
        bad "[$label] control did NOT differ (state '$CELL_EQ' $CELL_NOTE) -- the comparison cannot fail"
    fi
done

printf '== case-spelling identity: %d passed, %d failed (%d cells compared)\n' "$pass" "$fail" "$accepted"
[ "$fail" -eq 0 ]
