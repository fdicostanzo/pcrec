/* scripts/ksgen.c — [KNOW-SRC] THE EMBED GENERATOR (docs/design/measure_sets.md
 * rev 3 §9.2 part 4, §9.7 K2): `ksgen KIND OUT FILE...` writes a knowledge
 * kind's build-time PRE-PARSE of its committed store text into OUT, a C
 * table a library TU compiles in. Its companion `scripts/embed_text.sh`
 * writes the same text as a string table; one Makefile static-pattern rule
 * (`gen-<store>`, called from `gen-tables`) runs both.
 *
 * ONE ARM PER KIND, chosen by a row of `gen_arms[]` keyed by the kind's
 * name in the kinds table (`pcrec_ks_kind`, src/core/ksrc_kinds.c), which
 * also supplies the kind's file suffix. Today one kind has a store:
 *
 *   analysis  `ksgen analysis src/core/findings_table.inc
 *             src/findings/<name>.rxt...` — each shipped bundle parsed with
 *             the one `.rxt` reader, in the no-filesystem buffer mode the
 *             store is read in, and every data block written as a C table
 *             that `src/core/findings.c` compiles in ([FINDINGS] B1;
 *             findings design §13 B1 acceptance (3)). It was
 *             `scripts/findgen.c` until K2 and writes the same tables.
 *
 * WHY A PRE-PARSE. B1 measured parsing `default.rxt` on every compile at
 * ~47 us, about 20% of a minimal compile — above noise — and the design's
 * own rule for that case is a table generated FROM THE SAME TEXT at build
 * time with an agreement check, never a second source. The text stays the
 * source of truth: this program reads nothing else, and tests/findings/
 * re-parses the embedded text through the library and checks it agrees
 * with the table.
 *
 * It links a STAGE-0 library (findings.o built with PCREC_FIND_STAGE0, whose
 * own table is empty) because the real findings.o includes this program's
 * output; it only parses, so it never reads a table. Not part of libpcrec.
 *
 * Each FILE must define exactly one item, named for the file's basename:
 * the store looks an item up by that name. */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "core/internal.h"
#include "core/ksrc.h"

/* Refuses a string that would need escaping inside a C literal. Every
 * string written here is a name the reader already validated (a bundle
 * name, a kind, a query, an encoding list, a derivation), so this never
 * fires on a file that parsed; it is the generator's own guard. */
static void check_plain(const char *s, const char *what)
{
    for (const char *c = s; *c; c++)
        if (*c == '"' || *c == '\\' || (unsigned char)*c < 0x20 ||
            (unsigned char)*c >= 0x7f) {
            fprintf(stderr, "ksgen: %s '%s' holds a byte a C literal would "
                    "have to escape\n", what, s);
            exit(1);
        }
}

/* Reads `path` whole into a malloc'd buffer. */
static char *slurp(const char *path, size_t *len)
{
    FILE *f = fopen(path, "rb");
    char *buf;
    long sz;
    if (!f || fseek(f, 0, SEEK_END) != 0 || (sz = ftell(f)) < 0) {
        fprintf(stderr, "ksgen: cannot read %s\n", path);
        exit(1);
    }
    rewind(f);
    buf = malloc((size_t)sz + 1);
    if (!buf || fread(buf, 1, (size_t)sz, f) != (size_t)sz) {
        fprintf(stderr, "ksgen: cannot read %s\n", path);
        exit(1);
    }
    fclose(f);
    *len = (size_t)sz;
    return buf;
}

/* The ANALYSIS kind's arm: the store's bundles `files[0..nfiles)` as the
 * `PcrecFindTblBlock`/`PcrecFindTblBundle` tables `src/core/findings.c`
 * includes. `kind` supplies the file suffix the basename rule strips. */
static int gen_analysis(const KsKind *kind, FILE *out, char **files, int nfiles)
{
    size_t nb = 0, slen = strlen(kind->suffix);
    fprintf(out, "/* GENERATED by scripts/ksgen.c analysis from src/findings/<name>.rxt:\n"
                 " * the store PRE-PARSED by the one .rxt reader (make gen-findings).\n"
                 " * Never edit by hand; committed, checked by tests/findings/ §3. */\n");
    for (int a = 0; a < nfiles; a++) {
        const char *path = files[a], *base = strrchr(path, '/');
        char name[256];
        size_t len, nlen, nbundles = 0;
        char *text = slurp(path, &len);
        pcrec_error err;
        RxtSource *src;
        base = base ? base + 1 : path;
        nlen = strlen(base);
        if (nlen <= slen || nlen - slen >= sizeof name ||
            strcmp(base + nlen - slen, kind->suffix)) {
            fprintf(stderr, "ksgen: %s is not a <name>%s file\n", path,
                    kind->suffix);
            return 1;
        }
        memcpy(name, base, nlen - slen);
        name[nlen - slen] = 0;
        src = pcrec_rxt_source_parse_buf(path, text, len, &err);
        if (!src) { fprintf(stderr, "ksgen: %s\n", err.msg); return 1; }
        for (size_t r = 0; r < src->nrows; r++)
            if (src->rows[r].kind == RXT_DECL_ANALYSIS) {
                nbundles++;
                if (strcmp(src->rows[r].name, name) != 0) {
                    fprintf(stderr, "ksgen: %s defines analysis '%s', not "
                            "'%s'\n", path, src->rows[r].name, name);
                    return 1;
                }
            }
        if (nbundles != 1) {
            fprintf(stderr, "ksgen: %s defines %zu analyses; a store file "
                    "defines exactly one\n", path, nbundles);
            return 1;
        }
        for (size_t i = 0; i < src->nfblocks; i++, nb++) {
            const RxtFindBlock *fb = &src->fblocks[i];
            fprintf(out, "static const PcrecFindServe pcrec_find_tbl_serves_%zu[] = {\n", nb);
            for (size_t j = 0; j < fb->nserves; j++) {
                check_plain(fb->serves[j].query, "query");
                check_plain(fb->serves[j].encs, "encoding list");
                check_plain(fb->serves[j].via, "derivation");
                fprintf(out, "    { \"%s\", \"%s\", \"%s\" },\n",
                        fb->serves[j].query, fb->serves[j].encs,
                        fb->serves[j].via);
            }
            fprintf(out, "};\n");
            /* a `freq` block's 256 counts; a `cpfreq` block's rows ([B5]) */
            if (fb->counts) {
                fprintf(out, "static const unsigned long long pcrec_find_tbl_counts_%zu[256] = {\n", nb);
                for (int b = 0; b < 256; b++)
                    fprintf(out, "%lluull,%s", fb->counts[b], (b & 7) == 7 ? "\n" : " ");
                fprintf(out, "};\n");
            }
            if (fb->ncps) {
                fprintf(out, "static const PcrecFindCp pcrec_find_tbl_cps_%zu[] = {\n", nb);
                for (size_t j = 0; j < fb->ncps; j++)
                    fprintf(out, "    { 0x%lxu, %lluull },\n",
                            (unsigned long)fb->cps[j].cp, fb->cps[j].count);
                fprintf(out, "};\n");
            }
        }
        pcrec_rxt_source_free(src);
        free(text);
    }
    /* The index, in a second pass so every block's arrays precede it. */
    fprintf(out, "static const PcrecFindTblBlock pcrec_find_tbl[] = {\n");
    nb = 0;
    for (int a = 0; a < nfiles; a++) {
        size_t len;
        char *text = slurp(files[a], &len);
        pcrec_error err;
        RxtSource *src = pcrec_rxt_source_parse_buf(files[a], text, len, &err);
        for (size_t i = 0; i < src->nfblocks; i++, nb++) {
            const RxtFindBlock *fb = &src->fblocks[i];
            check_plain(fb->bundle, "bundle name");
            check_plain(fb->kind, "kind");
            char counts[64] = "NULL", cps[64] = "NULL";
            if (fb->counts)
                snprintf(counts, sizeof counts, "pcrec_find_tbl_counts_%zu", nb);
            if (fb->ncps)
                snprintf(cps, sizeof cps, "pcrec_find_tbl_cps_%zu", nb);
            /* [WINDOW-E1] the block's provenance stanza, which a query's
             * provenance is read from (D162 add. 4). The store's `default`
             * is the chain's terminal, reached by identity, so it must be
             * AUTHORED on every block: an answer through
             * PCREC_FIND_STOP_DEFAULT is a prior by construction
             * (window_contract.md §3.2's cross-check). */
            if (!fb->prov_source) {
                fprintf(stderr, "ksgen: %s: the '%s' block at line %zu has "
                        "no provenance source\n", files[a], fb->kind, fb->line);
                return 1;
            }
            if (!strcmp(fb->bundle, "default") &&
                strcmp(fb->prov_source, "authored") != 0) {
                fprintf(stderr, "ksgen: %s: the store's default must declare "
                        "'source authored' on every block (line %zu says '%s')\n",
                        files[a], fb->line, fb->prov_source);
                return 1;
            }
            check_plain(fb->prov_source, "provenance source");
            if (fb->prov_fidelity) check_plain(fb->prov_fidelity, "fidelity");
            fprintf(out, "    { \"%s\", \"%s\", %zu, pcrec_find_tbl_serves_%zu, %zu, "
                    "%s, %s, %zu, \"%s\", %lluull, ", fb->bundle, fb->kind,
                    fb->line, nb, fb->nserves, counts, cps, fb->ncps,
                    fb->prov_source,
                    fb->prov_bytes ? strtoull(fb->prov_bytes, NULL, 10) : 0ull);
            if (fb->prov_fidelity)
                fprintf(out, "\"%s\" },\n", fb->prov_fidelity);
            else
                fprintf(out, "NULL },\n");
        }
        pcrec_rxt_source_free(src);
        free(text);
    }
    fprintf(out, "};\n");
    /* [FINDINGS] B2: the bundle index — each file's ONE bundle, its
     * `include <x>` name with the brackets stripped (or NULL) and its line:
     * what the chain walk needs of a bundle beyond its blocks (§4.3). */
    fprintf(out, "static const PcrecFindTblBundle pcrec_find_tbl_bundles[] = {\n");
    for (int a = 0; a < nfiles; a++) {
        size_t len;
        char *text = slurp(files[a], &len);
        pcrec_error err;
        RxtSource *src = pcrec_rxt_source_parse_buf(files[a], text, len, &err);
        for (size_t r = 0; r < src->nrows; r++) {
            const RxtRow *row = &src->rows[r];
            if (row->kind != RXT_DECL_ANALYSIS) continue;
            check_plain(row->name, "bundle name");
            if (row->value && row->value[0]) {
                size_t n = strlen(row->value);
                check_plain(row->value, "include");
                fprintf(out, "    { \"%s\", \"%.*s\", %zu },\n", row->name,
                        (int)(n - 2), row->value + 1, row->line);
            } else {
                fprintf(out, "    { \"%s\", NULL, %zu },\n", row->name,
                        row->line);
            }
        }
        pcrec_rxt_source_free(src);
        free(text);
    }
    fprintf(out, "};\n");
    return 0;
}

/* The kinds this generator writes a pre-parse for: a first-match table keyed
 * by the kind's name. A kind joins with its store (measures at M0, §9.8). */
static const struct {
    const char *kind;
    int (*gen)(const KsKind *, FILE *, char **, int);
} gen_arms[] = {
    { "analysis", gen_analysis },
};

int main(int argc, char **argv)
{
    const KsKind *kind;
    FILE *out;
    int rc = -1;
    if (argc < 3) {
        fprintf(stderr, "usage: ksgen KIND OUT FILE...\n");
        return 2;
    }
    kind = pcrec_ks_kind(argv[1]);
    for (size_t i = 0; kind && i < sizeof gen_arms / sizeof *gen_arms; i++)
        if (!strcmp(gen_arms[i].kind, kind->kind)) {
            if (!(out = fopen(argv[2], "w"))) {
                fprintf(stderr, "ksgen: cannot write %s\n", argv[2]);
                return 1;
            }
            rc = gen_arms[i].gen(kind, out, argv + 3, argc - 3);
            if (fclose(out) != 0) {
                fprintf(stderr, "ksgen: write failed\n");
                return 1;
            }
            return rc;
        }
    fprintf(stderr, "ksgen: no store generator for kind '%s'\n", argv[1]);
    return 2;
}
